#!/usr/bin/env python3
"""Build a resume manifest from a partly-run manifest and its results bundle.

    python3 push/resume_manifest.gen.py SRC.json BUNDLE.json OUT.json [--skip-src PREFIX ...]

Keeps, in their original order and phases, every SRC item whose bundle entry is not `ok` (PLANNED / pending /
FAILED), minus items whose srcId starts with a --skip-src prefix (and items that reference those srcIds by @ref).
Items that already ran (`ok`) are dropped. Bundle entries are matched to manifest items by position (the journal
idx is the manifest index). Do not hand-edit the output.
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src"); ap.add_argument("bundle"); ap.add_argument("out")
    ap.add_argument("--skip-src", action="append", default=[])
    a = ap.parse_args()
    m = json.load(open(os.path.join(ROOT, a.src)))
    b = json.load(open(os.path.join(ROOT, a.bundle)))
    jitems = {it["idx"]: it for it in b["journal"]["items"]}
    assert len(jitems) == len(m["items"]), "bundle does not match the manifest"
    keep, skipped, done = [], [], 0
    for i, it in enumerate(m["items"]):
        j = jitems[i]
        assert j["name"] == it["name"], (i, j["name"], it["name"])
        if j["state"] in ("VERIFIED", "CONFIRMED"):
            done += 1
            continue
        blob = json.dumps(it)
        if any((it.get("srcId") or "").startswith(p) or ("@" in blob and p in blob) for p in a.skip_src):
            skipped.append(it["name"]); continue
        keep.append(it)
    out = {k: v for k, v in m.items() if k not in ("items", "imagePack", "imgSizes", "dedupNames")}
    if any(("@img:" in json.dumps(it)) for it in keep):
        for k in ("imagePack", "imgSizes"):
            if k in m: out[k] = m[k]
    out["_note"] = (f"RESUME of {os.path.basename(a.src)} from {os.path.basename(a.bundle)}: {done} items already "
                    f"verified are dropped; {len(skipped)} skipped ({', '.join(a.skip_src)}); {len(keep)} remain, "
                    "same order and phases. Generated by push/resume_manifest.gen.py; do not hand-edit.")
    out["items"] = keep
    with open(os.path.join(ROOT, a.out), "w") as f:
        json.dump(out, f, indent=1, ensure_ascii=False); f.write("\n")
    print(f"{a.out}: {len(keep)} items (dropped {done} done, skipped {len(skipped)})")


if __name__ == "__main__":
    main()
