#!/usr/bin/env python3
"""Build push/630: repoint four live animation assets at strips re-cut to <= 4096 px tall (direct edits): Rengoku Ro's
strike and smoulder (push/624) and Fury of The White Tiger's gates and tiger (push/627_ut, run 2026-11-17 with the
234 / 252 px strips: 6786 / 10080 px tall).

    python3 push/630_strip_recut.gen.py

Why: push/624 hosted 300 px strips (300 x 6900, 300 x 10500) on the director's own UploadThing. Off-Bunny hosts load
native, battle clips are one texture (assetAnimationClip, one column) and combat effects have no MAX_TEXTURE_SIZE
guard, so phones (4096 px cap) draw them as black boxes (seen on the review desk preview, 2026-11-17). The re-cut
strips (art/duelyst_fx/recut_4096.py): strike 23 x 178 px = 4094, smoulder 35 x 116 px = 4060. Same frames and speed,
fresh filenames (_c). URLs from state/recut_upload/uploaded.json. White Tiger: gates 29 x 140 px = 4060, tiger 40 x 102 px = 4080, same frames and
speed. Asset ids unchanged, so suggestion 96rmM8V6Qj2Ksq6s40e31 (Rengoku) and the push/629 suggestion (White Tiger)
stay valid; no jutsu edit, no equip links touched. Read both assets back after.
"""
import hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/630_strip_recut.json'
UP = 'state/recut_upload/uploaded.json'
LIC_R = 'CC0 1.0 - OpenDuelyst (open-duelyst/duelyst), fx_f4_obliterate, adapted for TNR'
LIC_W = 'CC0 1.0 - OpenDuelyst (open-duelyst/duelyst), fx_f2_eightgates_teallotus / fx_f2_saberspineseal, adapted for TNR'
ASSETS = [  # srcId (upload), asset id, name, path, px, frames, speed, license
    ('rengoku_anim_strike_c', 'nAUh6EdgIUrPwLeyaeTPB', 'Rengoku Ro - Purgatory Prison',
     'art/duelyst_fx/rengoku/final/anim_rengoku_strike_tight_178_c.webp', 178, 23, 70, LIC_R),
    ('rengoku_anim_smoulder_c', 'cMax_mQ9G8TGmWBB-DcVR', 'Rengoku Ro - Smoulder',
     'art/duelyst_fx/rengoku/final/anim_rengoku_smoulder_tight_116_c.webp', 116, 35, 70, LIC_R),
    ('white_tiger_anim_gates', '92C_BYjulGUsL1y1X49Ee', 'Fury of The White Tiger - Gates',
     'art/duelyst_fx/showcase/final/anim_white_tiger_gates_140.webp', 140, 29, 70, LIC_W),
    ('white_tiger_anim_tiger', 'A7JDFeATf0DL-Sdv_6ssF', 'Fury of The White Tiger - Tiger',
     'art/duelyst_fx/showcase/final/anim_white_tiger_tiger_102.webp', 102, 40, 80, LIC_W),
]
from PIL import Image
up = json.load(open(UP))['files']
items = []
for src, aid, name, path, px, frames, speed, lic in ASSETS:
    w, h = Image.open(path).size
    assert (w, h) == (px, px * frames) and h <= 4096, (path, w, h)
    u = up[src]
    assert u['file'] == os.path.basename(path), (src, u['file'])
    assert u['sha256'] == hashlib.sha256(open(path, 'rb').read()).hexdigest(), ('upload does not match file', path)
    assert u['url'].startswith('https://bbenpyo9uu.ufs.sh/f/'), u['url']
    items.append({"entity": "asset", "slot": "edit", "targetId": aid, "name": name,
                  "data": {"name": name, "type": "ANIMATION", "image": u['url'], "folder": "jutsuanimations",
                           "frames": frames, "speed": speed, "hidden": False, "onInitialBattleField": False,
                           "licenseDetails": lic}})
m = {
    "_note": "Repoints four live animation assets at strips re-cut to <= 4096 px tall, because phones draw taller native strips as black boxes: Rengoku Ro strike nAUh6EdgIUrPwLeyaeTPB (178 px) and smoulder cMax_mQ9G8TGmWBB-DcVR (116 px), Fury of The White Tiger gates 92C_BYjulGUsL1y1X49Ee (140 px) and tiger A7JDFeATf0DL-Sdv_6ssF (102 px). Same frames, speed and hidden false; ids unchanged, so both suggestions stay valid. No jutsu or AI edit. Generated by push/630_strip_recut.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset edits')
