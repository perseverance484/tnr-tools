#!/usr/bin/env python3
"""Job 593: the Mother of Echoes clips at 2.5x (per-effect animationScale, upstream 8bd670153).

The art was drawn for 2.5 hex heights (state/results/589_moe_stillness_test_quest.md). 588 set Stillness
by hand; this job does the rest of her kit through Forge's livePatch (fable/live-patch-animation-scale):
each jutsu edit carries no effects, and Forge sets animationScale on every effect of the LIVE record whose
appear/static/disappear clip is one of her assets, then sends the whole record. No tuning is touched.

Law 18/60 order, by phase:
  10  every AI that equips an in-scope jutsu: those jutsu off (jutsus asserted; items/stats re-sent from live)
  20  the in-scope jutsu, livePatch {animationScale: 2.5, assets: <her assets>}
  30  every one of those AIs: the full kit back, exactly as read live 2026-11-13

Inputs (committed, read live 2026-11-13 with ids-only selects over the connector):
  state/moe_scale/kits_live_20261113.json   AI id -> equipped jutsu ids (profile.getAi)
  state/moe_scale/scope.json                in-scope jutsu (an effect uses one of her clips), out (no clip), done (588)
  state/moe_scale/moe_assets.json           her asset ids (push/501's 973 + her FX), the livePatch allowlist

Run: python3 push/593_moe_animation_scale.gen.py  ->  push/593_moe_animation_scale.json
Refuses while scope.json still has pending (unread) jutsu.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = os.path.join(ROOT, "state", "moe_scale")
OUT = os.path.join(ROOT, "push", "593_moe_animation_scale.json")
SCALE = 2.5
AI_NAMES = {
    "k0hgSrghl_KcYs9ATVDJT": "Sayo, Saint of Stillness", "H3pNj2qUWpMpVRINiH6Vn": "Sayo, Glasswright of the Stilling",
    "fJLcH1mpB1XHHGtNWwvzD": "Sayo, Mother of Echoes", "IhNR-W1FElTsrWw1KfuQ9": "The Silence",
    "qFKcwTUkBtRiC-uM_8xG8": "A Feeler of the Deep", "zyOeF-rSpeXuMU7A3QQgo": "Your Likeness",
    "wivZbMygCZo6c9pRKWvCI": "The Gate Porter (Worn)", "g6bNcftMcQ9pV_nMki7Wv": "Sister Hana (Worn)",
    "KhFglnxE7ouIDywet3BPB": "Cadet Tomo (Worn)", "8GPW--ok-9m9CBUfBucV4": "An Absence",
    "FotHaXVoYS4In_wM-qczO": "Stillness Scale Test",
}


def load(name):
    with open(os.path.join(S, name)) as f:
        return json.load(f)


def main():
    kits, scope, assets = load("kits_live_20261113.json"), load("scope.json"), load("moe_assets.json")["assets"]
    pending = [j for j, v in scope.get("pending", {}).items() if v is None]
    if pending:
        sys.exit(f"scope.json has {len(pending)} unread jutsu: {pending}")
    inn = scope["in"]
    equipped = {j for kit in kits.values() for j in kit}
    missing = sorted(set(inn) - equipped)
    if missing:
        sys.exit(f"in-scope jutsu not on any read kit (law 18 cannot cover them): {missing}")
    unknown_ai = sorted(set(kits) - set(AI_NAMES))
    if unknown_ai:
        sys.exit(f"AI without a display name: {unknown_ai}")
    touched = [a for a, kit in kits.items() if any(j in inn for j in kit)]
    items = []
    for a in touched:
        keep = [j for j in kits[a] if j not in inn]
        items.append({"entity": "ai", "slot": "edit", "targetId": a, "phase": 10,
                      "name": f"{AI_NAMES[a]}: her jutsu off (law 18)", "data": {"jutsus": keep}})
    for j, name in sorted(inn.items(), key=lambda kv: kv[1]):
        items.append({"entity": "jutsu", "slot": "edit", "targetId": j, "phase": 20, "name": f"{name}: clips at {SCALE}x",
                      "data": {}, "livePatch": {"animationScale": SCALE, "assets": sorted(assets)}})
    for a in touched:
        items.append({"entity": "ai", "slot": "edit", "targetId": a, "phase": 30,
                      "name": f"{AI_NAMES[a]}: kit back (law 18)", "data": {"jutsus": kits[a]}})
    m = {"_note": (f"push/593: Mother of Echoes clips at {SCALE}x (RUL-2026-11-06-131 item 4; 588/589). {len(inn)} jutsu by "
                   f"Forge livePatch (effects derived from the live record at send time; needs the livePatch bundle), law 18 "
                   f"on {len(touched)} AIs (kits read live 2026-11-13). {len(scope['out_no_animation'])} equipped jutsu have no "
                   f"clip and are not touched; Stillness was done by 588. Generated by push/593_moe_animation_scale.gen.py; "
                   f"do not hand-edit."),
         "items": items}
    with open(OUT, "w") as f:
        json.dump(m, f, separators=(",", ":"))
    print(f"wrote {OUT}: {len(touched)} AIs x2, {len(inn)} jutsu, {len(items)} items, {os.path.getsize(OUT)} bytes")


if __name__ == "__main__":
    main()
