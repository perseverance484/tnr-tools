#!/usr/bin/env python3
"""Skyglass chart, page and reagent icons: placeholder -> final art (push/352).

IC01-IC07 (director-approved raws) and the six DR recolours (docs/design/skyglass_art/ART_REGISTER.md), processed by
state/skyglass_art/ic01_07_intake.py into art/skyglass_event_icons/exports/. This writes
push/352_skyglass_chart_icons.json: one direct, image-only item edit per row (`image` only, so `hidden` and every
other field stay as they are; every record is still hidden, created by push/329). Never hand-edit the output; add
a row and re-run. Same conventions as push/skyglass_art_swaps.gen.py.

Ids are literal and checked: each row's id must be the VERIFIED create of that exact name in the push/329 results
bundle below, so a wrong or renamed id stops the build.

The image pack ref is NOT typed: it is the newest commit on HEAD that touched any listed export, checked to contain
every file at the exact bytes on disk. Commit (and push) the exports first, then run this.

No quest.image edits: the chart-run and Haul quests whose icon is their chart's icon are not built yet
(state/skyglass_design/design_data.json runs[].quest.id null); add them when they exist.
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "push", "352_skyglass_chart_icons.json")
BUNDLE = os.path.join(ROOT, "harvests", "inbox", "tnr_results_1793424666625.json")  # push/329 results
EXP = "art/skyglass_event_icons/exports/"

# (register code, live id, record name, export file)
SWAPS = [
    ("IC01", "H1s2IwtZ5JqgPEoJ55IVj", "Tide Chart", "icon-tide-chart.webp"),
    ("IC02", "yE8TwzygWZSNoZD5x97rW", "Watch Roster", "icon-watch-roster.webp"),
    ("IC03", "sVqDdYUJIxxRYbmKbbxo0", "Reliquary Seal", "icon-reliquary-seal.webp"),
    ("IC04", "s1mYHuKqw2YuzIzxVwU-_", "The Last Heading", "icon-the-last-heading.webp"),
    ("IC05", "KuqLeFB12BdB-0s5O1udk", "Core Rot", "icon-core-rot.webp"),
    ("IC06", "JvrytTOdR1voVCoo3fckK", "Ledger Page: The Trophy Hold", "icon-ledger-page.webp"),
    ("IC07", "nLG6TK48xlyZ_t9R28QsY", "Stores Manifest: The Overgrown Stores", "icon-stores-manifest.webp"),
    ("DR01", "2sGi5SZXh2UutHmM-mIMD", "Rotted Reliquary Seal", "icon-rotted-reliquary-seal.webp"),
    ("DR02", "U2yJbBM6_N1xBBf0ez96F", "The Rotted Heading", "icon-the-rotted-heading.webp"),
    ("DR03", "uu6ETQimuBJ69jwr76IIi", "Ledger Page: The Bone Store", "icon-ledger-page-bone-store.webp"),
    ("DR04", "6QgcnW0v6gZeHY474BjR0", "Ledger Page: The Snare Room", "icon-ledger-page-snare-room.webp"),
    ("DR05", "9j4IErGW1gmZ-5FNjZMEQ", "Stores Manifest: The Ore Vault", "icon-stores-manifest-ore-vault.webp"),
    ("DR06", "7Sz2ttMScKH8b10XYS12I", "Stores Manifest: The Bloom Cellar", "icon-stores-manifest-bloom-cellar.webp"),
]
DONE = []


def git(*a):
    return subprocess.check_output(["git", "-C", ROOT, *a], text=True).strip()


def main():
    if not SWAPS:
        sys.exit("no pending swaps")
    created = {}
    for e in json.load(open(BUNDLE))["entries"]:
        if e["entity"] == "item" and e["slot"] == "create" and e.get("forgeState") == "VERIFIED":
            created[e["id"]] = e["name"]
    for code, tid, name, _ in SWAPS:
        if created.get(tid) != name:
            sys.exit(f"{code}: {tid} is {created.get(tid)!r} in the 329 bundle, not {name!r}")
    paths = [EXP + r[3] for r in SWAPS]
    ref = git("log", "-1", "--format=%H", "HEAD", "--", *paths)
    if not ref:
        sys.exit("exports not committed")
    files = {}
    for p in paths:
        disk = open(os.path.join(ROOT, p), "rb").read()
        committed = subprocess.check_output(["git", "-C", ROOT, "show", f"{ref}:{p}"])
        if committed != disk:
            sys.exit(f"{p}: working copy differs from {ref}; commit it first")
        files[os.path.basename(p)] = {"path": p, "sha256": hashlib.sha256(disk).hexdigest(), "bytes": len(disk)}
    items = [{"entity": "item", "slot": "edit", "name": name, "targetId": tid, "data": {"image": "@img:" + f}}
             for code, tid, name, f in SWAPS]
    m = {
        "_note": ("push/352 Skyglass chart, page and reagent icons (generated by push/skyglass_chart_icons.gen.py; "
                  "do not hand-edit). Direct image-only edits on the hidden push/329 items, replacing placeholders "
                  "with the director-approved IC01-IC07 art and the six scripted recolours (DR01-DR06): "
                  + ", ".join(f"{r[0]} {r[2]}" for r in SWAPS) +
                  ". hidden is not touched. Exports pinned by commit and SHA-256 in imagePack. No quest.image edits "
                  "(the chart-run and Haul quests are not built yet). Operator runs it from Forge; never skipPreflight."),
        "imgSizes": {k: v["bytes"] for k, v in files.items()},
        "imagePack": {"ref": ref, "files": files},
        "items": items,
    }
    with open(OUT, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(OUT, "ref", ref, "edits", len(items))


if __name__ == "__main__":
    main()
