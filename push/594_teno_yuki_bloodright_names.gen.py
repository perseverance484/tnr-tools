#!/usr/bin/env python3
"""Generate push/594: rename the 12 Teno Yuki Bloodright passives (RUL-2026-11-13-149). Do not hand-edit
the output.

A one-tree Bloodright package (Forge only writes skill-tree records through a compiled package). Every
node and the folder are BOUND to the records push/123 created, so nothing is created; the new names come
from the structural design at DESIGN_REF. Icons are bound to the image links the passives already hold
(the push/123 uploads, unchanged in every later results bundle), so nothing is uploaded. Silver and
rounds stay at the imported placeholders, so the only change Forge should preview is each node's name.

Inputs (all committed):
  - docs/design/bloodright/structural/teno_yuki.json at DESIGN_REF (the renamed design)
  - forge/bloodright/naming_pass_collection_b.json (the Teno Yuki tree push/123 imported)
  - harvests/inbox/tnr_results_1792425603256_9.json (push/123 Teno Yuki: record ids and icon links)

  python3 push/594_teno_yuki_bloodright_names.gen.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "push/594_teno_yuki_bloodright_names.json"
DESIGN = "docs/design/bloodright/structural/teno_yuki.json"
DESIGN_REF = "f31e7c9bbda8b2c22d6270c827b46ccd385a6dc4"  # RUL-2026-11-13-149 names
RESULTS = ROOT / "harvests/inbox/tnr_results_1792425603256_9.json"
BLOODLINE = "clh4d6qjs000gtb0hr357gjvv"
ICONS = {"Foundation": "foundation", "Hidden Art": "hidden_art", "Advanced Art": "advanced_art"}


def main():
    pkg = json.loads((ROOT / "forge/bloodright/naming_pass_collection_b.json").read_text())
    imported = next(t for t in pkg["bloodrightCollection"]["trees"] if t["source"]["path"] == DESIGN)
    res = json.loads(RESULTS.read_text())
    ids = {e["srcId"]: e["id"] for e in res["entries"] if e.get("state") == "ok"}
    links = res["idmap"]
    nodes = {k: v for k, v in ids.items() if k.startswith(f"br:{BLOODLINE}:p")}
    if len(nodes) != 12:
        raise SystemExit(f"expected 12 Teno Yuki records in {RESULTS.name}, found {len(nodes)}")
    tree = {
        "version": 1,
        "source": {"path": DESIGN, "ref": DESIGN_REF},
        "hiddenProbeId": imported["hiddenProbeId"],
        "bindings": {"folderId": ids[f"br:{BLOODLINE}:folder"],
                     "nodes": {k.rsplit(":", 1)[1]: v for k, v in sorted(nodes.items())}},
        "nodes": imported["nodes"],
        "icons": {cat: links[f"bloodright_teno_yuki_{stem}.webp"] for cat, stem in ICONS.items()},
    }
    for url in tree["icons"].values():
        if not url.startswith("https://"):
            raise SystemExit(f"icon link is not a recorded upload: {url}")
    out = {
        "_note": ("Rename the 12 Teno Yuki Bloodright passives (RUL-2026-11-13-149). Every node and the folder are bound "
                  "to the push/123 records and the icons to their current links, so Forge should preview a name change "
                  "on each node and nothing else. Generated by push/594_teno_yuki_bloodright_names.gen.py; do not "
                  "hand-edit. Operator-run only."),
        "bloodrightCollection": {"version": 1, "trees": [tree]},
    }
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    print(OUT.relative_to(ROOT), "12 bound nodes")


if __name__ == "__main__":
    main()
