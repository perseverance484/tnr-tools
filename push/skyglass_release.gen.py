#!/usr/bin/env python3
"""push/507: publish the Skyglass event pieces that are ready today (director, 2026-11-06: "release the page the
wreck sighted update and whatnot so we can go live today"). The Mother of Echoes fight stays hidden until the
clip-size update.

    python3 push/skyglass_release.gen.py  -> push/507_skyglass_release.json

Both quests already exist, HIDDEN, created by the committed runs of push/490 (tnr_results_1793933588063.json) and
push/497 (tnr_results_1793933653675.json). Each is re-sent whole from its current committed create data with
hidden false:
  phase 10  The Watch Log: First Page. The record as it ran, plus the QI01 page icon added after that run
            (3bcaff04; the only difference, checked field by field).
  phase 20  Wreck Sighted, the new event tutorial (unchanged since its run; the old one is deleted).
The shards need nothing here: push/419 unhid them and push/420 put their drops on the runs (both verified ok). Shard
of the Keel's drop is the director's editor row on the full Wreck dungeon. Do not hand-edit the output.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NUM = 507
SRC = [  # (create manifest, its results bundle, phase)
    ("push/490_skyglass_journal_week1.json", "harvests/inbox/tnr_results_1793933588063.json", 10),
    ("push/497_skyglass_wreck_sighted_tutorial.json", "harvests/inbox/tnr_results_1793933653675.json", 20),
]


def load(p):
    return json.load(open(os.path.join(ROOT, p)))


def main():
    items, pack, sizes = [], None, {}
    for mpath, bpath, phase in SRC:
        m, b = load(mpath), load(bpath)
        (it,) = m["items"]
        ok = [e for e in b["entries"] if e.get("state") == "ok" and e.get("slot") == "create" and e.get("entity") == "quest"]
        if len(ok) != 1 or ok[0].get("name") != it["name"]:
            raise SystemExit(f"{bpath}: expected one ok create of {it['name']!r}")
        data = dict(it["data"], hidden=False)
        items.append({"entity": "quest", "slot": "edit", "targetId": ok[0]["id"], "phase": phase,
                      "name": f"{it['name']}: publish", "data": data})
        if m.get("imagePack"):
            pack = m["imagePack"]
            sizes.update(m.get("imgSizes", {}))
    out = {"_note": (f"push/{NUM}: Skyglass release, today (director 2026-11-06). Publishes The Watch Log: First Page "
                     "(with its page icon) and the new Wreck Sighted, both re-sent whole from their committed create "
                     "data with hidden false. The Mother of Echoes fight stays hidden. The shards already drop "
                     "(push/419, 420). Generated by push/skyglass_release.gen.py; do not hand-edit."),
           "items": items}
    if sizes:
        out["imgSizes"] = sizes
    if pack:
        out["imagePack"] = pack
    p = os.path.join(ROOT, "push", f"{NUM}_skyglass_release.json")
    with open(p, "w") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"{os.path.relpath(p, ROOT)}: " + "; ".join(f"{i['name']} -> {i['targetId']}" for i in items))


if __name__ == "__main__":
    main()
