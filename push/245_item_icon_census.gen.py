#!/usr/bin/env python3
"""Generate push/245-248: read-only census of item icons, to find dated item art.

Director, 2026-10-25: "Lets identify some dated items to work on. Pull up some sheets for me to pick from."
Target set: every item the seed index (harvests/seed/41_INDEX_item.json) marks visible (528). Each is point-read with
item.get, persist full, so its image, type and rarity land in the bundle. Part 1 also reads item.getAllNames, whose row
count shows how far the item universe has drifted from the seed. Zero writes. Run from the repo root.
"""
import json, os
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
s = json.load(open('harvests/seed/41_INDEX_item.json'))
c = s['cols']
rows = sorted((r for r in s['rows'] if not r[c.index('hid')]), key=lambda r: r[c.index('n')].lower())
PARTS = 4
n = (len(rows) + PARTS - 1) // PARTS
for p in range(PARTS):
    part = rows[p * n:(p + 1) * n]
    before = [{"proc": "item.getAllNames", "input": {}}] if p == 0 else []
    before += [{"proc": "item.get", "input": {"id": r[c.index('id')]}, "persist": "full", "_name": r[c.index('n')]} for r in part]
    m = {"_note": f"Item icon census part {p + 1}/{PARTS}: read-only item.get (persist full) of {len(part)} visible items "
                  f"({part[0][c.index('n')]} .. {part[-1][c.index('n')]}), so their icons can be reviewed for dated art. "
                  "Changes nothing. Generated by push/245_item_icon_census.gen.py; do not hand-edit.",
         "capture": {"before": before}, "items": []}
    out = f'push/{245 + p}_item_icon_census_{p + 1}.json'
    json.dump(m, open(out, 'w'), indent=1, ensure_ascii=False); open(out, 'a').write('\n')
    print(out, len(before))
