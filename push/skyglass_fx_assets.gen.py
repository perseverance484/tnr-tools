#!/usr/bin/env python3
"""Generate push/320: create the Skyglass danger-language assets (hidden), for the in-battle check (director 2026-10-28).

    python3 push/skyglass_fx_assets.gen.py

Ten gameAssets from art/skyglass_boss_fx/exports (built by art/skyglass_boss_fx/animate.py):
- four STATIC mark tiles (they draw under the characters as an effect's staticAssetPath);
- four glint ANIMATIONs that loop over them (the safe one carries the floating emblem);
- two detonation ANIMATIONs (heavy eruption, crystal shard).
All created hidden (law 16b). Battles load only unhidden assets (law 16c), so the follow-up, built from this run's
results bundle, unhides them by literal id and creates a hidden test jutsu that lays the tiles. The image pack is pinned
at the commit that carries the files. Do not hand-edit the output.
"""
import hashlib, json, os, subprocess
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXP = 'art/skyglass_boss_fx/exports'
FOLDER = 'SkyglassBossFX'
ASSETS = [  # (srcId, name, type, file, speed ms)
    ('fx_tile_heavy', 'Skyglass Mark - Heavy (tile)', 'STATIC', 'tile_heavy_v3.webp', 1),
    ('fx_tile_control', 'Skyglass Mark - Binding (tile)', 'STATIC', 'tile_control_v3.webp', 1),
    ('fx_tile_linger', 'Skyglass Mark - Lingering Pool (tile)', 'STATIC', 'tile_linger_v3.webp', 1),
    ('fx_tile_safe', 'Skyglass Mark - Safe (tile)', 'STATIC', 'tile_safe_v3.webp', 1),
    ('fx_glint_heavy', 'Skyglass Mark - Heavy (glint)', 'ANIMATION', 'anim_heavy_glint_v3.webp', 50),
    ('fx_glint_control', 'Skyglass Mark - Binding (glint)', 'ANIMATION', 'anim_control_glint_v3.webp', 50),
    ('fx_glint_linger', 'Skyglass Mark - Lingering Pool (bubbles)', 'ANIMATION', 'anim_linger_glint_v3.webp', 50),
    ('fx_glint_safe', 'Skyglass Mark - Safe (floating emblem)', 'ANIMATION', 'anim_safe_glint_v3.webp', 50),
    ('fx_dt_heavy', 'Skyglass Blast - Eruption', 'ANIMATION', 'anim_dt_heavy_v2.webp', 50),
    ('fx_dt_shard', 'Skyglass Blast - Crystal Shard', 'ANIMATION', 'anim_dt_shard_v2.webp', 50),
]


def main():
    ref = subprocess.check_output(['git', '-C', ROOT, 'rev-parse', 'HEAD']).decode().strip()
    files, items = {}, []
    for src, name, typ, fn, speed in ASSETS:
        path = f'{EXP}/{fn}'
        b = open(os.path.join(ROOT, path), 'rb').read()
        blob = subprocess.check_output(['git', '-C', ROOT, 'show', f'{ref}:{path}'])
        assert blob == b, f'{path} differs from {ref[:7]}: commit it first'
        im = Image.open(os.path.join(ROOT, path))
        frames = 1 if typ == 'STATIC' else im.height // im.width
        assert im.width == 50 and (typ == 'STATIC' and im.height == 50 or im.height == 50 * frames)
        files[fn] = {'path': path, 'sha256': hashlib.sha256(b).hexdigest(), 'bytes': len(b)}
        items.append({'entity': 'asset', 'slot': 'create', 'srcId': src, 'name': name, 'data': {
            'name': name, 'type': typ, 'image': '@img:' + fn, 'folder': FOLDER, 'frames': frames, 'speed': speed,
            'hidden': True, 'onInitialBattleField': False, 'licenseDetails': 'TNR'}})
    m = {'_note': ('push/320 (director 2026-10-28: "rebuild them this way. We\'ll double check with a push"): creates the '
                   'Skyglass danger-language assets, hidden: four STATIC mark tiles (drawn under the characters as an '
                   'effect\'s staticAssetPath), four glint ANIMATIONs over them, two detonation ANIMATIONs. The follow-up, '
                   'built from this run\'s results bundle, unhides them (law 16c) and creates a hidden test jutsu that lays '
                   'the tiles. Generated by push/skyglass_fx_assets.gen.py; do not hand-edit.'),
         'imgSizes': {k: v['bytes'] for k, v in files.items()},
         'imagePack': {'ref': ref, 'files': files}, 'items': items}
    json.dump(m, open(os.path.join(ROOT, 'push/320_skyglass_fx_assets_create.json'), 'w'), indent=1)
    print(len(items), 'assets, pack @', ref[:7])


if __name__ == '__main__':
    main()
