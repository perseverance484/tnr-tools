#!/usr/bin/env python3
"""The Haul's own chests (push/370; RUL-2026-10-31-081).

    python3 push/skyglass_haul_chests.gen.py      # writes push/370_skyglass_haul_chests.json

Phase 1: eight HIDDEN item creates (push/skyglass_items.gen.py HAUL_CHESTS): Hide Bundle, Keeper's Pack, Prize
Strongbox, Keeper's Reserve (hunting pages) and Stores Bundle, Quartermaster's Pack, Overgrown Strongbox, Quartermaster's
Reserve (gathering pages), with the profession chests' tiers and tables (chests.json, RUL-2026-10-29-058), text from
SKYGLASS_TEXT.md section 4.5, and the PC01-PC08 art where delivered (engine default image otherwise). The eight live
profession chests are left untouched so players who own them keep their art, contents and text.
Phase 2: description-only edits of the six hidden Haul pages, whose "Pays:" line now names these chests (ids from
push/329's results bundle).
After it runs, push/skyglass_haul.gen.py --chests <370 bundle> maps the Haul's endings onto the new chest ids.
Do not hand-edit the output.
"""
import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NUM = 370
BUNDLE_329 = "harvests/inbox/tnr_results_1793424666625.json"


def load(name):
    spec = importlib.util.spec_from_file_location(name.replace(".", "_"), os.path.join(ROOT, "push", name))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


U = load("skyglass_update.gen.py")
IT = U.IT


def main():
    creates = IT.haul_chests()
    created = {e["name"]: e["id"] for e in json.load(open(os.path.join(ROOT, BUNDLE_329)))["entries"]
               if e.get("entity") == "item" and e.get("slot") == "create" and e.get("state") == "ok"}
    pages = [{"entity": "item", "slot": "edit", "phase": 2, "name": f"{n}: text (Pays line names the Haul chests)",
              "targetId": created[n], "data": {"description": IT.T.block(f"item:{n}.description")}} for n in IT.PAGES]
    assert len(creates) == 8 and len(pages) == 6
    U.write(NUM, "skyglass_haul_chests", (
        f"push/{NUM}: the Haul's own chests (RUL-2026-10-31-081). Phase 1: 8 HIDDEN creates (Hide Bundle, Keeper's Pack, "
        "Prize Strongbox, Keeper's Reserve; Stores Bundle, Quartermaster's Pack, Overgrown Strongbox, Quartermaster's "
        "Reserve), tiers and tables as the profession chests, untradeable. Phase 2: the six hidden Haul pages' text with "
        "the new Pays line. The eight live profession chests are not touched. Generated by push/skyglass_haul_chests.gen.py."),
        creates + pages)


if __name__ == "__main__":
    main()
