#!/usr/bin/env python3
"""Generate the AI pool battle-line pass: unequip -> edit -> re-equip (laws 18, 60). Do not hand-edit outputs.

Inputs (all committed):
  - harvests/inbox/tnr_results_1792551342555.json  push/157: all 82 pool jutsu, persist:full
  - harvests/inbox/tnr_results_1792551456483.json, ..._1792551557783, ..._1792551619150, ..._1792551674258
      push/158-161: profile.getAi persist:full for all 512 known live AIs (the before-image)
  - state/ai_pool_battle_lines/battle_lines.json (through build.py): the 82 jutsu edits

The 82 jutsu link almost every holder into one group, so the three steps are separate manifests
and must run strictly in order:
  162          unequip PROBE (1 AI) + read-back. Check it with the read-back script before 163.
  163-169      unequip the remaining AIs, 7 batches, each with a read-back.
  170          edit the 82 jutsu (battle line; name on 16; target on B31) + jutsu read-back.
  171-177      re-equip every AI's exact original kit, 7 batches, each with a read-back.

Only EQUIPPED pool rows are unequipped. A pool row stored as unequipped is never sent in either
direction, so it keeps its row (updateAi syncs by set difference) and stays unequipped; re-adding
it would store it equipped (RUL-2026-10-18-005). Items are never sent: Forge re-sends the live
items with their drop chances (recipes.mjs mergeAi).

  python3 push/162_ai_pool_reequip.gen.py [--check]
"""
import collections
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JUTSU_BUNDLE = "harvests/inbox/tnr_results_1792551342555.json"
AI_BUNDLES = ["harvests/inbox/tnr_results_1792551456483.json", "harvests/inbox/tnr_results_1792551557783.json",
              "harvests/inbox/tnr_results_1792551619150.json", "harvests/inbox/tnr_results_1792551674258.json"]
FIRST = 162
BATCH = 50
README = "push/README.md section 162-177"


def load_build():
    spec = importlib.util.spec_from_file_location("battle_lines_build", ROOT / "state/ai_pool_battle_lines/build.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def before_image():
    ais = {}
    for f in AI_BUNDLES:
        for c in json.loads((ROOT / f).read_text())["captures"]:
            if c.get("proc") == "profile.getAi" and c.get("ok") and c.get("persistOk") and isinstance(c.get("data"), dict):
                ais[c["data"]["userId"]] = c["data"]
    return ais


def plan():
    pool = json.loads((ROOT / "32b_DATA_pool.json").read_text())["records"]
    pool_ids = {r["id"] for r in pool.values()}
    ais = before_image()
    affected = []
    for u, a in ais.items():
        rows = a.get("jutsus") or []
        cycle = [r["jutsuId"] for r in rows if r["jutsuId"] in pool_ids and r.get("equipped") is True]
        if cycle:
            for r in rows:
                if r["jutsuId"] in pool_ids and (r.get("level"), r.get("experience")) != (1, 0):
                    raise SystemExit(f"{a['username']} ({u}): pool row {r['jutsuId']} is level {r.get('level')} "
                                     f"exp {r.get('experience')}; a re-insert would reset it to level 1")
            affected.append({"id": u, "name": a["username"].strip(),
                             "kit": [r["jutsuId"] for r in rows], "cycle": set(cycle)})
    affected.sort(key=lambda a: (a["name"].lower(), a["id"]))
    return pool, affected


def readback(ids):
    return {"before": [], "after": [{"proc": "profile.getAi", "input": {"userId": u}, "persist": "full"} for u in ids]}


def build():
    pool, affected = plan()
    # Probe: the smallest kit that still cycles a pool jutsu, so a surprise costs the least.
    probe = min(affected, key=lambda a: (len(a["kit"]), a["name"].lower(), a["id"]))
    rest = [a for a in affected if a is not probe]
    batches = [rest[i:i + BATCH] for i in range(0, len(rest), BATCH)]
    n_rows = sum(len(a["cycle"]) for a in affected)
    out = {}

    def unequip(group, label):
        items = [{"entity": "ai", "slot": "edit", "targetId": a["id"],
                  "name": f"{a['name']}: unequip {len(a['cycle'])} pool jutsu before the battle-line edit (law 60)",
                  "data": {"jutsus": [j for j in a["kit"] if j not in a["cycle"]]}} for a in group]
        note = (f"AI pool battle-line pass, step 1 UNEQUIP, {label}: {len(group)} AI(s). Removes only the EQUIPPED "
                "pool jutsu; everything else in the kit, the items, stats and rules are untouched. Ends with a full "
                "profile.getAi read-back. Check it with scripts/ai_pool_reequip_readback.py before the next "
                f"manifest. Order: 162 -> 163-169 -> 170 -> 171-177, never skipped ({README}). Do not run "
                "push/79 or push/128 until 177 is done. Generated by push/162_ai_pool_reequip.gen.py; do not hand-edit.")
        return {"_note": note, "items": items, "capture": readback([a["id"] for a in group])}

    def reequip(group, label):
        items = [{"entity": "ai", "slot": "edit", "targetId": a["id"],
                  "name": f"{a['name']}: re-equip original kit after the battle-line edit",
                  "data": {"jutsus": list(a["kit"])}} for a in group]
        note = (f"AI pool battle-line pass, step 3 RE-EQUIP, {label}: {len(group)} AI(s). Sends each AI's exact "
                "original kit from the push/158-161 before-image, original order. Run only after 170 is done. "
                "Ends with a full profile.getAi read-back; check it with scripts/ai_pool_reequip_readback.py. "
                f"({README}) Generated by push/162_ai_pool_reequip.gen.py; do not hand-edit.")
        return {"_note": note, "items": items, "capture": readback([a["id"] for a in group])}

    num = FIRST
    out[f"push/{num}_ai_pool_unequip_probe.json"] = unequip([probe], "PROBE - run first and check the read-back")
    for i, b in enumerate(batches, 1):
        num += 1
        out[f"push/{num}_ai_pool_unequip_{i}.json"] = unequip(b, f"batch {i} of {len(batches)}")

    build_mod = load_build()
    manifest_text, _review, problems = build_mod.build(str(ROOT / JUTSU_BUNDLE))
    if problems:
        raise SystemExit("battle lines: " + "; ".join(problems))
    edits = json.loads(manifest_text)["items"]
    num += 1
    out[f"push/{num}_ai_pool_battle_lines_edit.json"] = {
        "_note": ("AI pool battle-line pass, step 2 EDIT: the 82 shared-AI-pool jutsu. battleDescription on all 82, "
                  f"name on {sum('name' in it['data'] for it in edits)} (B28 Recoil Slam -> Backlash Palm), target on B31 (OTHER_USER -> ALLY), "
                  "injectableInBattle re-sent at its live value (law 20). Run ONLY after 162-169 are all done and "
                  "their read-backs pass: editing a jutsu an AI still has equipped severs that AI's combat link "
                  "(laws 18, 60). Ends with a full jutsu.get read-back. Built from "
                  "state/ai_pool_battle_lines/battle_lines.json. Generated by push/162_ai_pool_reequip.gen.py; do not hand-edit."),
        "items": edits,
        "capture": {"before": [], "after": [{"proc": "jutsu.get", "input": {"id": it["targetId"]}, "persist": "full"}
                                            for it in edits]}}
    groups = [[probe] + batches[0]] + batches[1:]
    for i, b in enumerate(groups, 1):
        num += 1
        out[f"push/{num}_ai_pool_reequip_{i}.json"] = reequip(b, f"batch {i} of {len(groups)}")

    unequipped = [it["targetId"] for p, m in out.items() if "_unequip" in p for it in m["items"]]
    reequipped = [it["targetId"] for p, m in out.items() if "_reequip_" in p for it in m["items"]]
    assert sorted(unequipped) == sorted(reequipped) == sorted(a["id"] for a in affected)
    assert len(edits) == len(pool) == 82
    return out, {"ais": len(affected), "rows": n_rows, "probe": probe}


def main():
    out, info = build()
    stale = []
    for path, m in out.items():
        text = json.dumps(m, indent=1, ensure_ascii=False) + "\n"
        p = ROOT / path
        if "--check" in sys.argv:
            if not p.is_file() or p.read_text() != text:
                stale.append(path)
        else:
            p.write_text(text)
        kinds = collections.Counter(it["entity"] for it in m["items"])
        print(path, len(m["items"]), dict(kinds), "reads", sum(len(v) for v in m["capture"].values()))
    print(f"{info['ais']} AIs, {info['rows']} equipped pool rows cycled; probe {info['probe']['name']} ({info['probe']['id']})")
    if stale:
        print("stale:", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
