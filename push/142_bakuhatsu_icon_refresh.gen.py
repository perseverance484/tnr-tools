#!/usr/bin/env python3
"""Generate push/142: the new Bakuhatsu jutsu icons (2026-10-19 Concussive Fracture set), sent to
the content review desk (Forge suggest mode). Do not hand-edit the output.

Each item changes one field, `image`. injectableInBattle is re-sent at its captured value (law 20:
omitted means false). Each item carries its own rationale.
None of the five is equipped by an AI: all five were in the unequipped batch (push/116) of the
2026-10-12 census, so an approved edit severs no AI combat link (laws 18, 60).

Inputs (all committed):
  - docs/design/bloodright/balance/kits_from_reference_captures.json  (jutsu ids, injectableInBattle)
  - art/jutsu_icons/bakuhatsu/exports/*.webp  (artpreflight JUTSU_ICON pass)
The generator then binds the image pack with forge/tools/make_image_pack.mjs.

  python3 push/142_bakuhatsu_icon_refresh.gen.py <image pack ref>
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "push/142_bakuhatsu_icon_refresh.json"
KIT = json.loads((ROOT / "docs/design/bloodright/balance/kits_from_reference_captures.json").read_text())["bakuhatsu"]
EXP = "art/jutsu_icons/bakuhatsu/exports"

# (jutsu name, repo path, rationale)
ICONS = [
    ("Inferno Cataclysm", f"{EXP}/icon_bakuhatsu_inferno_cataclysm_v1.webp",
     "New Bakuhatsu icon: a pillar of fire erupting from a fissure and throwing up slabs of stone, matching the devastating ground explosion this jutsu unleashes."),
    ("Kinetic Nova", f"{EXP}/icon_bakuhatsu_kinetic_nova_v1.webp",
     "New Bakuhatsu icon: a ball of explosive chakra bursting into many small explosions, matching the blast that disrupts all other chakra in the area."),
    ("Blast Shield", f"{EXP}/icon_bakuhatsu_blast_shield_v1.webp",
     "New Bakuhatsu icon: a ring of concussive fire deflecting incoming debris, matching the explosive barrier that softens the next attack the user takes."),
    ("Charge 4 Explosion", f"{EXP}/icon_bakuhatsu_charge_4_explosion_v1.webp",
     "New Bakuhatsu icon: linked micro-explosions sparking across cracked ground, matching the chakra spread over the battlefield that detonates on everything it touches."),
    ("Howitzer Crash", f"{EXP}/icon_bakuhatsu_howitzer_crash_v3.webp",
     "New Bakuhatsu icon: a V-shaped shock wave converging on a single point of impact, matching the explosive launch at the target that ends in one powerful detonation."),
]


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: 142_bakuhatsu_icon_refresh.gen.py <image pack ref>")
    by_name = {j["name"]: j for j in KIT["jutsu"]}
    items, img_sizes, maps = [], {}, []
    for name, path, why in ICONS:
        j = by_name.get(name)
        if not j:
            raise SystemExit(f"no captured Bakuhatsu jutsu {name}")
        if not isinstance(j.get("injectableInBattle"), bool):
            raise SystemExit(f"{name}: captured injectableInBattle missing")
        logical = Path(path).name
        img_sizes[logical] = (ROOT / path).stat().st_size
        maps += ["--map", f"{logical}={path}"]
        items.append({"entity": "jutsu", "slot": "edit", "name": name, "targetId": j["id"],
                      "data": {"image": f"@img:{logical}", "injectableInBattle": j["injectableInBattle"]},
                      "suggestion": {"rationale": why}})
    manifest = {
        "_note": ("New Bakuhatsu jutsu icons (5), the director-approved 2026-10-19 Concussive Fracture set "
                  "(art/jutsu_icons/bakuhatsu/), replacing the old figure-silhouette icons. Sent to the content "
                  "review desk; nothing changes until a reviewer approves. Only `image` changes; injectableInBattle "
                  "is re-sent at its live value (false, 2026-10-20 public read; law 20). No AI equips any of the five "
                  "(push/116 unequipped batch), so no AI link is severed (laws 18, 60). Generated by "
                  "push/142_bakuhatsu_icon_refresh.gen.py; do not hand-edit. Operator-run only; never skipPreflight."),
        "mode": "suggest",
        "suggestion": {"category": "VISUAL", "title": "New jutsu icon",
                       "rationale": "New jutsu icon from the director-approved Bakuhatsu icon set."},
        "imgSizes": img_sizes,
        "items": items,
    }
    OUT.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    subprocess.run(["node", str(ROOT / "forge/tools/make_image_pack.mjs"), str(OUT), *maps,
                    "--ref", sys.argv[1], "--write"], check=True, cwd=ROOT)


if __name__ == "__main__":
    main()
