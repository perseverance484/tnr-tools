#!/usr/bin/env python3
"""Close or reopen both Skyglass Wrecks with the event weekend (director 2026-11-08).

    python3 push/skyglass_wreck_window.gen.py close 2026-11-10T00:00:00.000Z   # push/514: expire Mon 6 PM Central
    python3 push/skyglass_wreck_window.gen.py reopen                            # clears expiresAt for Friday

Only content.expiresAt is sent; Forge fetch-merges the rest of each dungeon. An expired dungeon is off
getAvailable and refuses new lobbies (TheNinjaRPG routers/dungeon.ts getAvailable, create); runs already
started keep their snapshot and finish. Dungeons have no start date, so each event weekend needs a reopen.
Do not hand-edit the output.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DUNGEONS = {"Skyglass Wreck": "RHqzYdY4EAQA9HwsBKWDS", "Faded Skyglass Wreck": "j4QEUtjbK_lbOYUPVoidk"}  # push/390


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    if mode == "close" and len(sys.argv) == 3:
        num, at, verb = 514, sys.argv[2], "expire at " + sys.argv[2]
    elif mode == "reopen":
        num, at, verb = int(sys.argv[2]) if len(sys.argv) > 2 else 515, None, "reopen (expiresAt cleared)"
    else:
        sys.exit(__doc__)
    items = [{"entity": "dungeon", "slot": "edit", "phase": 1, "targetId": i, "name": f"{n}: {verb}",
              "data": {"expiresAt": at}} for n, i in DUNGEONS.items()]
    m = {"_note": f"push/{num}: both Skyglass Wrecks {verb}. expiresAt only, fetch-merged. "
                  "Generated by push/skyglass_wreck_window.gen.py; do not hand-edit.",
         "dedupNames": True, "items": items}
    out = os.path.join(ROOT, "push", f"{num}_skyglass_wreck_window.json")
    json.dump(m, open(out, "w"), indent=1, ensure_ascii=False)
    print(f"{os.path.relpath(out, ROOT)}: {len(items)} items")


if __name__ == "__main__":
    main()
