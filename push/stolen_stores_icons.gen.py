#!/usr/bin/env python3
"""Job 675, HIDDEN: the director's own Stolen Stores icons onto the records that carried the Galley Stores placeholder.

    python3 push/stolen_stores_icons.gen.py   -> push/675_stolen_stores_icons.json

The director sent the art in the Isonade thread (2026-11-20 15:42Z and 15:58Z). Processed in art/stolen_stores_icons/
(transparency, trim, 256 px lossless webp, artpreflight 0 errors) and uploaded hidden by the UploadThing workflow
(state/isonade_upload/uploaded.json). Every target is hidden today and stays hidden; the runner fetch-merges an edit,
so only `image` changes.

  item  Chart of the Flooded Stores  <- chart
  quest The Flooded Stores           <- chart
  quest Short Rations                <- ration tin
  quest Watch Log: Stolen Stores (Shallows) <- torn strip
The 81+ page (AgGR962c3XNo6Pr0up2qT) is published with a future start and is replaced whole by push/643 at release,
so its book icon rides push/643 (push/stolen_stores_pages.gen.py ICON_RELEASE), as does the strip. push/673 sends only
{hidden: false} to the other three, so nothing at 6 PM puts the placeholder back. Do not hand-edit the output.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UP = json.load(open(os.path.join(ROOT, "state/isonade_upload/uploaded.json")))["files"]


def url(src):
    u = UP[src]["url"]
    assert u.startswith("https://bbenpyo9uu.ufs.sh/f/"), u
    return u


TARGETS = [
    ("item", "FuQzaFNlpyOUGlO5BtjyX", "Chart of the Flooded Stores", "ss_icon_chart_flooded_stores_ss1"),
    ("quest", "-_1MdlGp-gxdiWKb6Bf3V", "The Flooded Stores", "ss_icon_chart_flooded_stores_ss1"),
    ("quest", "Gqbnq2LVtIVBlLYlAnam1", "Short Rations", "ss_icon_short_rations_ss1"),
    ("quest", "qOhvkP3aPCPH88wI7-IZW", "The Watch Log: Stolen Stores (Shallows)", "ss_icon_watchlog_stolen_stores_shallows_ss1"),
]


def main():
    items = [{"entity": e, "slot": "edit", "targetId": t, "phase": 1, "name": f"{n}: the director's icon (hidden)",
              "data": {"image": url(s)}} for e, t, n, s in TARGETS]
    m = {"_note": ("push/675, HIDDEN: the director's Stolen Stores icons onto the chart item, The Flooded Stores, "
                   "Short Rations and the Shallows page (image only; every record stays hidden). The 81+ page's icon "
                   "rides push/643. Generated by push/stolen_stores_icons.gen.py; do not hand-edit."),
         "items": items}
    out = os.path.join(ROOT, "push", "675_stolen_stores_icons.json")
    with open(out, "w") as fh:
        json.dump(m, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print("wrote", os.path.relpath(out, ROOT), len(items), "items")


if __name__ == "__main__":
    main()
