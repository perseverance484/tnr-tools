#!/usr/bin/env python3
"""Build push/233: swap the Ethereal Rebirth cast animation to v3 (direct edit of the same asset).

v3 (director, 2026-10-24): the v2 ribbons and flecks with the original (v1) starburst core; one continuous gold ribbon
that spins, peels off and lashes out (the v2 lash was a second drawing and jumped); the opening kept behind the token.

    python3 push/233_ethereal_rebirth_animation_v2.gen.py

Asset HwkXTjErL_Laxs8WtqBiI ("Ethereal Rebirth - Soul Ribbons", created by push/230) keeps its id, so push/231, which
points the absorb effect at it, needs no change. The image becomes the v2 strip
(art/jutsu_icons/ethereal_rebirth/animation/exports/anim_ethereal_rebirth_v2.webp: build_strip.py --set v2 from the art
director's transparent v2 layers; director: "Use v2"), uploaded under a new filename (law 32). Frames and speed are
unchanged (40 x 60 ms). hidden: false, because battles load only unhidden assets (law 16c, corrected 2026-10-24); this
edit therefore also covers push/232's unhide. The image pack is pinned at HEAD, so the strip must be committed.
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
STRIP = 'art/jutsu_icons/ethereal_rebirth/animation/exports/anim_ethereal_rebirth_v3.webp'
ASSET_ID = 'HwkXTjErL_Laxs8WtqBiI'
OUT = 'push/233_ethereal_rebirth_animation_v2.json'
FRAMES, SPEED = 40, 60
NAME = 'Ethereal Rebirth - Soul Ribbons'

from PIL import Image
w, h = Image.open(STRIP).size
assert w == 128 and h == 128 * FRAMES, (w, h)
b = open(STRIP, 'rb').read()
assert len(b) < 460800, len(b)
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
assert subprocess.check_output(['git', 'show', f'{ref}:{STRIP}']) == b, 'commit the strip first'
fn = os.path.basename(STRIP)
m = {
    "_note": "Swaps the Ethereal Rebirth cast animation asset HwkXTjErL_Laxs8WtqBiI to the v3 strip (v2 ribbons and flecks, the original starburst core, one continuous gold lash, the opening behind the token; 40 frames x 60 ms). Same id, so push/231 is unchanged. New filename (law 32). hidden: false so it plays in battle (law 16c corrected); this also does push/232's job. Generated by push/233_ethereal_rebirth_animation_v2.gen.py; do not hand-edit.",
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": STRIP, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "asset", "slot": "edit", "targetId": ASSET_ID, "name": NAME,
        "data": {"name": NAME, "type": "ANIMATION", "image": "@img:" + fn, "folder": "jutsuanimations", "frames": FRAMES,
                 "speed": SPEED, "hidden": False, "onInitialBattleField": False, "licenseDetails": "TNR"},
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: edit {ASSET_ID} -> v2 strip ({len(b)} bytes), hidden false, pack @ {ref[:7]}')
