#!/usr/bin/env python3
"""Build push/235: unhide the Ethereal Rebirth passive loop asset created by push/234 (direct edit).

    python3 push/235_ethereal_rebirth_loop_unhide.gen.py <push/234 results bundle>

Battles load only game assets with hidden = false (law 16c; theninjarpg misc.ts fetchGameAssets via layout/Combat.tsx),
so the loop would never play. Creates still ship hidden (law 16b, lint L13), hence this follow-up by literal id. The asset
data is re-sent as created, with hidden: false; the image is not re-sent (Forge merges the live record, so it stays).
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/235_ethereal_rebirth_loop_unhide.json'
CREATE = 'archive/spent-manifests/push-2026-10-22/234_ethereal_rebirth_loop.json'
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
aid = json.load(open(sys.argv[1])).get('idmap', {}).get('er_anim_soul_orbit')
assert aid, 'er_anim_soul_orbit not in the bundle idmap: run push/234 first'
created = json.load(open(CREATE))['items'][0]
data = dict(created['data'], hidden=False)
data.pop('image')
m = {
    "_note": "Unhides the Ethereal Rebirth passive loop asset created by push/234 (Soul Orbit, the absorb effect's staticAnimation): battles load only unhidden assets (law 16c). Generated by push/235_ethereal_rebirth_loop_unhide.gen.py; do not hand-edit.",
    "items": [{"entity": "asset", "slot": "edit", "targetId": aid, "name": created['data']['name'], "data": data}],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: unhide {aid}')
