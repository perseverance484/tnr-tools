#!/usr/bin/env python3
"""Build push/235: Ethereal Rebirth animations, fluidity pass + unhide the loop (direct edits of both assets).

    python3 push/235_ethereal_rebirth_loop_unhide.gen.py <push/230 bundle> <push/234 bundle> <push/237 bundle>

1. The cast animation (push/230's asset, swapped to v5 by push/233) -> the v7 strip (launch braid): 66 frames x 36 ms.
2. The passive loop (push/234's asset, created hidden) -> the loop2 strip: 100 frames x 36 ms, and hidden: false
   (battles load only unhidden assets, law 16c).
Both strips: docs/design/ethereal_rebirth_animation/V1_NOTES.md "v6 + loop2" (director, 2026-10-24: "very smooth...
transition from one to the next smoothly"). They share one frame time so the cast's hand-off lands on the loop (the
game starts them on the same tick). New filenames (law 32). The image pack is pinned at HEAD: commit the strips first.
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/235_ethereal_rebirth_loop_unhide.json'
SPENT = 'archive/spent-manifests/push-2026-10-22/'
E = 'art/jutsu_icons/ethereal_rebirth/animation/exports/'
if len(sys.argv) != 4:
    raise SystemExit(__doc__)
cast_id = json.load(open(sys.argv[1])).get('idmap', {}).get('er_anim_soul_ribbons')
loop_id = json.load(open(sys.argv[2])).get('idmap', {}).get('er_anim_soul_orbit')
hit_id = json.load(open(sys.argv[3])).get('idmap', {}).get('er_anim_soul_strike')
assert cast_id and loop_id and hit_id, 'run push/230, push/234 and push/237 first'

from PIL import Image
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
pack, sizes, items = {}, {}, []
for aid, create, strip, frames in ((cast_id, '230_ethereal_rebirth_animation.json', E + 'anim_ethereal_rebirth_v7.webp', 66),
                                   (loop_id, '234_ethereal_rebirth_loop.json', E + 'anim_ethereal_rebirth_loop2.webp', 100)):
    w, h = Image.open(strip).size
    assert w == 112 and h == 112 * frames, (strip, w, h)
    b = open(strip, 'rb').read()
    assert len(b) < 460800, len(b)
    assert subprocess.check_output(['git', 'show', f'{ref}:{strip}']) == b, 'commit the strips first'
    fn = os.path.basename(strip)
    pack[fn] = {"path": strip, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
    sizes[fn] = len(b)
    data = dict(json.load(open(SPENT + create))['items'][0]['data'], image='@img:' + fn, frames=frames, speed=36,
                hidden=False)
    items.append({"entity": "asset", "slot": "edit", "targetId": aid, "name": data['name'], "data": data})
# 3. the hit (push/237's asset, created hidden): unhide only, image as created (law 16c)
hit_create = next(p for p in (SPENT + '237_ethereal_rebirth_hit.json', 'push/237_ethereal_rebirth_hit.json') if os.path.exists(p))
hdata = dict(json.load(open(hit_create))['items'][0]['data'], hidden=False)
hdata.pop('image')
items.append({"entity": "asset", "slot": "edit", "targetId": hit_id, "name": hdata['name'], "data": hdata})
m = {
    "_note": "Unhides the Ethereal Rebirth hit (push/237, the damage effect's appearAnimation). Ethereal Rebirth animations, fluidity pass: the cast animation (HwkX..., appearAnimation) -> v7 (66 frames x 36 ms, the launch braid) and the passive loop (jRU-..., staticAnimation) -> loop2 (100 frames x 36 ms) and unhidden (law 16c). Same frame time, so the cast's blue band hands off onto the loop's. New filenames (law 32). Run before push/236 (the suggestion that points the absorb effect at both). Generated by push/235_ethereal_rebirth_loop_unhide.gen.py; do not hand-edit.",
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": pack},
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {cast_id} -> v7, {loop_id} -> loop2 + unhide, {hit_id} unhide, pack @ {ref[:7]}')
