#!/usr/bin/env python3
"""Job 670, HIDDEN: no player seal can take hold on Isonade before round 6, and Omen: Black Water waits for round 6.

The director (2026-11-20 01:07Z, relayed): "I want both to be true, below 75% and after round 5. My plan is to give
Isonade Seal immunity for the first 5 rounds until Black Water is used for the first time. Seal Immunity drops and
they Seal themselves for the damage amp next round. Just to slow players down a bit so they arent speed running
through it".

What this writes (engine pin 3314d122):
- Isonade's AI record gains sealprevent 100 for 5 rounds. Record effects enter battle as fromType "bloodline" with
  their own rounds (server/api/routers/combat.ts 4117-4136), and every effect's rounds tick down by 1 each time the
  round advances (libs/combat/util.ts 3042-3049), from the first advance 0 -> 1, so it reads 5 - r at round r and
  stops guarding at round 5.
  - A player's seal checks sealprevent first (libs/combat/tags.ts seal(), preventCheck with no creation-round
    exception) and is cancelled on a pass, so seals cast in rounds 1-4 are cancelled. A seal cast in round 5 lands,
    but a seal only disables effects once it has resolved (isEffectEnabled skips isNew seals), so it takes hold from
    round 6. No player seal takes hold before round 6.
  - 5 is the longest timer that leaves Black Water's own self seal alone: in the sim (state/flooded_stores_build/
    isonade_v10_sim) a 6-round guard cancels the self seal of an omen fired in round 6; 5 does not.
  - Clear and Cleanse skip fromType "bloodline" (persistentEffectSourceTypes, tags.ts 1235), so no player can strip
    it early. A seal cannot pause it either, because it stops the seal that would pause it.
- Rule 15 (Omen: Black Water, health_below 75) gains round_greater_than 5 (libs/combat/ai_v2.ts: battle.round > 5),
  so the omen comes the first round from 6 on that Isonade is under 75%. By then the immunity has run out, so the
  omen's own self seal lands as before and opens the damage window.

Why not "until the first Black Water" exactly: the only seal immunity a player cannot Clear sits on the AI record or
worn gear, and nothing Isonade casts can remove either one, so it has to run out on a timer. A jutsu-laid immunity
could be dropped by the omen, but a player's Clear would strip it too. With the round-6 gate, the immunity ends on
the first round Black Water can come.

Unchanged: the record's stunprevent and 70% hull, the worn stun guard (Isonade's Old Hull, job 669, kept by the Forge
AI merge), the 18 jutsu and the other 19 rules.

Usage: python3 push/670_isonade_seal_window.gen.py
Writes push/670_isonade_seal_window.json. Do not hand-edit.
"""
import copy
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ISONADE = "K_lwNvMPJLMsn1sUGXqZm"
OMEN_BW = "vGtG2yV8WqaRTHh-19nVg"
CAP = os.path.join(ROOT, "state/stolen_stores_captures/isonade_v8_live_2026-11-20")
IMMUNE_ROUNDS = 5

ai = json.load(open(os.path.join(CAP, "post669_getAi_isonade.json")))
prof = json.load(open(os.path.join(CAP, "pre670_aiProfile_isonade.json")))
assert ai["userId"] == ISONADE and prof["userId"] == ISONADE
assert [e["type"] for e in ai["effects"]] == ["stunprevent", "decreasedamagetaken"], ai["effects"]
assert ai["effects"][1]["power"] == 70
assert len(ai["items"]) == 1 and len(ai["jutsus"]) == 18

stun = ai["effects"][0]
seal_guard = dict(stun, type="sealprevent", calculation="static", rounds=IMMUNE_ROUNDS, description="Isonade cannot be sealed yet")
effects = copy.deepcopy(ai["effects"]) + [seal_guard]

rules = copy.deepcopy(prof["rules"])
assert len(rules) == 20
omen = [i for i, r in enumerate(rules) if r["action"].get("jutsuId") == OMEN_BW]
assert omen == [14], omen
assert rules[14]["conditions"] == [{"type": "health_below", "value": 75, "description": "Health below given percentage"}]
rules[14]["conditions"].append({"type": "round_greater_than", "value": IMMUNE_ROUNDS,
                                "description": "Current round is greater than specified value"})

items = [
    {"entity": "ai", "slot": "edit", "targetId": ISONADE, "phase": 1,
     "name": f"Isonade: record gains sealprevent 100 for {IMMUNE_ROUNDS} rounds (stun guard, hull 70, kit and Old Hull kept)",
     "data": {"effects": effects}},
    {"entity": "aiProfile", "slot": "edit", "targetId": ISONADE, "phase": 2,
     "name": f"Isonade: Omen: Black Water also needs round > {IMMUNE_ROUNDS} (20 rules, rest unchanged)",
     "data": {"rules": rules, "includeDefaultRules": prof["includeDefaultRules"]}},
]
m = {"_note": ("push/670, HIDDEN: Isonade seal guard (no player seal takes hold before round 6) and Omen: Black Water from round 6. Generated by "
               "push/670_isonade_seal_window.gen.py; do not hand-edit."),
     "items": items}
out = os.path.join(ROOT, "push", "670_isonade_seal_window.json")
with open(out, "w") as f:
    json.dump(m, f, separators=(",", ":"))
print(f"wrote {out}: {len(items)} items")
