#!/usr/bin/env python3
"""Build push/232: unhide the Ethereal Rebirth cast animation asset created by push/230 (direct edit).

    python3 push/232_ethereal_rebirth_animation_unhide.gen.py <push/230 results bundle>

Battles load only game assets with hidden = false (studie-tech/theninjarpg app/src/server/api/routers/misc.ts
fetchGameAssets, called through misc.getAllGameAssetNames by layout/Combat.tsx), so a hidden animation never plays.
Creates must still ship hidden (law 16b, lint L13), hence this follow-up. Run it right after push/230 and before push/231.
The full asset data is re-sent with hidden: false (same values as the create).
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/232_ethereal_rebirth_animation_unhide.json'
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
bundle = json.load(open(sys.argv[1]))
aid = bundle.get('idmap', {}).get('er_anim_soul_ribbons')
assert aid, 'er_anim_soul_ribbons not in the bundle idmap: run push/230 first'
created = json.load(open('push/230_ethereal_rebirth_animation.json'))['items'][0]
url = None
for k, v in (bundle.get('imgUrls') or bundle.get('images') or {}).items():
    if k.endswith('anim_ethereal_rebirth_v1.webp'):
        url = v
data = dict(created['data'], hidden=False)
if url:
    data['image'] = url
else:
    data.pop('image')  # keep the uploaded image as it is
m = {
    "_note": "Unhides the Ethereal Rebirth cast animation asset created by push/230: battles load only unhidden assets, so a hidden animation never plays (director, 2026-10-24; law 16c corrected). Generated by push/232_ethereal_rebirth_animation_unhide.gen.py; do not hand-edit.",
    "items": [{"entity": "asset", "slot": "edit", "targetId": aid, "name": created['data']['name'], "data": data}],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: unhide {aid}')
