#!/usr/bin/env python3
"""Generate push/326_variant_token_capture_1/_2: read-only census of every live VARIANT_TOKEN variant.

RUL-2026-10-29-054 item 2: before any Skyglass Token ships, every live token-cost variant without a required unlock
item is bound to a token, because the Skyglass Token (unlockitemvariant, variantId null) would also unlock it. The
director believes all live token variants are bought with the Lion Token (FG4xYkI8UmRrJCdD3yPxI, variantId null); an
unhidden "Test Variant" token (QeQtevFEEL766JJQZ5tWK) also exists. Needs Forge 0.12.1 (item.getVariantNames and
item.getItemVariants as persist-full captures) and a signed-in session (both reads are protected). Zero writes.

Two passes, because item.getVariantNames answers {id, name: "<item>: <variant>"} with no itemId, item names can
themselves contain ": ", and about 107 live items are named by no repository file (push/323: 873 live vs 766 seed):
  pass 1  (no args)            item.getVariantNames + item.get of the Lion Token and the Test Variant.
  pass 2  --pass2 <bundle>     from the pass-1 results bundle: every base item whose name prefixes a variant name,
                               resolved against answers/names_item.json and every item read/entry in harvests/, gets
                               item.getItemVariants {itemId}; getVariantNames is read again first so the two can be
                               compared. Every split point of "<item>: <variant>" is tried and every matching id is
                               read (an extra read is harmless; the rows say which item is real). An unresolved name
                               stops the generator; supply its id with --item "<item name>=<id>" (the staff page
                               /manual/item lists ids).
  report  --report <bundle>    from the pass-2 bundle: the token variants with no requiredItemId (the ones to bind),
                               and any getVariantNames id that no getItemVariants read covered.
Run from anywhere; paths are relative to the repository root (--root overrides it).
"""
import argparse, glob, json, os, sys

LION, TEST = "FG4xYkI8UmRrJCdD3yPxI", "QeQtevFEEL766JJQZ5tWK"
TAIL = " Changes nothing. Generated by push/326_variant_token_capture.gen.py; do not hand-edit."

ap = argparse.ArgumentParser()
ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
g = ap.add_mutually_exclusive_group()
g.add_argument("--pass2", metavar="BUNDLE")
g.add_argument("--report", metavar="BUNDLE")
ap.add_argument("--item", action="append", default=[], metavar="NAME=ID")
a = ap.parse_args()
os.chdir(a.root)


def write(path, m):
    json.dump(m, open(path, "w"), indent=1, ensure_ascii=False)
    open(path, "a").write("\n")
    print(path, len(m["capture"]["before"]), "reads")


def captures(bundle, proc):
    """Persisted bodies of one procedure in a results bundle; a failed or unpersisted read is fatal."""
    out = []
    for c in json.load(open(bundle))["captures"]:
        if c.get("proc") != proc:
            continue
        if not (c.get("ok") and c.get("persistOk") and "data" in c):
            sys.exit(f"{bundle}: {proc} {c.get('input')} was not read and persisted ({c.get('error') or c.get('persistError')})")
        out.append(c)
    return out


def catalog():
    """name -> {ids}: the seed catalogue, every item body in harvests/, every item entry with an id."""
    names = {}
    add = lambda n, i: names.setdefault(n, set()).add(i) if isinstance(n, str) and isinstance(i, str) and i else None
    for i, n, *_ in json.load(open("answers/names_item.json"))["rows"]:
        add(n, i)
    for f in sorted(glob.glob("harvests/**/*.json", recursive=True)):
        try:
            d = json.load(open(f))
        except (ValueError, OSError):
            continue
        if not isinstance(d, dict):
            continue
        for c in d.get("captures") or []:
            x = c.get("data") if isinstance(c, dict) else None
            if c.get("proc") in ("item.get", "item.getItemWithCraftingRequirements") and isinstance(x, dict):
                add(x.get("name"), x.get("id"))
        for e in d.get("entries") or []:
            if isinstance(e, dict) and e.get("entity") == "item":
                add(e.get("name"), e.get("id"))
    for kv in a.item:
        n, _, i = kv.rpartition("=")
        add(n, i)
    return names


if a.report:
    rows = [v for c in captures(a.report, "item.getItemVariants") for v in c["data"]]
    listed = {r["id"]: r["name"] for c in captures(a.report, "item.getVariantNames") for r in c["data"]}
    token = [v for v in rows if v["costType"] == "VARIANT_TOKEN"]
    print(f"{len(listed)} listed token variants; {len(token)} token variants read across "
          f"{len(captures(a.report, 'item.getItemVariants'))} items")
    for v in sorted(token, key=lambda v: (v["itemId"], v["order"])):
        print(f"  {'BIND' if not v.get('requiredItemId') else 'ok  '} {v['id']} item {v['itemId']} #{v['order']} "
              f"{v['name']!r} requiredItemId={v.get('requiredItemId')}")
    missing = sorted(set(listed) - {v["id"] for v in token})
    for i in missing:
        print(f"  NOT COVERED {i} {listed[i]!r}: no getItemVariants read returned it")
    sys.exit(1 if missing else 0)

if not a.pass2:
    m = {"_note": "Variant token census pass 1/2: read-only item.getVariantNames (persist full: every VARIANT_TOKEN "
                  "variant as {id, \"<item>: <variant>\"}) and item.get (persist full) of the Lion Token and the Test "
                  "Variant token, so their live unlockitemvariant.variantId is on record. Pass 2 is generated from "
                  "this bundle (--pass2). RUL-2026-10-29-054 item 2. Requires Forge 0.12.1 and a signed-in session."
                  + TAIL,
         "capture": {"before": [
             {"proc": "item.getVariantNames", "persist": "full"},
             {"proc": "item.get", "input": {"id": LION}, "persist": "full", "_name": "Lion Token"},
             {"proc": "item.get", "input": {"id": TEST}, "persist": "full", "_name": "Test Variant"},
         ]},
         "items": []}
    write("push/326_variant_token_capture_1.json", m)
    sys.exit(0)

listed = [r for c in captures(a.pass2, "item.getVariantNames") for r in c["data"]]
names = catalog()
want, unresolved = {}, []
for r in listed:
    parts = r["name"].split(": ")
    hits = {i: ": ".join(parts[:k]) for k in range(1, len(parts)) for i in names.get(": ".join(parts[:k]), ())}
    if not hits:
        unresolved.append(r)
    want.update(hits)
if unresolved:
    for r in unresolved:
        print(f"unresolved: {r['id']} {r['name']!r}", file=sys.stderr)
    sys.exit(f"{len(unresolved)} variant name(s) name no known item; pass --item \"<item name>=<id>\" for each")
items = sorted(want.items(), key=lambda t: (t[1].lower(), t[0]))
m = {"_note": f"Variant token census pass 2/2: item.getVariantNames again (persist full), then item.getItemVariants "
              f"(persist full: id, costType, requiredItemId and the rest) of the {len(items)} base item(s) whose names "
              f"prefix the {len(listed)} token variant(s) listed by pass 1 ({os.path.basename(a.pass2)}). Check with "
              "--report: every listed id must appear in a getItemVariants read; token variants with no requiredItemId "
              "are bound next. RUL-2026-10-29-054 item 2. Requires Forge 0.12.1 and a signed-in session." + TAIL,
     "capture": {"before": [{"proc": "item.getVariantNames", "persist": "full"}]
                 + [{"proc": "item.getItemVariants", "input": {"itemId": i}, "persist": "full", "_name": n} for i, n in items]},
     "items": []}
write("push/326_variant_token_capture_2.json", m)
