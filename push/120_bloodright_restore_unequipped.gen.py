#!/usr/bin/env python3
"""Generate the restore manifests for RUL-2026-10-18-005. Do not hand-edit outputs.

push/112-115 re-equipped Bloodright kit jutsu with profile.updateAi, which always inserts a new
userJutsu row with equipped = true (profile.ts applyUserContentChanges at 94f9d84). 82 of those
rows on 32 AIs had been equipped = false, and battles load only equipped jutsu (combat.ts
initiateBattle, `where: eq(jutsus.equipped, true)`), so those AIs now use jutsu they did not use
before. updateAi cannot store equipped = false, so the old battle behaviour is restored by
removing exactly those jutsu from the AI's kit. Nothing else is sent; Forge re-sends items.

Inputs (all committed):
  - harvests/inbox/tnr_results_1792352813119.json, ..._1792352829484.json  (push/109-110 before-image)
  - harvests/inbox/tnr_results_1792361926421.json, ..._1792361977483.json,
    ..._1792362073011.json, ..._1792362166649.json                       (push/112-115 read-backs)

Each manifest ends with a full profile.getAi read-back of its AIs.

  python3 push/120_bloodright_restore_unequipped.gen.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEFORE = ["harvests/inbox/tnr_results_1792352813119.json", "harvests/inbox/tnr_results_1792352829484.json"]
AFTER = ["harvests/inbox/tnr_results_1792361926421.json", "harvests/inbox/tnr_results_1792361977483.json",
         "harvests/inbox/tnr_results_1792362073011.json", "harvests/inbox/tnr_results_1792362166649.json"]
FIRST = 120
PER_MANIFEST = 16


def ais(paths):
    out = {}
    for f in paths:
        for c in json.loads((ROOT / f).read_text())["captures"]:
            if c.get("proc") == "profile.getAi" and c.get("ok") and c.get("persistOk"):
                out[c["data"]["userId"]] = c["data"]
    return out


def build():
    before, after = ais(BEFORE), ais(AFTER)
    entries = []
    removed_total = 0
    for u, a in sorted(after.items(), key=lambda kv: (kv[1]["username"].strip().lower(), kv[0])):
        was = {r["jutsuId"]: r["equipped"] for r in before[u]["jutsus"]}
        now = {r["jutsuId"]: r["equipped"] for r in a["jutsus"]}
        if set(was) != set(now):
            raise SystemExit(f"{a['username']}: kit membership changed since the before-image; refusing")
        remove = sorted(j for j in now if was[j] is False and now[j] is True)
        if not remove:
            continue
        names = sorted(r["jutsu"]["name"] for r in a["jutsus"] if r["jutsuId"] in remove)
        keep = [r["jutsuId"] for r in before[u]["jutsus"] if r["jutsuId"] not in remove]  # before-image order
        entries.append((u, a["username"].strip(), keep, names))
        removed_total += len(remove)
    batches = [entries[i:i + PER_MANIFEST] for i in range(0, len(entries), PER_MANIFEST)]
    out = {}
    for n, b in enumerate(batches, 1):
        items = [{"entity": "ai", "slot": "edit", "targetId": u,
                  "name": f"{name}: remove {len(names)} kit jutsu that were unequipped before push/112-115 ({', '.join(names)})",
                  "data": {"jutsus": keep}} for u, name, keep, names in b]
        out[f"push/{FIRST + n - 1}_bloodright_restore_unequipped_{n}.json"] = {
            "_note": (f"Restore battle behaviour, batch {n} of {len(batches)} (RUL-2026-10-18-005): {len(b)} AI(s). "
                      "Each AI's kit is re-sent without the Bloodright kit jutsu that were equipped=false before "
                      "push/112-115 and came back equipped=true; battles load only equipped jutsu, so removing them "
                      "restores how the AI fought. Read-back of every AI at the end. Generated by "
                      "push/120_bloodright_restore_unequipped.gen.py; do not hand-edit. Operator-run only."),
            "items": items,
            "capture": {"before": [], "after": [{"proc": "profile.getAi", "input": {"id": u}, "persist": "full"}
                                                for u, *_ in b]},
        }
    assert removed_total == sum(len(names) for e in entries for names in [e[3]])
    return out, len(entries), removed_total


def main():
    out, n_ai, n_j = build()
    stale = []
    for path, m in out.items():
        text = json.dumps(m, indent=1, ensure_ascii=False) + "\n"
        p = ROOT / path
        if "--check" in sys.argv:
            if not p.is_file() or p.read_text() != text:
                stale.append(path)
        else:
            p.write_text(text)
        print(path, len(m["items"]), "AI edits,", len(m["capture"]["after"]), "reads")
    print(f"{n_ai} AIs, {n_j} jutsu removed")
    if stale:
        print("stale:", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
