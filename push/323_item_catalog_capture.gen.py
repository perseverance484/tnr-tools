#!/usr/bin/env python3
"""Generate push/323_item_catalog_capture_1..6: read-only full capture of every item record.

Director, 2026-10-28: "Thinking you may need a fresh capture of all items for this." The capture is for the Skyglass
consumable-cache split and the profession-material review (RUL-2026-10-28-018). The seed index
(harvests/seed/41_INDEX_item.json) lists 766 items, hidden ones included. Each is point-read with item.get, persist full,
so shop flag, crafting requirements, event flag and effects land in the bundle. Part 1 also reads item.getAllNames (row
count only; Forge allows persist only on audited point reads), which shows how many items are newer than the seed.
Zero writes. Run from the repo root.
"""
import json, os
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
s = json.load(open('harvests/seed/41_INDEX_item.json'))
c = s['cols']
rows = sorted((r for r in s['rows'] if not r[c.index('absent_since')]), key=lambda r: r[c.index('n')].lower())
PARTS = 6
n = (len(rows) + PARTS - 1) // PARTS
for p in range(PARTS):
    part = rows[p * n:(p + 1) * n]
    before = [{"proc": "item.getAllNames", "input": {}}] if p == 0 else []
    before += [{"proc": "item.get", "input": {"id": r[c.index('id')]}, "persist": "full", "_name": r[c.index('n')]}
               for r in part]
    m = {"_note": f"Item catalog capture part {p + 1}/{PARTS}: read-only item.get (persist full) of {len(part)} items "
                  f"({part[0][c.index('n')]} .. {part[-1][c.index('n')]}), hidden ones included. It feeds the Skyglass "
                  "consumable-cache split and the profession-material review (RUL-2026-10-28-018)."
                  + (" Also item.getAllNames (row count only; Forge allows persist only on point reads), which shows how many items are newer than the seed."
                     if p == 0 else "")
                  + " Changes nothing. Generated by push/323_item_catalog_capture.gen.py; do not hand-edit.",
         "capture": {"before": before}, "items": []}
    out = f'push/323_item_catalog_capture_{p + 1}.json'
    json.dump(m, open(out, 'w'), indent=1, ensure_ascii=False); open(out, 'a').write('\n')
    print(out, len(before))
