#!/usr/bin/env python3
"""Weapon effect-target fix (task u8f4d4e913e3313820988decfe0333d9c, 2026-11-26).

    python3 push/weapon_effect_targets.gen.py      # writes push/631_weapon_effect_targets.json

The director reported Gale Fans and Soul Harvester buffing the enemy and debuffing the user. An audit of every live
weapon (95 visible, 56 hidden) against each tag's polarity in docs/combat-engine/tags/*.yaml found four wrong targets:

- Gale Fans: afterburn (a debuff on the holder) sat on SELF -> INHERIT (the enemy hit).
- Soul Harvester: lifesteal (a buff on the attacker) sat on INHERIT -> SELF.
- Flaming Sword: increasedamagegiven (a buff) sat on INHERIT -> SELF.
- Warden's Bracers: reflect (a buff on the defender) sat on INHERIT -> SELF.

Only the `target` of the named effect changes; every other effect field is copied verbatim from the live read in
state/weapon_target_audit/live_read_2026-11-26.json. item.update rewrites the recipe from the payload, so each edit
carries its current craftingRequirements ([] where the item has none). Re-read the four items before running: if any
updatedAt moved since the read, regenerate from a fresh read.
"""
import copy
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NUM = 631
OUT = os.path.join(ROOT, "push", f"{NUM}_weapon_effect_targets.json")
READ = os.path.join(ROOT, "state", "weapon_target_audit", "live_read_2026-11-26.json")

# id -> (effect type, live target, fixed target)
FIXES = {
    "_JYBIKp2yspE-lxvmo24t": ("afterburn", "SELF", "INHERIT"),           # Gale Fans
    "WlYWR3Fit50gKxDUdnZXt": ("lifesteal", "INHERIT", "SELF"),           # Soul Harvester
    "1GmiQAGuBZZsjIFqcqPkR": ("increasedamagegiven", "INHERIT", "SELF"), # Flaming Sword
    "qTzWEb6tFBv8dl15ztqDO": ("reflect", "INHERIT", "SELF"),             # Warden's Bracers
}


def main():
    live = json.load(open(READ))["items"]
    items = []
    for tid, (tag, old, new) in FIXES.items():
        rec = live[tid]
        effects = copy.deepcopy(rec["effects"])
        hits = [e for e in effects if e["type"] == tag]
        assert len(hits) == 1, (rec["name"], tag, len(hits))
        assert hits[0]["target"] == old, (rec["name"], tag, hits[0]["target"])
        hits[0]["target"] = new
        changed = [i for i, (a, b) in enumerate(zip(rec["effects"], effects)) if a != b]
        assert len(changed) == 1 and len(effects) == len(rec["effects"]), rec["name"]
        reqs = [{"ids": [r["requirementItemId"]], "number": r["quantity"]} for r in rec["craftingRequirements"]]
        items.append({
            "entity": "item", "slot": "edit", "targetId": tid,
            "name": f"{rec['name']}: {tag} target {old} -> {new}",
            "data": {"effects": effects, "craftingRequirements": reqs},
        })
    m = {
        "_note": (f"push/{NUM} weapon effect-target fix: Gale Fans afterburn SELF->INHERIT; Soul Harvester lifesteal, "
                  "Flaming Sword increasedamagegiven and Warden's Bracers reflect INHERIT->SELF. Effects otherwise verbatim "
                  "from the 2026-11-26 live read; craftingRequirements carried so the recipes survive the update. hidden "
                  "untouched. Generated by push/weapon_effect_targets.gen.py; do not hand-edit."),
        "items": items,
    }
    with open(OUT, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"push/{NUM}_weapon_effect_targets.json: {len(items)} items")


if __name__ == "__main__":
    main()
