#!/usr/bin/env python3
"""push/585, HIDDEN-safe text fix: two Skyglass omens printed a raw "%target" in the battle log.

    python3 push/skyglass_omen_text.gen.py --live state/omen_text_live_kits.json

Omen: Seven Planks and Omen: Three-Plank Line cast on GROUND coordinates, so there is no character for %target to
name (seen in The Whole Wreck hand test, 2026-11-10; dauntless approved the reword 00:49 UTC). Only battleDescription
changes (plus injectableInBattle false, law 20). Law 18/60: every holder drops the omen (phase 1), the two jutsu are
edited (phase 2), every holder gets its exact kit back (phase 3). Rules are not sent. Items are re-sent in full (law 70).

Holders come from push/skyglass_mark_fix.gen.py holders() (the committed manifests and results bundles) and are
checked against fresh profile.getAi reads in --live (id -> {"jutsus": [...], "items": [...]}); the build stops on any
difference. Do not hand-edit the output.
"""
import importlib.util
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT = {
    "cJD-5e-7oZhQfvDfypyK-": ("Omen: Seven Planks", "%user marks seven planks with a red seal."),
    "gLsou07qLtM34zyepQRcS": ("Omen: Three-Plank Line", "%user sights down a short red line across the deck."),
}


def main():
    spec = importlib.util.spec_from_file_location("mf", os.path.join(ROOT, "push", "skyglass_mark_fix.gen.py"))
    mf = importlib.util.module_from_spec(spec)
    argv, sys.argv = sys.argv, [sys.argv[0]]
    spec.loader.exec_module(mf)
    sys.argv = argv
    live = {k: v for k, v in json.load(open(sys.argv[sys.argv.index("--live") + 1])).items() if k != "_read"}
    holders = mf.holders(set(TEXT))
    assert set(h["id"] for h in holders) == set(live), (sorted(set(h["id"] for h in holders) ^ set(live)))
    off, on, notes = [], [], []
    for h in holders:
        L = live[h["id"]]
        assert sorted(L["jutsus"]) == sorted(h["kit"]), (h["name"], "kit drift", sorted(set(L["jutsus"]) ^ set(h["kit"])))
        items = L["items"]
        kit = list(L["jutsus"])
        names = [TEXT[j][0] for j in h["off"]]
        off.append({"entity": "ai", "slot": "edit", "targetId": h["id"], "phase": 1,
                    "name": f"{h['name']}: omen off for the text fix (law 18/60)",
                    "data": {"jutsus": [j for j in kit if j not in TEXT], "items": items}})
        on.append({"entity": "ai", "slot": "edit", "targetId": h["id"], "phase": 3,
                   "name": f"{h['name']}: omen back on (law 18/60)", "data": {"jutsus": kit, "items": items}})
        notes.append(f"{h['name']} ({h['id']}): off/on {names}")
    edits = [{"entity": "jutsu", "slot": "edit", "targetId": j, "phase": 2, "name": f"{n}: log text without %target",
              "data": {"battleDescription": t, "injectableInBattle": False}} for j, (n, t) in TEXT.items()]
    for _, t in TEXT.values():
        assert "%target" not in t and "—" not in t and "–" not in t
    m = {"_note": "push/585: Omen: Seven Planks and Omen: Three-Plank Line log text without %target (ground casts "
                  "have no target to name). Holders drop the omen, the text is edited, holders re-equip their exact "
                  "kit (law 18/60); items re-sent (law 70); rules untouched. Generated by "
                  "push/skyglass_omen_text.gen.py; do not hand-edit.",
         "_holders": notes, "items": off + edits + on}
    path = os.path.join(ROOT, "push", "585_skyglass_omen_text.json")
    with open(path, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(os.path.relpath(path, ROOT), len(m["items"]), "items,", len(holders), "holders")


if __name__ == "__main__":
    main()
