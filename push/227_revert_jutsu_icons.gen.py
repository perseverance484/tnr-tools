#!/usr/bin/env python3
"""Build push/227: put the original image back on the 59 jutsu that carry our new icons (direct edit, image only).

    python3 push/227_revert_jutsu_icons.gen.py

Source: state/jutsu_icon_revert/revert_2026-10-23.json (how each jutsu and its original were found is in its _note).
Each edit sends only `image` (the original URL) and `injectableInBattle` at its live value (law 20). Director's ruling
(2026-10-23): no unequip / re-equip cycle, so editing the three AI-equipped jutsu (Arctic Frost, Prism, Earthen Bastion)
severs those AIs' combat links (law 18); the affected AIs are named in the manifest note and need re-saving afterwards.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SRC = 'state/jutsu_icon_revert/revert_2026-10-23.json'
OUT = 'push/227_revert_jutsu_icons.json'
doc = json.load(open(SRC))
items = []
for r in doc['jutsu']:
    assert r['original_image'].startswith('https://'), r['name']
    items.append({"entity": "jutsu", "slot": "edit", "name": f"{r['name']}: original icon restored", "targetId": r['id'],
                  "data": {"image": r['original_image'], "injectableInBattle": r['injectableInBattle']}})
m = {"_note": "Reverts our new jutsu icons (director, 2026-10-23: players did not like them; a slower, one-jutsu-at-a-time premium rework follows later). 59 jutsu get their original image back; nothing else changes (image plus injectableInBattle re-sent at its live value, law 20). Direct edit. No unequip / re-equip (director's call): editing Arctic Frost, Prism and Earthen Bastion severs the combat link of the AIs that have them equipped (law 18) per the 2026-10-21 census: ANBU Coordinator, Frost Warden, Frost Sovereign (Arctic Frost), Mermaid Jade and ' Jade' (Prism), War Commander (Earthen Bastion); re-save those AIs afterwards. Ends with a jutsu.get read-back of all 59. Source: " + SRC + ". Generated by push/227_revert_jutsu_icons.gen.py; do not hand-edit.",
     "items": items,
     "capture": {"before": [], "after": [{"proc": "jutsu.get", "input": {"id": r['id']}, "persist": "full"} for r in doc['jutsu']]}}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} jutsu edits')
