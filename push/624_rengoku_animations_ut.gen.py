#!/usr/bin/env python3
"""Build push/624_rengoku_animations_ut: push/624's two hidden asset creates with the image pointed at the director's own
UploadThing instead of a Forge image pack, so it runs over the game connector (mcp_run; no browser upload).

    python3 push/624_rengoku_animations_ut.gen.py

Brandon 2026-11-18: "Use UploadThing" (the MoE route, push/527/608). Files uploaded by the rengoku-uploadthing workflow
on the task branch; URLs in state/rengoku_upload/uploaded.json, sha-checked against push/624's imagePack. Same srcIds,
so push/625 and push/626 build from this run's bundle unchanged. Off-Bunny hosts skip the game's ?width= rendition and
its upload moderation (director's call). Do not hand-edit.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SRC = 'push/624_rengoku_animations.json'
UP = 'state/rengoku_upload/uploaded.json'
OUT = 'push/624_rengoku_animations_ut.json'
m = json.load(open(SRC))
up = json.load(open(UP))['files']
items = []
for it in m['items']:
    fn = it['data']['image'].split(':', 1)[1]
    u = up[it['srcId']]
    assert u['file'] == fn and u['sha256'] == m['imagePack']['files'][fn]['sha256'], ('upload does not match pack', fn)
    assert u['url'].startswith('https://bbenpyo9uu.ufs.sh/f/'), u['url']
    items.append(dict(it, data=dict(it['data'], image=u['url'])))
out = {
    "_note": "push/624 (Rengoku Ro strike + smoulder, 2 hidden ANIMATION creates, 300 px, 70 ms) with the strips hosted on the director's own UploadThing (Brandon 2026-11-18: 'Use UploadThing'), so it runs over the connector. Same srcIds as push/624: build push/625 and push/626 from this run's bundle. Generated by push/624_rengoku_animations_ut.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(out, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset creates')
