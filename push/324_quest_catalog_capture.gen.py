#!/usr/bin/env python3
"""Generate push/324_quest_catalog_capture_1..4: read-only full capture of every quest record.

Director, 2026-10-28: "Approve and build the audit" (RUL-2026-10-28-023). The hunter's and gatherer's chests are about to
be flagged canBeHunted / canBeGathered. Any quest or objective whose reward sets reward_hunter_items or
reward_gathering_items with NO id list draws from every flagged item (theninjarpg routers/quests.ts ~2218), so it would
start dropping chests. This capture reads every quest in the seed index (harvests/seed/47_INDEX_quest.json; hidden ones
included) with quests.get, persist full, so each record's rewards can be audited. Part 1 also reads quests.getAllNames,
which returns only a row count: Forge allows persist only on point reads. The count shows how many quests are newer
than the seed. Zero writes. Run from the repo root.
"""
import json, os
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
s = json.load(open('harvests/seed/47_INDEX_quest.json'))
c = s['cols']
rows = sorted((r for r in s['rows'] if not r[c.index('absent_since')]), key=lambda r: (r[c.index('n')] or '').lower())
PARTS = 4
n = (len(rows) + PARTS - 1) // PARTS
for p in range(PARTS):
    part = rows[p * n:(p + 1) * n]
    before = [{"proc": "quests.getAllNames", "input": {}}] if p == 0 else []
    before += [{"proc": "quests.get", "input": {"id": r[c.index('id')]}, "persist": "full", "_name": r[c.index('n')]}
               for r in part]
    m = {"_note": f"Quest catalog capture part {p + 1}/{PARTS}: read-only quests.get (persist full) of {len(part)} quests "
                  f"({part[0][c.index('n')]} .. {part[-1][c.index('n')]}), hidden ones included. It audits reward_hunter_items "
                  "/ reward_gathering_items with no id list before the profession chests are flagged huntable and "
                  "gatherable (RUL-2026-10-28-023)."
                  + (" Also quests.getAllNames (row count only)." if p == 0 else "")
                  + " Changes nothing. Generated by push/324_quest_catalog_capture.gen.py; do not hand-edit.",
         "capture": {"before": before}, "items": []}
    out = f'push/324_quest_catalog_capture_{p + 1}.json'
    json.dump(m, open(out, 'w'), indent=1, ensure_ascii=False); open(out, 'a').write('\n')
    print(out, len(before))
