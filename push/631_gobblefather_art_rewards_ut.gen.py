#!/usr/bin/env python3
"""Build push/631_gobblefather_art_rewards_ut.json: push/631 with every @img ref pointed at the director's own
UploadThing instead of a browser Forge image upload, so it runs over the game connector (the push/627_ut route).

    python3 push/631_gobblefather_art_rewards_ut.gen.py

URLs come from state/gobblefather_upload/uploaded.json (the upload of state/gobblefather_upload/upload_list.json),
each sha-checked against push/631's imgSizes and art/gobblefather/. Same srcIds and items as push/631.
"""
import hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SRC = 'push/631_gobblefather_art_rewards.json'
UP = 'state/gobblefather_upload/uploaded.json'
OUT = 'push/631_gobblefather_art_rewards_ut.json'
m = json.load(open(SRC))
up = {v['file']: v for v in json.load(open(UP))['files'].values()}
used = set()


def swap(o):
    if isinstance(o, dict):
        return {k: swap(v) for k, v in o.items()}
    if isinstance(o, list):
        return [swap(v) for v in o]
    if isinstance(o, str) and o.startswith('@img:'):
        fn = o[5:]
        u = up[fn]
        raw = open(f'art/gobblefather/{fn}', 'rb').read()
        assert len(raw) == m['imgSizes'][fn], ('size differs from 631', fn)
        assert hashlib.sha256(raw).hexdigest() == u['sha256'], ('upload does not match art', fn)
        assert u['url'].startswith('https://bbenpyo9uu.ufs.sh/f/'), u['url']
        used.add(fn)
        return u['url']
    return o


items = swap(m['items'])
assert used == set(m['imgSizes']), ('images not all used', set(m['imgSizes']) - used)
out = {
    "_note": "push/631 (The Gobblefather step 3: art + rewards) with its 21 images hosted on the director's own UploadThing, so it runs over the connector. Same srcIds and items as push/631. HIDDEN except the badge and the Night's Testament variant, which have no hidden state. Follow-up over the connector: token edit binding unlockitemvariant.variantId to the variant id from this run's bundle. Generated by push/631_gobblefather_art_rewards_ut.gen.py; do not hand-edit.",
    "dedupNames": m.get('dedupNames', True),
    "items": items,
}
json.dump(out, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} items, {len(used)} images on UploadThing')
