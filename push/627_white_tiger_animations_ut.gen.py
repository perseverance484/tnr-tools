#!/usr/bin/env python3
"""Build push/627_white_tiger_animations_ut: push/627's two hidden asset creates with the image pointed at the director's
own UploadThing instead of a Forge image pack, so it runs over the game connector (the push/624_rengoku_animations_ut
route).

    python3 push/627_white_tiger_animations_ut.gen.py

URLs come from state/recut_upload/uploaded.json (the upload of state/recut_upload/upload_list.json), sha-checked
against push/627's imagePack. Strips are <= 4096 px tall (off-Bunny hosts load native; phones draw taller strips as
black boxes). Same srcIds as push/627, so push/628 and push/629 build from this run's bundle unchanged.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SRC = 'push/627_white_tiger_animations.json'
UP = 'state/recut_upload/uploaded.json'
OUT = 'push/627_white_tiger_animations_ut.json'
m = json.load(open(SRC))
up = json.load(open(UP))['files']
items = []
for it in m['items']:
    fn = it['data']['image'].split(':', 1)[1]
    u = up[it['srcId']]
    assert u['file'] == fn and u['sha256'] == m['imagePack']['files'][fn]['sha256'], ('upload does not match pack', fn)
    assert u['url'].startswith('https://bbenpyo9uu.ufs.sh/f/'), u['url']
    items.append(dict(it, data=dict(it['data'], image=u['url'])))
out = {
    "_note": "push/627 (Fury of The White Tiger gates + tiger, 2 hidden ANIMATION creates, 140 / 102 px, <= 4096 px tall) with the strips hosted on the director's own UploadThing, so it runs over the connector. Same srcIds as push/627: build push/628 and push/629 from this run's bundle. Generated by push/627_white_tiger_animations_ut.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(out, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset creates on UploadThing')
