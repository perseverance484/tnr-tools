#!/usr/bin/env python3
"""Build push/628: unhide the two Fury of The White Tiger animation assets created by push/627 (direct edits).

    python3 push/628_white_tiger_animations_unhide.gen.py <push/627 results bundle>

Battles load only unhidden assets (law 16c). Each asset's data is re-sent as created with hidden: false; the image
is not re-sent (Forge merges the live record). Run before push/629 (the suggestion). Pattern: push/625.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/628_white_tiger_animations_unhide.json'
CREATE = next(p for p in ['push/627_white_tiger_animations.json'] +
              [os.path.join(d, '627_white_tiger_animations.json') for d in
               sorted(os.path.join('archive/spent-manifests', x) for x in os.listdir('archive/spent-manifests'))]
              if os.path.exists(p))
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
idmap = json.load(open(sys.argv[1])).get('idmap', {})
items = []
for it in json.load(open(CREATE))['items']:
    aid = idmap.get(it['srcId'])
    assert aid, f"{it['srcId']} not in the bundle idmap: run push/627 first"
    data = dict(it['data'], hidden=False)
    data.pop('image')
    items.append({"entity": "asset", "slot": "edit", "targetId": aid, "name": it['name'], "data": data})
m = {
    "_note": "Unhides the two Fury of The White Tiger animation assets created by push/627 (gates, tiger): battles load only unhidden assets (law 16c). Run before push/629 (the suggestion). Generated by push/628_white_tiger_animations_unhide.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: unhide ' + ', '.join(i['targetId'] for i in items))
