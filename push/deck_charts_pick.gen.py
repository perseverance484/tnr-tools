#!/usr/bin/env python3
"""Stolen Stores: add the Chart of the Flooded Stores as a fifth pick on the Salvager's live Deck Charts trade.

    python3 push/deck_charts_pick.gen.py   -> push/644: RELEASE ONLY (Friday), not run here

The director, 2026-11-18 18:44 UTC, relayed in this thread: "Why would you need a new trade?" and "Any chart counts".
So there is no new trade: the Flooded Stores chart joins her existing Deck Charts trade (zYhkIQeVGNUMljwev3-ud) as a
pick, and the Watch Log chart order counts that trade whatever is picked (push/stolen_stores_pages.gen.py).

Built from the live read of the trade saved at state/stolen_stores_captures/deck_charts_trade_2026-11-18.json
(updatedAt 2026-11-14T00:06:52Z). The edit sends the whole content block, so the objectives list here is the live one
plus one branch and one win node; nothing else changes. Forge fetch-merges the top level and reads the record back.

Release order: the chart item (push/635, hidden) must be unhidden first, or the pick pays an item players can't see.
Re-read the trade before running; if updatedAt has moved, regenerate from a fresh capture.
Do not hand-edit the output.
"""
import copy
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NANO = re.compile(r"^[A-Za-z0-9_-]{21}$")
CAPTURE = os.path.join(ROOT, "state", "stolen_stores_captures", "deck_charts_trade_2026-11-18.json")
TRADE = "zYhkIQeVGNUMljwev3-ud"
CHART = "FuQzaFNlpyOUGlO5BtjyX"  # Chart of the Flooded Stores (push/635, hidden)
CHART_NAME = "Chart of the Flooded Stores"
LIVE_UPDATED = "2026-11-14T00:06:52.907Z"
OLD_PICK = "She spreads four charts on a flat stone, still damp. \"Deck charts. Pick one.\""
NEW_PICK = "She spreads five charts on a flat stone, still damp. \"Deck charts. Pick one.\""
TOP = ["name", "description", "image", "questType", "questRank", "successDescription", "retryDelay", "attemptDelay",
       "consecutiveObjectives", "hidden", "requiredLevel", "maxLevel", "maxAttempts", "maxCompletes",
       "prerequisiteQuestId", "tierLevel", "requiredVillage", "requiredBloodlineId", "startsAt", "endsAt"]


def build(rec):
    assert rec["id"] == TRADE and rec["updatedAt"] == LIVE_UPDATED, "capture is not the 2026-11-18 read"
    content = copy.deepcopy(rec["content"])
    objs = content["objectives"]
    by = {o["id"]: o for o in objs}
    assert "w_flooded" not in by
    pick = by["d_pick"]
    assert pick["description"] == OLD_PICK
    pick["description"] = NEW_PICK
    assert [b["nextObjectiveId"] for b in pick["nextObjectiveId"]] == ["w_tide", "w_roster", "w_cache", "w_galley"]
    pick["nextObjectiveId"].append({"text": CHART_NAME, "nextObjectiveId": "w_flooded"})
    win = copy.deepcopy(by["w_galley"])
    win["id"] = "w_flooded"
    win["description"] = f"She hands over the {CHART_NAME}."
    assert win["reward_items"][0]["ids"] == ["rztQVUjxTLRpyEPb3yrr6"]
    win["reward_items"] = [{"ids": [CHART], "number": 100, "quantity": 1}]
    objs.insert(objs.index(by["w_galley"]) + 1, win)
    ids = {o["id"] for o in objs}
    for o in objs:
        nx = o.get("nextObjectiveId")
        for n in ([b["nextObjectiveId"] for b in nx] if isinstance(nx, list) else ([nx] if nx else [])):
            assert n in ids, (o["id"], n)
        assert "—" not in o["description"] and "–" not in o["description"], o["id"]
    data = {k: rec[k] for k in TOP if k in rec}
    data["content"] = content
    assert data["hidden"] is False  # live record stays live; this only adds a pick
    return data


def main():
    assert NANO.match(CHART) and NANO.match(TRADE)
    rec = json.load(open(CAPTURE))["record"]
    data = build(rec)
    m = {"_note": "push/644, RELEASE ONLY (Friday Nov 20, with the director's go): add the Chart of the Flooded Stores "
                  "as a fifth pick on the Salvager's Deck Charts trade (live) and say five charts. Unhide the chart "
                  "item first. Re-read the trade before running. Generated by push/deck_charts_pick.gen.py; do not "
                  "hand-edit.",
         "dedupNames": True, "_release_only": True,
         "items": [{"entity": "quest", "slot": "edit", "targetId": TRADE, "phase": 1,
                    "name": "The Salvager's Trade: Deck Charts: + Chart of the Flooded Stores", "data": data}]}
    path = os.path.join(ROOT, "push", "644_deck_charts_flooded_pick.json")
    with open(path, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(os.path.relpath(path, ROOT), 1, "item")


if __name__ == "__main__":
    main()
