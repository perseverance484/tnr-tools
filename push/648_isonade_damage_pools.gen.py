#!/usr/bin/env python3
"""Job 648, HIDDEN: Isonade's brine pools deal lingering damage instead of draining (the director, Nov 18).

Why: the live game locks every other action of a fighter that shares a tag with the action just used, for the rounds
the shared-cooldown table gives that tag (misc.getSharedCooldowns, read 2026-11-18: drain 4 rounds; damage is not in
the table). All six slam lands carried a drain, so landing Slam I locked Slam II for 4 rounds: the Slam II warning
lapsed in the hidden test and Isonade fell through to its next rule. The director's call (2026-11-18): "Let's just do
a different effect for the pools? Like damage".

What changes, on the six slam lands only (Slam I/II/III and Slam I/II/III, Bitten):
  - the drain tag goes; a ground damage tag with the same rounds takes its place (POOL_POWER, formula). Live engine:
    ground damage converts to an instant hit on whoever stands on the tile at every action, the way the drain did.
  - the land's own hit drops by POOL_POWER, because the pool tag also hits on the landing action; a land still totals
    560 on anyone caught in the rows.
  - descriptions say the brine hits instead of drains.
The visual, markers, targeting, AP and animations stay as the live records have them. Base: push/645's output, which
the live records match field for field (spot-read 2026-11-18 ~21:50Z, after job 646 changed only one battle text,
which this job does not send).

Tuning: harness/isonade.ts (poolKind "damage") on the live-lock engine; numbers in
/mnt/project-files/tnr/isonade_build/v3 and state/flooded_stores_build/isonade_v3_results.md.

Law 18: phase 10 takes the six off Isonade, phase 20 edits them, phase 30 puts the full kit back.

Run: python3 push/648_isonade_damage_pools.gen.py -> push/648_isonade_damage_pools.json. Do not hand-edit.
"""
import copy
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, "push", "645_isonade_warnings_tuning.json")
OUT = os.path.join(ROOT, "push", "648_isonade_damage_pools.json")

ISONADE = "K_lwNvMPJLMsn1sUGXqZm"
KIT = ["5HnvskWG20YUlJciX8gvA", "5tqEkTPERX3lkyon_LOKp", "6w0MWbsSIB2j02MADv1nK", "7wxzJedprikQuUr7nSDrS",
       "8cKI86O81cXAMaFS9qqOo", "9QsiAey2OR8hB3UTNhRGh", "EMD7BPKzoOhGB-aOb_Rf2", "gUO8uQLCC5AjvfOuETYlN",
       "hcqL90RPenl24EY73YJr4", "Kaebmb1nzNi3sMadz0W12", "nngO-MnDwNRUEDdrPw6sI", "Qo04-DUTH_cSbnLmPhLEy",
       "SbfiGJPGdjVmLZcAWQrKl", "SWTtkWhjBsHKAu-OI-CQj", "VCaNcj9kGc8kaFk6rQdpR", "XY3PFkXuY_bHQGmg33hz1",
       "yFClnbV7Yr4WpvmcrDEMi"]  # live profile after job 646
SLAM = ["5tqEkTPERX3lkyon_LOKp", "8cKI86O81cXAMaFS9qqOo", "XY3PFkXuY_bHQGmg33hz1"]
BITTEN = ["5HnvskWG20YUlJciX8gvA", "7wxzJedprikQuUr7nSDrS", "gUO8uQLCC5AjvfOuETYlN"]

SLAM_TOTAL = 560
POOL_POWER = int(os.environ.get("POOL_POWER", "200"))
POOL_DESC = "Brine pool: hits anyone standing in it with every action"


def one(effects, t):
    hits = [e for e in effects if e["type"] == t]
    assert len(hits) == 1, (t, len(hits))
    return hits[0]


def main():
    base = {it["targetId"]: it for it in json.load(open(BASE))["items"]
            if it["entity"] == "jutsu" and it["phase"] == 20}
    items = [{"entity": "ai", "slot": "edit", "targetId": ISONADE, "phase": 10,
              "name": "Isonade: six slam lands off (law 18)", "data": {"jutsus": [j for j in KIT if j not in SLAM + BITTEN]}}]
    for jid in SLAM + BITTEN:
        it = base[jid]
        data = copy.deepcopy(it["data"])
        fx = data["effects"]
        dmg, drain = one(fx, "damage"), one(fx, "drain")
        assert dmg["power"] == SLAM_TOTAL and dmg["rounds"] == 0 and drain["power"] == 12 and drain["rounds"] == 3
        dmg["power"] = SLAM_TOTAL - POOL_POWER
        pool = copy.deepcopy(dmg)
        pool.update({"power": POOL_POWER, "rounds": drain["rounds"], "description": POOL_DESC, "appearAnimation": ""})
        fx[fx.index(drain)] = pool
        data["description"] = data["description"].replace("flood them with brine for", "flood them with brine that hits for")
        data["description"] = data["description"].replace("the brine lasts", "the brine hits for")
        assert "drain" not in json.dumps(fx)
        name = it["name"].split(":")[0]
        items.append({"entity": "jutsu", "slot": "edit", "targetId": jid, "phase": 20,
                      "name": f"{name}: brine pool deals damage (no drain)", "data": data})
    items.append({"entity": "ai", "slot": "edit", "targetId": ISONADE, "phase": 30,
                  "name": "Isonade: kit back (law 18)", "data": {"jutsus": KIT}})
    m = {"_note": (f"push/648, HIDDEN: Isonade's brine pools deal damage (power {POOL_POWER}, 3 rounds) instead of a 12% "
                   f"drain, so the slams no longer lock each other (live drain shared cooldown 4). Lands still total "
                   f"{SLAM_TOTAL}. Law 18 in phases 10/30. Generated by push/648_isonade_damage_pools.gen.py; do not hand-edit."),
         "items": items}
    with open(OUT, "w") as f:
        json.dump(m, f, separators=(",", ":"))
    print(f"wrote {OUT}: {len(items)} items, {os.path.getsize(OUT)} bytes, pool power {POOL_POWER}")


if __name__ == "__main__":
    main()
