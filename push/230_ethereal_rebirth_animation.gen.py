#!/usr/bin/env python3
"""Build push/230: create the Ethereal Rebirth cast animation asset (direct; suggest mode cannot create).

    python3 push/230_ethereal_rebirth_animation.gen.py

The strip: art/jutsu_icons/ethereal_rebirth/animation/exports/anim_ethereal_rebirth_v1.webp (build_strip.py v1, director:
"Looks pretty good", 2026-10-24): 40 square frames of 128 px stacked vertically, 60 ms per frame (2.4 s). Gold and blue
soul-light ribbons pour out of the user's chest and wrap around their avatar, one lashes out, and they dissolve into
flecks (docs/handoffs/ETHEREAL_REBIRTH_ANIMATION_ART_REQUEST.md, docs/design/ethereal_rebirth_animation/V1_NOTES.md).
A new asset (nothing is shared or overwritten). It is created hidden, because the gates require hidden: true on every
create (law 16b, lint L13). Battles load only assets with hidden = false (theninjarpg misc.ts fetchGameAssets, used by
layout/Combat.tsx), so a hidden animation never plays (director, 2026-10-24; law 16c corrected): push/232 unhides it,
built from this run's results bundle (validate.py lint L01 needs a literal targetId, so it cannot ride in this manifest). push/231 then points Ethereal Rebirth's absorb effect at the new id from this run's results bundle
(idmap key er_anim_soul_ribbons), with the new icon and text, as one suggestion.
The image pack is pinned at HEAD, so the strip must be committed.
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
STRIP = 'art/jutsu_icons/ethereal_rebirth/animation/exports/anim_ethereal_rebirth_v1.webp'
OUT = 'push/230_ethereal_rebirth_animation.json'
FRAMES, SPEED = 40, 60
NAME = 'Ethereal Rebirth - Soul Ribbons'

from PIL import Image
im = Image.open(STRIP)
w, h = im.size
assert w == 128 and h == 128 * FRAMES, (w, h)
b = open(STRIP, 'rb').read()
assert len(b) < 460800, len(b)
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
blob = subprocess.check_output(['git', 'show', f'{ref}:{STRIP}'])
assert blob == b, 'the committed strip differs from the file on disk: commit it first'
fn = os.path.basename(STRIP)
m = {
    "_note": "Creates the Ethereal Rebirth cast animation asset: gold and blue soul-light ribbons pour out of the user's chest, wrap around their avatar (far side hidden behind the token, near side in front), one lashes out towards the enemy, and they dissolve into flecks (40 frames x 60 ms = 2.4 s). Direct create, hidden (law 16b gate); push/232 unhides it (battles load only unhidden assets; law 16c corrected 2026-10-24). The jutsu is not touched here: push/231 is built from this run's results bundle (idmap er_anim_soul_ribbons) to set the absorb effect's appearAnimation, with the new icon and text, as one suggestion. Generated by push/230_ethereal_rebirth_animation.gen.py; do not hand-edit.",
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": STRIP, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "asset", "slot": "create", "srcId": "er_anim_soul_ribbons", "name": NAME,
        "data": {
            "name": NAME,
            "type": "ANIMATION",
            "image": "@img:" + fn,
            "folder": "jutsuanimations",
            "frames": FRAMES,
            "speed": SPEED,
            "hidden": True,
            "onInitialBattleField": False,
            "licenseDetails": "TNR",
        },
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 asset create, {FRAMES} frames x {SPEED} ms, {len(b)} bytes, pack @ {ref[:7]}')
