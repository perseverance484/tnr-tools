#!/usr/bin/env python3
"""Skyglass chart cards for the five pre-existing HIDDEN charts (push/368; RUL-2026-10-31-074, director 2026-10-31).

    python3 push/skyglass_chart_text.gen.py       # writes push/368_skyglass_chart_text.json

The four Rare charts (Buried Cache, Drowned Foundry, Quarantined Archive, Captain's Watch) and the Lastlight Lantern
are hidden live records (director 2026-10-31: "Players cant see them, theyre hidden"), so their approved card text and
tier can go now instead of waiting for go-live. This sends ONLY `description` and `rarity` (no `hidden`, so each stays
hidden), taken verbatim from the same edits go-live push/339 builds (push/skyglass_items.gen.py via
push/skyglass_update.gen.py); 339 re-sends the same values, so running both is harmless. Do not hand-edit the output.
"""
import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NUM = 368
OUT = os.path.join(ROOT, "push", f"{NUM}_skyglass_chart_text.json")
CHARTS = ["Chart of the Buried Cache", "Chart of the Drowned Foundry", "Chart of the Quarantined Archive",
          "Chart of the Captain's Watch", "Lastlight Lantern"]

spec = importlib.util.spec_from_file_location("upd", os.path.join(ROOT, "push", "skyglass_update.gen.py"))
U = importlib.util.module_from_spec(spec)
spec.loader.exec_module(U)


def main():
    _, edits = U.split_items(U.IT.all_items()["items"])
    want = {U.IT.LIVE[n]: n for n in CHARTS}
    items = []
    for e in edits:
        if e["targetId"] in want:
            d = {k: e["data"][k] for k in ("description", "rarity")}
            assert not any(isinstance(v, str) and v.startswith("@") for v in d.values()), e["targetId"]
            items.append({"entity": "item", "slot": "edit", "name": f"{want[e['targetId']]}: card text (RUL-2026-10-31-074)",
                          "targetId": e["targetId"], "data": d})
    assert len(items) == len(CHARTS), [i["name"] for i in items]
    m = {"_note": (f"push/{NUM}: the approved card text and tier for the five pre-existing hidden charts (four Rare charts "
                   "and the Lastlight Lantern). description and rarity only; records stay hidden. Go-live 339 re-sends the "
                   "same values. Generated by push/skyglass_chart_text.gen.py; do not hand-edit."),
         "dedupNames": True, "items": items}
    with open(OUT, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"push/{NUM}_skyglass_chart_text.json: {len(items)} items")


if __name__ == "__main__":
    main()
