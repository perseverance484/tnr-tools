#!/usr/bin/env python3
"""Generate push/350: a hidden achievement probe (RUL-2026-10-31, Walked Every Deck feasibility).

    python3 push/achievement_probe.gen.py

Question: does an UNSTARTED achievement keep complete_specific_quest progress across saves? Reading
theninjarpg@3314d122 libs/quest.ts filterQuestTrackersForDbPersist (~215-260) suggests it does not: trackers of
mock achievements (no QuestHistory row yet) are dropped on persist unless a goal is a location, a CompletionTasks /
bloodline_collection goal that is done, or a CombatActivityTasks counter. complete_specific_quest is none of those.

Creates three HIDDEN records (staff with canPlayHiddenQuests can play them; hidden achievements are mocked for
canChangeContent roles, libs/quest.ts mockAchievementHistoryEntries ~2181):
  - "Probe Deck A" and "Probe Deck B": one dialog, one click, win. No battle, no reward.
  - "Probe: Both Decks": an achievement with two complete_specific_quest goals (A once, B once), any order
    (consecutiveObjectives false, as Walked Every Deck would need), no reward.
Shape copied from the live achievement "Pizza Delivery Reward" (elopwNBvN0rbuCfzTOo5E, harvest
tnr_results_1791233210169.json). Zero live requests. Delete or keep hidden after the test. Do not hand-edit the output.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = "https://uploadthing.b-cdn.net/f/630cf6e7-c152-4dea-a3ff-821de76d7f5a_default.webp"
BG = "https://ui0arpl8sm.ufs.sh/f/Hzww9EQvYURJyX6gwPukVH2MI5Lo4ehEfAXvZdcmtWqPg7rp"  # cache_site, live


def probe_quest(key, label):
    return {"entity": "quest", "slot": "create", "srcId": f"p350_{key}", "phase": 1, "name": label,
            "data": {"name": label, "description": f"Staff test quest for the achievement probe. Click once to finish.",
                     "image": IMG, "questType": "event", "questRank": "D",
                     "successDescription": "Probe step done.", "retryDelay": "none", "attemptDelay": "none",
                     "consecutiveObjectives": True, "hidden": True, "requiredLevel": 1, "maxLevel": 100,
                     "maxAttempts": 1, "maxCompletes": 1, "prerequisiteQuestId": None, "tierLevel": None,
                     "requiredVillage": None, "requiredBloodlineId": None, "startsAt": None, "endsAt": None,
                     "content": {"objectives": [
                         {"id": "d_go", "task": "dialog", "description": f"{label}: click to finish.",
                          "sceneBackground": BG, "sceneCharacters": [],
                          "nextObjectiveId": [{"text": "Finish", "nextObjectiveId": "w_done"}]},
                         {"id": "w_done", "task": "win_quest", "description": "Done.",
                          "sceneBackground": BG, "sceneCharacters": []}],
                         "sceneBackground": BG, "sceneCharacters": [], "entryItems": [], "reward": {}}}}


def goal(gid, key):
    return {"id": gid, "task": "complete_specific_quest", "value": 1, "description": "",
            "completeQuestIds": [f"@quest:p350_{key}"], "sceneBackground": "", "sceneCharacters": []}


ach = {"entity": "quest", "slot": "create", "srcId": "p350_achievement", "phase": 2, "name": "Probe: Both Decks",
       "data": {"name": "Probe: Both Decks", "description": "Staff probe: complete Probe Deck A, then Probe Deck B.",
                "image": IMG, "questType": "achievement", "questRank": "D",
                "successDescription": "Probe passed: progress survived.", "consecutiveObjectives": True,  # Forge L03 requires it; the persistence question is the same (A then B)
                "hidden": True, "requiredLevel": 1, "maxLevel": 100, "prerequisiteQuestId": None, "tierLevel": None,
                "content": {"objectives": [goal("g_a", "a"), goal("g_b", "b")],
                            "sceneBackground": "", "sceneCharacters": [], "reward": {}}}}

out = {"_note": ("push/350 achievement probe (hidden). Run, then on a staff character: (1) complete Probe Deck A; "
                 "(2) reload the page (and ideally log out and back in) so the character is saved and re-read; "
                 "(3) open Achievements and check whether 'Probe: Both Decks' shows goal A done; (4) complete Probe Deck B "
                 "and check whether the achievement completes. A done after reload = progress persists (Walked Every Deck "
                 "can ship as designed); A not done = the persistence bug is real. Generated by push/achievement_probe.gen.py; "
                 "do not hand-edit."),
       "items": [probe_quest("a", "Probe Deck A"), probe_quest("b", "Probe Deck B"), ach]}
path = os.path.join(ROOT, "push/350_achievement_probe.json")
with open(path, "w", encoding="utf-8") as fh:
    json.dump(out, fh, indent=1, ensure_ascii=False); fh.write("\n")
print("push/350_achievement_probe.json: 3 quest creates (hidden)")
