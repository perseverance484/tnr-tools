#!/usr/bin/env python3
"""Mother of Echoes test art (push/467): make the uber's art visible for the director's tester WITHOUT publishing the
real fight. Zero live requests.

    python3 push/mother_of_echoes_test_art.gen.py --bundles <440, 461-464 bundles> --economy <417 bundle> \\
        --from <466 bundle>
        -> push/467_mother_of_echoes_test_art.json

Phase 10: the FX assets push/466 created hidden are unhidden (law 16c: battles load only unhidden assets). Phase 20: the
practice quest (push/469, quest YDmKO6fp2vBRnTf7fHWQZ) re-sent whole (quest edits do not fetch-merge) with its icon
and the three act scenes. The real quest (push/464) stays hidden: the publish is a later, separate job, built after
the pass-6 tuning job. Scene assets need no unhide (gameAsset.getSceneAssets does not filter hidden). The avatars are
already on the boss AIs since 466.

Built from push/mother_of_echoes.gen.py (unhide_items, asset_ids, pack) and push/mother_of_echoes_practice.gen.py
(practice_data), so the records cannot drift from their sources. Do not hand-edit the output.
"""
import argparse
import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name, path):
    s = importlib.util.spec_from_file_location(name, os.path.join(ROOT, "push", path))
    m = importlib.util.module_from_spec(s)
    s.loader.exec_module(m)
    return m


moe = load("moe", "mother_of_echoes.gen.py")
practice = load("practice", "mother_of_echoes_practice.gen.py")

NUM = 467
PRACTICE_QUEST = "YDmKO6fp2vBRnTf7fHWQZ"  # push/469 run: harvests/inbox/tnr_results_1793840873454.json (VERIFIED)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bundles", nargs="*", default=[], help="results bundles of 440 and 461-464")
    ap.add_argument("--economy", help="push/417 results bundle")
    ap.add_argument("--from", dest="frm", required=True, help="push/466 results bundle (the asset ids)")
    a = ap.parse_args()
    b = moe.Build(moe.load_spec())
    ids = moe.created(a.bundles, moe.PFX)
    econ = moe.created([a.economy], moe.ECON)
    moe.need(econ, [moe.ECON + k for k in ("keel", "crown", "tide", "ledger", *moe.TOKEN_PCT)], "--economy")
    moe.need(ids, [moe.sid(t) for t in b.bosses], "test art")
    aids = moe.asset_ids(a.frm)
    unhide = moe.unhide_items(aids)
    d = practice.practice_data(b, ids, econ, aids)
    q = [{"entity": "quest", "slot": "edit", "targetId": PRACTICE_QUEST, "name": f"{practice.NAME}: act scenes and icon",
          "data": d}]
    items = moe.phased([(10, unhide), (20, q)])
    m = {"_note": (f"push/{NUM}: Mother of Echoes test art (director, 2026-11-04: \"Just unhide the animations and "
                   f"avatars now\"). Phase 10: the {len(unhide)} FX assets from push/466 unhidden (literal ids from its "
                   "results bundle). Phase 20: the practice quest (push/469) re-sent whole with its icon and the three "
                   "act scenes; it stays hidden. The real quest stays hidden; its publish is a later job. Generated by "
                   "push/mother_of_echoes_test_art.gen.py; do not hand-edit.")}
    m.update(moe.pack([moe.QUEST_ICON]))
    m["items"] = items
    p = os.path.join(ROOT, "push", f"{NUM}_mother_of_echoes_test_art.json")
    with open(p, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"{os.path.relpath(p, ROOT)}: {len(items)} items")


if __name__ == "__main__":
    main()
