"""AS RUN 2026-11-18 02:33 UTC (job 627-mwlibblz), kept as a record: built from push/627 BEFORE the <= 4096 px re-cut
(67c2970), so these strips are 234 / 252 px wide and 6786 / 10080 px tall. Do not rerun; the current route is
push/627_white_tiger_animations_ut.gen.py.

Build push/627_white_tiger_animations_ut_tall: push/627's two hidden asset creates with the image pointed at the director's own
UploadThing instead of a Forge image pack, so it runs over the game connector (mcp_run; no browser upload).

    python3 push/627_white_tiger_animations_ut.gen.py

the director 2026-11-18: "Use uploadthing if needed" (the Rengoku route, push/624_rengoku_animations_ut). Files uploaded by the whitetiger-uploadthing workflow
on the task branch; URLs in state/whitetiger_upload/uploaded.json, sha-checked against push/627's imagePack. Same srcIds,
so push/628 and push/629 build from this run's bundle unchanged. Off-Bunny hosts skip the game's ?width= rendition and
its upload moderation (director's call). Do not hand-edit.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SRC = 'push/627_white_tiger_animations.json'
UP = 'state/whitetiger_upload/uploaded.json'
OUT = 'push/627_white_tiger_animations_ut_tall.json'
m = json.load(open(SRC))
up = json.load(open(UP))['files']
items = []
for it in m['items']:
    fn = it['data']['image'].split(':', 1)[1]
    u = up[it['srcId']]
    assert u['file'] == fn and u['sha256'] == m['imagePack']['files'][fn]['sha256'], ('upload does not match pack', fn)
    assert u['url'].startswith('https://bbenpyo9uu.ufs.sh/f/'), u['url']
    items.append(dict(it, data=dict(it['data'], image=u['url'])))
out = {
    "_note": "push/627 (Fury of The White Tiger gates + tiger, 2 hidden ANIMATION creates, 29 x 70 ms / 40 x 80 ms) with the strips hosted on the director's own UploadThing (the director 2026-11-18: 'Use uploadthing if needed'), so it runs over the connector. Same srcIds as push/627: build push/628 and push/629 from this run's bundle. Generated by push/627_white_tiger_animations_ut.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(out, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset creates')
