#!/usr/bin/env python3
"""Build push/238: create the three Celestial Dew animation assets (direct; suggest mode cannot create).

    python3 push/238_celestial_dew_animations.gen.py

Strips: art/jutsu_icons/celestial_dew/animation/exports/anim_celestial_dew_{appear,loop,break}_v2.webp
(docs/design/celestial_dew_animation/PROJECT.md section 7), 112 px frames at 36 ms. All on the shield effect: its
appearAnimation (the moon, the drop, the splash, the ripples and the ward forming, on one clock), staticAnimation (loop)
and disappearAnimation (break). The heal's appear is cleared in the suggestion. Created hidden (law 16b gate); from this run's results bundle a follow-up unhides them (law 16c) and the jutsu
suggestion points the effects at them. The image pack is pinned at HEAD: commit the strips first.
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
E = 'art/jutsu_icons/celestial_dew/animation/exports/'
OUT = 'push/238_celestial_dew_animations.json'
ASSETS = [  # srcId, name, file, frames
    ('cd_anim_appear', 'Celestial Dew - Falling Dew', 'anim_celestial_dew_appear_v2.webp', 66),
    ('cd_anim_loop', 'Celestial Dew - Ward', 'anim_celestial_dew_loop_v2.webp', 100),
    ('cd_anim_break', 'Celestial Dew - Ward Breaking', 'anim_celestial_dew_break_v2.webp', 30),
]
from PIL import Image
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
pack, sizes, items = {}, {}, []
for src, name, fn, frames in ASSETS:
    path = E + fn
    w, h = Image.open(path).size
    assert w == 112 and h == 112 * frames, (fn, w, h)
    b = open(path, 'rb').read()
    assert len(b) < 460800, (fn, len(b))
    assert subprocess.check_output(['git', 'show', f'{ref}:{path}']) == b, 'commit the strips first'
    pack[fn] = {"path": path, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
    sizes[fn] = len(b)
    items.append({"entity": "asset", "slot": "create", "srcId": src, "name": name,
                  "data": {"name": name, "type": "ANIMATION", "image": "@img:" + fn, "folder": "jutsuanimations",
                           "frames": frames, "speed": 36, "hidden": True, "onInitialBattleField": False,
                           "licenseDetails": "TNR"}})
m = {
    "_note": "Creates the three Celestial Dew animation assets, all for the shield effect (appear: the moon, the drop, the splash, the ripples and the ward forming; loop: the ward while the shield lasts; break: the ward shattering). 112 px frames at 36 ms. Direct creates, hidden (law 16b gate); a follow-up built from this run's bundle unhides them (law 16c) and the jutsu suggestion sets the shield's appear/static/disappear and clears the heal's appear. Generated by push/238_celestial_dew_animations.gen.py; do not hand-edit.",
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": pack},
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset creates, pack @ {ref[:7]}')
