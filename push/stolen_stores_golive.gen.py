#!/usr/bin/env python3
"""Stolen Stores go-live master (Friday 2026-11-20 release), RELEASE ONLY: not run until the director's go.

    python3 push/stolen_stores_golive.gen.py   -> push/673_stolen_stores_golive_master.json

One Forge manifest for every Forge-able go-live step, in release order, built from the release-only manifests
already generated (never retyped):

  phase 1   unhide the Chart of the Flooded Stores item and Isonade's nine animation assets (push/631, hidden)
  phase 2   unhide The Flooded Stores run and Short Rations (push/639)
  phase 3   Deck Charts gets the Flooded Stores pick (push/644)
  phase 4   both Watch Log pages (push/643)
  phase 5   new Wreck Sighted copies unhidden, last weekend's hidden, the Fire's topics (push/650)

Then, outside Forge, one direct connector call: push/639_salvager_pool_upsert.json (re-read the placement first,
read it back after). The sector 210 map publish is a separate yes and is not in here.

Stays hidden, on purpose: Isonade's Old Hull (AI-only armor), every AI record (AI rows have no hidden column;
law 16b), the AI-only jutsu (as on every earlier Skyglass boss), Isonade Test, the 81+ staff test page, the grant
test quest.

643, 644 and 650 carry whole records from earlier reads: regenerate each from a fresh read before the sitting,
then regenerate this file. Do not hand-edit the output.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHART_ITEM = "FuQzaFNlpyOUGlO5BtjyX"
RUN = "-_1MdlGp-gxdiWKb6Bf3V"
ASSETS = {  # push/631 bundle harvests/inbox/tnr_results_1795025876815.json; hidden on read 2026-11-20
    "xKgBBZRVs3gxXVCh-zcqD": "Isonade - Body Water (loop)",
    "izjz7PL-zMiOpIjInnV2w": "Isonade - Slam (hit)",
    "BexP4ZKBGwv4gjE3yGYLM": "Isonade - Brine Pool (loop)",
    "isRdjcXFqu3n2gFlWWHmK": "Isonade - Arm Burst (appear)",
    "vLnK4950XUPvsbRVyfHLl": "Isonade - Arm Lash (hit)",
    "5vyAK-S4YUq6iaJic-MzM": "Isonade - Black Water (hit)",
    "PKF3LhQ9hBFqqUlsw4A0_": "Isonade - Open Eye (loop)",
    "Xba6Lf1BgwZfF__uxH0Q1": "Isonade - Bite of the Ship (appear)",
    "quxGkGewzASdB9QriUEbn": "Isonade - Rot Drip (loop)",
}
SOURCES = [  # (phase, manifest)
    (2, "push/639_short_rations_release.json"),
    (3, "push/644_deck_charts_flooded_pick.json"),
    (4, "push/643_stolen_stores_pages_release.json"),
    (5, "push/650_wreck_sighted_stolen_stores_release.json"),
]


def main():
    items = [{"entity": "asset", "slot": "edit", "targetId": aid, "phase": 1, "name": name + ": unhide",
              "data": {"hidden": False}} for aid, name in ASSETS.items()]
    items.append({"entity": "item", "slot": "edit", "targetId": CHART_ITEM, "phase": 1,
                  "name": "Chart of the Flooded Stores: unhide", "data": {"hidden": False}})
    items.append({"entity": "quest", "slot": "edit", "targetId": RUN, "phase": 2,
                  "name": "The Flooded Stores: unhide", "data": {"hidden": False}})
    for phase, path in SOURCES:
        src = json.load(open(os.path.join(ROOT, path)))
        base = min(i["phase"] for i in src["items"])
        for it in src["items"]:
            it = dict(it)
            # keep each source's own order inside its phase band
            it["phase"] = phase * 100 + (it["phase"] - base)
            it["name"] = f"[{os.path.basename(path)[:3]}] " + it["name"]
            items.append(it)
    for it in items:
        if it["phase"] < 100:
            it["phase"] *= 100
    items.sort(key=lambda i: i["phase"])  # stable: each source keeps its own order
    targets = [i["targetId"] for i in items]
    assert len(targets) == len(set(targets)), "a record is touched twice"
    out = os.path.join(ROOT, "push", "673_stolen_stores_golive_master.json")
    note = ("push/673, RELEASE ONLY (Friday Nov 20, with the director's go): the Stolen Stores go-live master. "
            "Unhides the chart item, Isonade's 9 animations, The Flooded Stores and Short Rations; then 644 (Deck "
            "Charts pick), 643 (both Watch Log pages), 650 (new Wreck Sighted copies live, last weekend's hidden, "
            "the Fire's topics). After it: push/639_salvager_pool_upsert.json as a direct call (re-read first). Map "
            "publish is separate. Re-read and regenerate 643, 644 and 650 before running. Generated by "
            "push/stolen_stores_golive.gen.py; do not hand-edit.")
    json.dump({"_note": note, "items": items}, open(out, "w"), indent=1, ensure_ascii=False)
    print("wrote", out, len(items), "items")


if __name__ == "__main__":
    main()
