#!/usr/bin/env python3
"""Generate push/126-128: Crimson Impact's new icon through the review desk without severing Ravena
Bloodsilk's combat link (laws 18, 60). Director's choice: suggest it, Ravena waits. Do not hand-edit.

  126  write mode:   unequip Crimson Impact from Ravena Bloodsilk (her kit minus that one jutsu).
  127  suggest mode: Crimson Impact `image` -> the new icon. Run only after 126 is DONE.
  128  write mode:   re-equip Ravena's exact kit. Run only after the 127 suggestion is APPLIED
                     (Check suggestions), or after it is rejected, so she is never left without it.

Before-image: push/119 read-back (harvests/inbox/tnr_results_1792361116796.json, 2026-10-18), the
latest profile.getAi of Ravena on record. updateAi keeps the rows it is sent and adds a new
equipped row for a jutsu it re-adds, so her one unequipped row (tRwJPl...) stays as it is
(push/111 probe and its read-back).

  python3 push/126_crimson_impact_icon.gen.py [<image pack ref>]
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEFORE = ROOT / "harvests/inbox/tnr_results_1792361116796.json"
RAVENA = "Vg5Tqp6mBvOJsm5zPMpdv"
CI = "fKEHVLvvj6q_b4l_X_k4k"
ICON = "art/style_refs/jutsu_icons/bee/icon_bee_crimson_impact_v1.webp"
KITS = json.loads((ROOT / "docs/design/bloodright/balance/kits_from_reference_captures.json").read_text())


def write(n, slug, manifest):
    p = ROOT / f"push/{n}_{slug}.json"
    p.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    return p


def main():
    ai = next(c["data"] for c in json.loads(BEFORE.read_text())["captures"]
              if c.get("proc") == "profile.getAi" and c.get("ok") and c["data"]["userId"] == RAVENA)
    kit = [r["jutsuId"] for r in ai["jutsus"]]
    if CI not in kit:
        raise SystemExit("Ravena's recorded kit does not hold Crimson Impact")
    ci = next(j for j in KITS["blood_enchanted_eyes"]["jutsu"] if j["id"] == CI)
    name = ai["username"].strip()

    write(126, "crimson_impact_unequip", {
        "_note": f"Step 1 of 3 (push/126-128). Unequip Crimson Impact from {name} so the icon suggestion in push/127 "
                 "can be approved without severing her combat link (laws 18, 60). Generated by "
                 "push/126_crimson_impact_icon.gen.py; do not hand-edit. Operator-run only.",
        "items": [{"entity": "ai", "slot": "edit", "targetId": RAVENA,
                   "name": f"{name}: unequip Crimson Impact before its icon edit (law 60)",
                   "data": {"jutsus": [j for j in kit if j != CI]}}],
    })

    logical = Path(ICON).name
    p = write(127, "crimson_impact_icon_suggestion", {
        "_note": "Step 2 of 3 (push/126-128). Run only after push/126 is DONE. Sends Crimson Impact's new icon to the "
                 "content review desk; only `image` changes. Generated by push/126_crimson_impact_icon.gen.py; "
                 "do not hand-edit. Operator-run only.",
        "mode": "suggest",
        "suggestion": {"category": "VISUAL", "title": "Jutsu icon refresh",
                       "rationale": ("New Blood-Enchanted Eyes icon: blood tendrils erupting from a single point of impact, "
                                     "matching the violent rending strike that siphons vitality from the damage it deals. "
                                     f"Note for the reviewer: {name} has this jutsu unequipped until the suggestion is "
                                     "decided, and is re-equipped straight after.")},
        "imgSizes": {logical: (ROOT / ICON).stat().st_size},
        "items": [{"entity": "jutsu", "slot": "edit", "name": "Crimson Impact", "targetId": CI,
                   "data": {"image": f"@img:{logical}", "injectableInBattle": ci["injectableInBattle"]}}],
    })
    ref = sys.argv[1] if len(sys.argv) > 1 else "HEAD"
    subprocess.run(["node", str(ROOT / "forge/tools/make_image_pack.mjs"), str(p), "--map", f"{logical}={ICON}",
                    "--ref", ref, "--write"], check=True)

    write(128, "crimson_impact_reequip", {
        "_note": f"Step 3 of 3 (push/126-128). Run only after the push/127 suggestion is APPLIED or REJECTED (Check "
                 f"suggestions). Re-equips {name}'s exact kit in its original order (law 60). Generated by "
                 "push/126_crimson_impact_icon.gen.py; do not hand-edit. Operator-run only.",
        "items": [{"entity": "ai", "slot": "edit", "targetId": RAVENA,
                   "name": f"{name}: re-equip Crimson Impact after its icon edit (law 60)",
                   "data": {"jutsus": kit}}],
    })


if __name__ == "__main__":
    main()
