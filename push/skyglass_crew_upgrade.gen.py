#!/usr/bin/env python3
"""Generate push/361 (the live Skyglass crew upgraded in place for the endgame Wreck) and push/367 (kit off, law 18).

    python3 push/skyglass_crew_upgrade.gen.py              # 361_skyglass_crew_upgrade.json: 9 AI edits (kit, rules, tuning)
    python3 push/skyglass_crew_upgrade.gen.py --unequip    # 367_skyglass_crew_unequip.json: 9 AI edits, jutsus [] (law 18)

RUL-2026-10-31-067 item 1: the base version of each crew member is the LIVE record, tuned for the endgame Wreck (no
Wreck copies). Source: state/skyglass_build/build_spec.json (provenance in its README):
  - kit and ordered rules: `sharedKits[<live name>]` (one shared jutsu set, SKYGLASS_BOSS_FIGHTS.md section 5);
  - tuning: `endgame.ais[]` (level, rank, statsMultiplier, poolsMultiplier, the six stats, innate effect rows).
Masteries are the captured live row's (push/249, harvests/inbox/tnr_results_1792900120886.json) at the same scale as
the stats (stats are ratio weights, law 15), so the server's scaleUserStats lands where the harness did. Items are
re-sent as captured (law 69 {ids, number}); avatar and username are not sent (they stay live).

Rules: includeDefaultRules false; the fallback fix (RUL-2026-10-30-060 item 7) ends every free-pick chain on the named
basic attack (`basicAttack`, accepted by Forge 0.12.3 and validate.py, RUL-2026-10-31-071 item 1). The generator
refuses: more than 20 rules (AI_PROFILE_MAX_RULES), a use_highest_power_* / use_random_jutsu / use_combo_action rule,
a rule firing a jutsu outside the kit, or a pool-jutsu distance gate that is not range+1 (law 40, Forge kitProblems).
Library jutsu by literal id from push/342's bundle (law 17).

Law 18/60: an AI edit that equips a jutsu must come AFTER every pending edit of that jutsu. 361 edits no jutsu. Any
LATER edit of a library jutsu these records hold (the visual-asset push's animations; any text or tuning edit) runs
as: 367 (kit off) -> the jutsu edit -> 361 regenerated and re-run (kit back on). 367 is that first step; it is not
part of the normal run order.

Do not hand-edit the output.
"""
import copy
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import skyglass_wave2 as W  # noqa: E402


def upgrades(ids, notes):
    b = W.spec("build_spec.json")
    rows = W.crew_rows()
    out = []
    for a in b["endgame"]["ais"]:
        s = W.slug(a["harnessId"])
        live = a["copyOf"]["liveAi"]
        lid = W.base_key_map()["base:" + s]
        row = rows[lid]
        kit = b["sharedKits"][live]
        assert kit["liveAiId"] == lid, (live, kit["liveAiId"])
        where = f"base:{s} ({live})"
        jutsus = [ids.jutsu(j["id"] if isinstance(j, dict) else j, where) for j in kit["jutsu"]]
        rules = [W.convert_rule(r, ids, where) for r in kit["rules"]]
        rules = W.finish_rules(rules, where, notes)
        W.check_ai(where, jutsus, rules)
        data = {"jutsus": jutsus, "items": W.items_of(row), "level": a["level"], "rank": a["rank"],
                "statsMultiplier": a["statsMultiplier"], "poolsMultiplier": a["poolsMultiplier"]}
        factor = a["stats"]["offence"] / row["offence"]
        for k in W.STATS6:
            data[k] = a["stats"][k]
        for k in W.MASTERIES:
            data[k] = max(10, round(row[k] * factor, 2)) if row[k] > 10 else row[k]
        data["effects"] = copy.deepcopy(a["effects"])
        data["includeDefaultRules"] = False
        data["rules"] = rules
        old = [j["jutsu"]["name"] for j in row.get("jutsus", []) if j.get("equipped")]
        note = (f"{live}: kit {len(jutsus)} jutsu (was {len(old)} equipped at push/249), {len(rules)} rules; level "
                f"{a['level']}, stats x{a['statsMultiplier']}, pools x{a['poolsMultiplier']} (HP "
                f"{a['pools']['maxHealth']:,}), {len(a['effects'])} innate row(s)")
        out.append({"entity": "ai", "slot": "edit", "targetId": lid, "name": f"{live}: endgame Wreck kit and tuning",
                    "_note": note, "data": data})
    return out


def unequip():
    rows = W.crew_rows()
    out = []
    for key, lid in W.base_key_map().items():
        row = rows[lid]
        out.append({"entity": "ai", "slot": "edit", "targetId": lid,
                    "name": f"{row['username']}: kit off (law 18)", "data": {"jutsus": [], "items": W.items_of(row)}})
    return out


def main():
    args = sys.argv[1:]
    if "--unequip" in args:
        n = W.NUM["unequip"]
        items = unequip()
        m = {"_note": (f"push/{n}: the 9 base crew records' kits off (law 18/60), the first step of any later edit to a "
                       f"library jutsu they hold: run {n}, then the jutsu edit, then push/{W.NUM['crew']} regenerated "
                       "(kit back on). Items re-sent as captured (push/249). Generated by "
                       "push/skyglass_crew_upgrade.gen.py --unequip; do not hand-edit."), "items": items}
        return W.write(os.path.join(W.OUT, f"{n}_skyglass_crew_unequip.json"), m)
    if args:
        raise SystemExit(__doc__)
    ids = W.Ids()
    notes = []
    items = upgrades(ids, notes)
    n = W.NUM["crew"]
    m = {"_note": (f"push/{n}: the live Skyglass crew upgraded in place for the endgame Wreck (RUL-2026-10-31-067 item "
                   "1): kit, rules (<= 20, includeDefaultRules false, named basic-attack fallback) and tuning from "
                   f"{W.build_dir_note()}/build_spec.json (sharedKits + endgame.ais). 9 AI edits, records stay hidden. "
                   "Library jutsu by literal id from push/342's bundle. Run BEFORE push/362 (the Wreck floors point at "
                   "these records) and in the go-live window: the live chart runs still fight these records until "
                   "push/339 points them at their Veteran copies. Generated by push/skyglass_crew_upgrade.gen.py; do "
                   "not hand-edit."),
         "_records": [e.pop("_note") for e in items], "_rule_notes": notes, "items": items}
    W.write(os.path.join(W.OUT, f"{n}_skyglass_crew_upgrade.json"), m)


if __name__ == "__main__":
    main()
