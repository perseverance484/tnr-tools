#!/usr/bin/env python3
"""
push/94: repair Sentinel's final edit again, named "Skyglass Sentinel" (RUL-2026-10-12-015).

    python3 push/94_ghost_ship_skyglass_sentinel_repair.gen.py           # write push/94 json + report
    python3 push/94_ghost_ship_skyglass_sentinel_repair.gen.py --check   # regenerate in memory, compare

What happened in push/93 (harvests/inbox/tnr_results_1791780626532.json):
- The rename to "Guardian" was refused: Duplicate entry 'Guardian' for key
  'UserData.UserData_username_key'. The AI is still "Ghostly Guardian" at multiplier 3, with the new kit.
- Both quest edits landed, so the 8 boss lines now say "Guardian".

What this emits:
1. push/90 item 29 (resolved as in push/93) with username "Skyglass Sentinel".
2. Both quests exactly as push/90 shipped them, resolved through the push/90 idmap. That restores the
   original "the Sentinel" lines. The generator proves the live push/93 after-capture differs from that
   only at the 8 boss lines.

Helpers come from push/93's generator, so the two resolve and diff identically.
"""
from __future__ import annotations

import copy
import hashlib
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("p93", os.path.join(HERE, "93_ghost_ship_guardian_repair.gen.py"))
p93 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(p93)
fail, load, resolve, diffs = p93.fail, p93.load, p93.resolve, p93.diffs

ROOT = p93.ROOT
OUT = "push/94_ghost_ship_skyglass_sentinel_repair.json"
REPORT = "state/ghost_ship_skyglass_sentinel_repair_report.json"
P93_RESULTS = "harvests/inbox/tnr_results_1791780626532.json"
NEW_NAME = "Skyglass Sentinel"
SENTINEL, QUEST_IDS = p93.SENTINEL, p93.QUEST_IDS


def build() -> tuple[dict, dict]:
    p90 = load(p93.P90, p93.P90_SHA)
    idmap = load(p93.RESULTS)["idmap"]  # push/90 run: uploads and created ids
    r93 = load(P93_RESULTS)
    after = {(c["proc"], json.dumps(c["input"], sort_keys=True)): c["data"]
             for c in r93["captures"] if c["phase"] == "after" and c.get("data")}
    ent = next((e for e in r93["entries"] if e.get("id") == SENTINEL and e.get("entity") == "ai" and e.get("state") == "error"), None)
    if not ent or "Duplicate entry 'Guardian'" not in ent.get("detail", ""):
        fail("push/93 results do not record the Guardian duplicate-name failure this manifest repairs")
    items = p90["items"]
    if items[29].get("targetId") != SENTINEL or items[29]["data"].get("username") != "Sentinel":
        fail("push/90 item 29 is not the Sentinel final edit")

    used: set = set()
    ai = copy.deepcopy(items[29])
    ai["data"] = resolve(ai["data"], idmap, used)
    ai["data"]["username"] = NEW_NAME
    changed = sorted(k for k in set(ai["data"]) | set(items[29]["data"]) if ai["data"].get(k) != items[29]["data"].get(k))
    if changed != ["avatar", "username"] or ai["data"]["statsMultiplier"] != 5:
        fail(f"payload departs from push/90 item 29 at {changed}")
    live_ai = after[("profile.getAi", json.dumps({"userId": SENTINEL}))]
    if live_ai["username"] != "Ghostly Guardian" or sorted(uj["jutsuId"] for uj in live_ai["jutsus"]) != sorted(ai["data"]["jutsus"]):
        fail("live AI is not the expected half-applied row (Ghostly Guardian with the new kit)")
    ai["name"] = "Skyglass Sentinel (was Ghostly Guardian; Sentinel and Guardian both taken): rename, rules, avatar, multiplier 5, kit re-sent"

    quests, restored = [], []
    for qid in QUEST_IDS:
        q = copy.deepcopy(next(e for e in items if e["entity"] == "quest" and e.get("targetId") == qid))
        q["data"] = resolve(q["data"], idmap, used)
        live = after[("quests.get", json.dumps({"id": qid}))]
        d = diffs(q["data"], live)
        want = {f"/content/objectives/{i}/description" for i, o in enumerate(q["data"]["content"]["objectives"])
                if o["id"] in p93.RENAMED_OBJECTIVES}
        if set(d) != want or len(want) != 4:
            fail(f"quest {qid}: live differs from push/90 at {sorted(d)}, expected exactly the 4 boss lines")
        restored += [f"{qid}/{o}" for o in p93.RENAMED_OBJECTIVES]
        q["name"] = q["name"].replace(": Skyglass retheme + 83-node expansion", ": boss text Guardian -> Sentinel (push/90 text restored)")
        quests.append(q)

    reads = ([{"proc": "profile.getAi", "input": {"userId": SENTINEL}, "persist": "full"}]
             + [{"proc": "quests.get", "input": {"id": qid}, "persist": "full"} for qid in QUEST_IDS])
    doc = {
        "_note": ("Ghost Ship push/94: Skyglass Sentinel repair (RUL-2026-10-12-015). Generated by "
                  "push/94_ghost_ship_skyglass_sentinel_repair.gen.py; do not hand-edit. Re-sends push/90's failed "
                  "Sentinel final edit as \"Skyglass Sentinel\", and both quests exactly as push/90 shipped them "
                  "(restores the 8 \"the Sentinel\" lines push/93 changed). No creates, no uploads; quests stay "
                  "hidden:true. Run by the operator only, Forge 0.5.2."),
        "dedupNames": True,
        "items": [ai] + quests,
        "capture": {"before": reads, "after": copy.deepcopy(reads)},
    }
    report = {
        "schema": "tnr.repair_manifest_report", "ruling": "RUL-2026-10-12-015", "manifest": OUT,
        "push90": {"path": p93.P90, "sha256": p93.P90_SHA},
        "push93Results": {"path": P93_RESULTS, "sha256": hashlib.sha256(open(os.path.join(ROOT, P93_RESULTS), "rb").read()).hexdigest()},
        "failure": ent["detail"],
        "resolvedRefs": {r: idmap[r.split(":", 1)[1]] for r in sorted(used)},
        "restoredObjectives": restored,
        "aiKeysChangedFromPush90": ["avatar (resolved @img)", "username"],
        "questsEqualPush90": True, "liveDiffersOnlyAtBossLines": True, "liveKitEqualsSentKit": True,
    }
    return doc, report


def main() -> int:
    doc, report = build()
    text = json.dumps(doc, indent=1, ensure_ascii=False) + "\n"
    report["manifestSha256"] = hashlib.sha256(text.encode()).hexdigest()
    rtext = json.dumps(report, indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv[1:]:
        for rel, want in ((OUT, text), (REPORT, rtext)):
            path = os.path.join(ROOT, rel)
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != want:
                print(f"STALE: {rel} differs from the generator", file=sys.stderr)
                return 1
        print(f"OK: {OUT} and {REPORT} reproduce ({len(doc['items'])} items, sha256 {report['manifestSha256']})")
        return 0
    for rel, t in ((OUT, text), (REPORT, rtext)):
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8") as fh:
            fh.write(t)
    print(f"wrote {OUT} + {REPORT}: {len(doc['items'])} items, lines restored {len(report['restoredObjectives'])}, "
          f"sha256 {report['manifestSha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
