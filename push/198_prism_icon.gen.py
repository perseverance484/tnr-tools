#!/usr/bin/env python3
"""Generate push/198-200: Prism's new Crystal Essence icon through the review desk without severing the
combat link of the two AIs that equip it, Jade and Mermaid Jade (laws 18, 60). Do not hand-edit.

Director's order (2026-10-21): "We suggest first then do the equip/re-equip". A suggestion does not
change the jutsu; the edit happens when a reviewer approves it. So law 60's order (unequip, edit,
re-equip) holds as long as 199 runs BEFORE the suggestion is approved.

  198  suggest mode: Prism `image` -> the new icon.
  199  write mode:   unequip Prism from Jade and Mermaid Jade. Run right after 198, before approval.
  200  write mode:   re-equip both exact kits. Run once the 198 suggestion is APPLIED or REJECTED.

Before-image: the 2026-10-21 AI census, harvests/inbox/tnr_results_1792551557783.json (push/159).
Prism record: harvests/inbox/tnr_results_1792216502874.json (2026-10-17).

  python3 push/198_prism_icon.gen.py <image pack commit>
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AI_BEFORE = ROOT / "harvests/inbox/tnr_results_1792551557783.json"
JUTSU_BEFORE = ROOT / "harvests/inbox/tnr_results_1792216502874.json"
PRISM = "6XpY1m4rAwrBHBKYsPRDJ"
AIS = {"RWDWENhorIa5zRfeHtOU7": "Jade", "RPyVKLWMVYK6nkznxkJas": "Mermaid Jade"}
ICON = "icon_crystal_essence_prism_v1.webp"
ICON_PATH = f"art/jutsu_icons/crystal_essence/exports/{ICON}"


def write(n, slug, manifest):
    p = ROOT / f"push/{n}_{slug}.json"
    p.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    print(p.name)


def main():
    ref = sys.argv[1]
    caps = json.loads(AI_BEFORE.read_text())["captures"]
    kits = {}
    for uid in AIS:
        ai = next(c["data"] for c in caps if c.get("proc") == "profile.getAi" and c.get("ok") and c["data"]["userId"] == uid)
        kit = [r["jutsuId"] for r in ai["jutsus"]]
        assert PRISM in kit and all(r.get("equipped") for r in ai["jutsus"]), uid
        kits[uid] = kit
    prism = next(c["data"] for c in json.loads(JUTSU_BEFORE.read_text())["captures"]
                 if isinstance(c.get("data"), dict) and c["data"].get("id") == PRISM)
    data = (ROOT / ICON_PATH).read_bytes()

    write(198, "prism_icon_suggestion", {
        "_note": "Step 1 of 3 (push/198-200). New Prism icon (director-supplied Crystal Essence set, art/jutsu_icons/crystal_essence/). Suggest mode: nothing changes until a reviewer approves. Only image changes; injectableInBattle re-sent at its live value (law 20). Prism is equipped by Jade and Mermaid Jade: run push/199 straight after this, BEFORE the suggestion is approved (laws 18, 60). Generated by push/198_prism_icon.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
        "mode": "suggest",
        "suggestion": {"category": "VISUAL", "title": "New jutsu icon", "rationale": "New icon from the Crystal Essence icon set."},
        "imgSizes": {ICON: len(data)},
        "imagePack": {"ref": ref, "files": {ICON: {"path": ICON_PATH, "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}}},
        "items": [{"entity": "jutsu", "slot": "edit", "name": prism["name"], "targetId": PRISM,
                   "data": {"image": "@img:" + ICON, "injectableInBattle": prism["injectableInBattle"]},
                   "suggestion": {"rationale": "New icon: a crystal prism splitting a beam of sunlight into the ground, matching Prism's channelled light. Part of the new Crystal Essence icon set."}}],
    })
    write(199, "prism_unequip", {
        "_note": "Step 2 of 3 (push/198-200). Unequip Prism from Jade and Mermaid Jade so the push/198 icon suggestion can be approved without severing their combat link (laws 18, 60). Run straight after 198, before the suggestion is approved. Until push/200 both AIs fight without Prism. Generated by push/198_prism_icon.gen.py; do not hand-edit. Operator-run only.",
        "items": [{"entity": "ai", "slot": "edit", "targetId": uid, "name": f"{AIS[uid]}: unequip Prism before its icon edit (law 60)",
                   "data": {"jutsus": [j for j in kits[uid] if j != PRISM]}} for uid in AIS],
    })
    write(200, "prism_reequip", {
        "_note": "Step 3 of 3 (push/198-200). Run only after the push/198 suggestion is APPLIED or REJECTED (Check suggestions). Re-equips Jade's and Mermaid Jade's exact kits in their original order (law 60). Generated by push/198_prism_icon.gen.py; do not hand-edit. Operator-run only.",
        "items": [{"entity": "ai", "slot": "edit", "targetId": uid, "name": f"{AIS[uid]}: re-equip Prism after its icon edit (law 60)",
                   "data": {"jutsus": kits[uid]}} for uid in AIS],
    })


if __name__ == "__main__":
    main()
