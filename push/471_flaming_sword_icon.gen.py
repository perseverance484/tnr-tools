#!/usr/bin/env python3
"""Generate push/471_flaming_sword_icon.json - icon suggestions for two live weapons."""
import hashlib, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = "9921c15b7a4ba33a2a2ab93955334944dd132303"
ICONS = [
    # (file, repo dir, targetId, name, item rationale)
    ("icon-flaming-sword.webp", "art/item_icons/flaming_sword/exports", "1GmiQAGuBZZsjIFqcqPkR", "Flaming Sword",
     "New icon: a katana with a flame-wreathed blade, black-and-red wrapped grip, gold tsuba and red tassel, matching the Flaming Sword's fire strike."),
    ("icon-tatsumakis-bellow.webp", "art/item_icons/tatsumakis_bellow/exports", "rIUgbOss7B5xTKEkg22MH", "Tatsumaki's Bellow",
     "New icon: a steel kunai with a glowing green core, wrapped in a swirling green wind, matching the tailwind and invisible wind blades it summons."),
]
files, sizes, items = {}, {}, []
for fn, d, tid, name, why in ICONS:
    path = d + "/" + fn
    raw = open(os.path.join(ROOT, path), "rb").read()
    sizes[fn] = len(raw)
    files[fn] = {"path": path, "sha256": hashlib.sha256(raw).hexdigest(), "bytes": len(raw)}
    items.append({"entity": "item", "slot": "edit", "phase": 1, "targetId": tid, "name": name,
                  "data": {"image": "@img:" + fn}, "suggestion": {"rationale": why}})
m = {
    "_note": "push/471: new icons for two live EPIC weapons, Flaming Sword (1GmiQAGuBZZsjIFqcqPkR) and Tatsumaki's Bellow (rIUgbOss7B5xTKEkg22MH). Suggest mode: content review desk, nothing changes until a reviewer approves. Only `image` changes on each. Live records (harvests/inbox/tnr_results_1793209875301.json and tnr_results_1793211272111.json, updatedAt 2026-10-28): both visible with non-empty battleDescription, so neither save is blocked. Flaming Sword source was an RGB render on a painted checkerboard (rawqc reject), salvaged by border flood-fill + two enclosed pocket removals, keyed through chroma.py --target ICON. Tatsumaki's Bellow source had native alpha: body alpha 240-253 snapped opaque, alpha <=8 haze cleared. Both padded square, 256x256 lossless WebP with hard alpha; artpreflight --type ICON 0/0. Generated by push/471_flaming_sword_icon.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
    "mode": "suggest",
    "suggestion": {"category": "VISUAL", "title": "New weapon icons",
                   "rationale": "New pixel-art icons for the Flaming Sword and Tatsumaki's Bellow."},
    "imgSizes": sizes,
    "imagePack": {"ref": REF, "files": files},
    "items": items,
}
out = os.path.join(ROOT, "push", "471_flaming_sword_icon.json")
json.dump(m, open(out, "w"), indent=1, ensure_ascii=False); open(out, "a").write("\n")
print(out)
