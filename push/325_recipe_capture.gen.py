#!/usr/bin/env python3
"""Generate push/325_recipe_capture_*: read-only full capture of every crafting and cooking recipe.

Director, 2026-10-28: "all crafting recipes were updated so we need to pull those. I want our drops to reflect the
changes." Recipes live in the CraftingRequirement table, which item.get does not return. Forge 0.10.1 (merge 5a20f3b9)
allows full persistence of item.getItemWithCraftingRequirements (one item by id: the item, its recipe rows and each
ingredient item). The targets are every item the push/323 capture marks canBeCrafted, plus every MEAL item (cooking
recipes share the table). Zero writes. Run from the repo root.
"""
import json, os, glob
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = ['tnr_results_1793209531278.json', 'tnr_results_1793209875301.json', 'tnr_results_1793210157421.json',
       'tnr_results_1793210735523.json', 'tnr_results_1793211014994.json', 'tnr_results_1793211272111.json']
items = {}
for f in src:
    for c in json.load(open('harvests/inbox/' + f))['captures']:
        x = c.get('data')
        if c.get('proc') == 'item.get' and isinstance(x, dict) and (x.get('canBeCrafted') or x.get('itemType') == 'MEAL'):
            items[x['id']] = x['name']
rows = sorted(items.items(), key=lambda t: t[1].lower())
PART = 61
parts = [rows[i:i + PART] for i in range(0, len(rows), PART)] or [[]]
for p, part in enumerate(parts, 1):
    m = {"_note": f"Recipe capture part {p}/{len(parts)}: read-only item.getItemWithCraftingRequirements (persist full) of "
                  f"{len(part)} craftable or MEAL items ({part[0][1]} .. {part[-1][1]}), from the push/323 item capture. It "
                  "feeds the Skyglass cache quantities priced by crafting cost (RUL-2026-10-28-018). Requires Forge 0.10.1. "
                  "Changes nothing. Generated by push/325_recipe_capture.gen.py; do not hand-edit.",
         "capture": {"before": [{"proc": "item.getItemWithCraftingRequirements", "input": {"id": i}, "persist": "full", "_name": n}
                                for i, n in part]},
         "items": []}
    out = f'push/325_recipe_capture_{p}.json'
    json.dump(m, open(out, 'w'), indent=1, ensure_ascii=False); open(out, 'a').write('\n')
    print(out, len(part))
