#!/usr/bin/env python3
"""Build push/630: repoint Rengoku Ro's two live animation assets at strips re-cut to <= 4096 px tall (direct edits).

    python3 push/630_rengoku_recut.gen.py

Why: push/624 hosted 300 px strips (300 x 6900, 300 x 10500) on the director's own UploadThing. Off-Bunny hosts load
native, battle clips are one texture (assetAnimationClip, one column) and combat effects have no MAX_TEXTURE_SIZE
guard, so phones (4096 px cap) draw them as black boxes (seen on the review desk preview, 2026-11-17). The re-cut
strips (art/duelyst_fx/recut_4096.py): strike 23 x 178 px = 4094, smoulder 35 x 116 px = 4060. Same frames and speed,
fresh filenames (_c). URLs from state/recut_upload/uploaded.json. Asset ids unchanged, so suggestion
96rmM8V6Qj2Ksq6s40e31 stays valid; no jutsu edit, no equip links touched. Read both assets back after.
"""
import hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/630_rengoku_recut.json'
UP = 'state/recut_upload/uploaded.json'
LICENSE = 'CC0 1.0 - OpenDuelyst (open-duelyst/duelyst), fx_f4_obliterate, adapted for TNR'
ASSETS = [  # srcId (upload), asset id, name, path, px, frames, speed
    ('rengoku_anim_strike_c', 'nAUh6EdgIUrPwLeyaeTPB', 'Rengoku Ro - Purgatory Prison',
     'art/duelyst_fx/rengoku/final/anim_rengoku_strike_tight_178_c.webp', 178, 23, 70),
    ('rengoku_anim_smoulder_c', 'cMax_mQ9G8TGmWBB-DcVR', 'Rengoku Ro - Smoulder',
     'art/duelyst_fx/rengoku/final/anim_rengoku_smoulder_tight_116_c.webp', 116, 35, 70),
]
from PIL import Image
up = json.load(open(UP))['files']
items = []
for src, aid, name, path, px, frames, speed in ASSETS:
    w, h = Image.open(path).size
    assert (w, h) == (px, px * frames) and h <= 4096, (path, w, h)
    u = up[src]
    assert u['file'] == os.path.basename(path), (src, u['file'])
    assert u['sha256'] == hashlib.sha256(open(path, 'rb').read()).hexdigest(), ('upload does not match file', path)
    assert u['url'].startswith('https://bbenpyo9uu.ufs.sh/f/'), u['url']
    items.append({"entity": "asset", "slot": "edit", "targetId": aid, "name": name,
                  "data": {"name": name, "type": "ANIMATION", "image": u['url'], "folder": "jutsuanimations",
                           "frames": frames, "speed": speed, "hidden": False, "onInitialBattleField": False,
                           "licenseDetails": LICENSE}})
m = {
    "_note": "Rengoku Ro: repoints the two live animation assets (strike nAUh6EdgIUrPwLeyaeTPB, smoulder cMax_mQ9G8TGmWBB-DcVR) at strips re-cut to <= 4096 px tall (178 / 116 px frames), because phones draw the 300 px native strips (6900 / 10500 px tall) as black boxes. Same frames, speed and hidden false; ids unchanged, so suggestion 96rmM8V6Qj2Ksq6s40e31 stays valid. No jutsu or AI edit. Generated by push/630_rengoku_recut.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset edits')
