#!/usr/bin/env python3
"""Build push/626: Rengoku Ro's new animations (suggest mode, one suggestion to the content review desk).

    python3 push/626_rengoku_suggestion.gen.py <push/624 results bundle> [capture bundle with a fresh jutsu.get]

Without a capture bundle the live record is state/rengoku/live_jutsu_20261116.json (connector read, 2026-11-16).
Art only, no mechanics: the damage effect's appearAnimation -> the push/624 strike, its disappearAnimation cleared
(the stock wind clip o7OZjzCesfwdgw6PsE1eg replayed on top), animationScale 1 -> 3 (the ring encircles the target's
tile); the afterburn's staticAnimation -> the push/624 smoulder, animationScale 1 -> 3. Power, rounds, text, icon
unchanged. The live effects array is re-sent (arrays are replaced, not merged); injectableInBattle re-sent at its live
value (law 20). Run push/625 (the unhide) first. Law 18: not checked against AI kits (no census; ~900 AIs) - see the
handoff. Pattern: push/240 (Celestial Dew). Director chose the "tight" variant and said submit, 2026-11-16.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
JID = 'fKQxOwBqZs8PXvpdGlbPg'
LIVE = 'state/rengoku/live_jutsu_20261116.json'
OUT = 'push/626_rengoku_suggestion.json'
OLD_CLIP = 'o7OZjzCesfwdgw6PsE1eg'
TITLE = 'New strike and smoulder animations'
RATIONALE = ("Rengoku Rō played a stock red wind clip that does not match its prison of endless flame. The strike now "
             "shows that prison: a ring of ghost-flame rises around the target, implodes and detonates, and the "
             "afterburn re-flares the ring dimly for its 2 rounds. Art only (animation scale 3, the old end clip "
             "cleared); power, rounds and text are unchanged.")
if len(sys.argv) not in (2, 3):
    raise SystemExit(__doc__)
idmap = json.load(open(sys.argv[1])).get('idmap', {})
strike, smoulder = idmap.get('rengoku_anim_strike'), idmap.get('rengoku_anim_smoulder')
assert strike and smoulder, 'the Rengoku assets are not in the bundle idmap: run push/624 first'

live = None
if len(sys.argv) == 3:
    for c in json.load(open(sys.argv[2]))['captures']:
        d = c.get('data')
        for cand in (d, (d or {}).get('data') if isinstance(d, dict) else None):
            if isinstance(cand, dict) and cand.get('id') == JID:
                live = cand
    assert live, 'Rengoku Ro not found in the capture bundle'
else:
    live = json.load(open(LIVE))
assert live['id'] == JID and live['name'] == 'Rengoku Rō', 'live record not found'
dmg = [e for e in live['effects'] if e['type'] == 'damage']
ab = [e for e in live['effects'] if e['type'] == 'afterburn']
assert len(live['effects']) == 2 and len(dmg) == 1 and len(ab) == 1, 'effects not as expected; re-read the record'
assert dmg[0].get('appearAnimation') == OLD_CLIP and not ab[0].get('staticAnimation'), \
    'animations changed since the read; re-read the record'
effects = []
for e in live['effects']:
    if e['type'] == 'damage':
        effects.append(dict(e, appearAnimation=strike, disappearAnimation='', animationScale=3))
    else:
        effects.append(dict(e, staticAnimation=smoulder, animationScale=3))
sug = {"category": "ANIMATION", "title": TITLE, "rationale": RATIONALE}
m = {
    "_note": "Rengoku Ro: one suggest-mode suggestion setting the damage effect's appear to the push/624 strike (ring of ghost-flame, implosion, dome detonation, smoke), clearing its stock disappear, and the afterburn's static loop to the push/624 smoulder; animationScale 3 on both. Mechanics, text and icon unchanged. Effects array re-sent; injectableInBattle re-sent at its live value (law 20). Generated by push/626_rengoku_suggestion.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
    "mode": "suggest",
    "suggestion": sug,
    "items": [{
        "entity": "jutsu", "slot": "edit", "name": "Rengoku Rō", "targetId": JID,
        "data": {"effects": effects, "injectableInBattle": live['injectableInBattle']},
        "suggestion": sug,
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 suggestion (damage appear {strike}, afterburn static {smoulder}, scale 3)')
