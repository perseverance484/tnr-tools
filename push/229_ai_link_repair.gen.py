#!/usr/bin/env python3
"""Build push/229 (unequip) and push/230 (re-equip) to repair AI combat links severed by push/227.

    python3 push/229_ai_link_repair.gen.py <push/228 results bundle>

push/227 edited 51 jutsu (image only); editing a jutsu an AI has equipped severs that AI's combat link (law 18). The repair is
strictly: unequip in one run, then re-equip in a later run (law 60). Kits come from the push/228 capture (today's state): each
affected AI's jutsus list is sent without the edited jutsu (229), then the exact original list in its original order (230).
Only EQUIPPED rows of edited jutsu are cycled; a re-added row comes back at level 1, so the generator refuses if any cycled row
is above level 1. Items are not sent (Forge re-sends the live items). Each manifest ends with a profile.getAi read-back.
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
edited = {r['id']: r['name'] for r in json.load(open('state/jutsu_icon_revert/revert_2026-10-23.json'))['jutsu']}
affected = []
for c in json.load(open(sys.argv[1]))['captures']:
    v = c.get('data')
    if c.get('proc') != 'profile.getAi' or not c.get('ok') or not isinstance(v, dict):
        continue
    rows = v.get('jutsus') or []
    cycle = [r['jutsuId'] for r in rows if r['jutsuId'] in edited and r.get('equipped') is True]
    if not cycle:
        continue
    for r in rows:
        if r['jutsuId'] in cycle and (r.get('level'), r.get('experience')) != (1, 0):
            raise SystemExit(f"{v['username']}: {edited[r['jutsuId']]} is level {r.get('level')}; re-adding resets it to 1")
    affected.append({'id': v['userId'], 'name': v['username'].strip() or v['username'], 'kit': [r['jutsuId'] for r in rows], 'cycle': cycle})
if not affected:
    raise SystemExit('no captured AI has an edited jutsu equipped: nothing to repair')
readback = {"before": [], "after": [{"proc": "profile.getAi", "input": {"userId": a['id']}, "persist": "full"} for a in affected]}
src = os.path.basename(sys.argv[1])
un = {"_note": f"AI link repair step 1 UNEQUIP (law 60): {len(affected)} AI(s). Removes only the equipped jutsu push/227 edited; the rest of each kit, items, stats and rules are untouched. Run push/230 (re-equip) only after this one is done. Kits from push/228 ({src}). Generated by push/229_ai_link_repair.gen.py; do not hand-edit.",
      "items": [{"entity": "ai", "slot": "edit", "targetId": a['id'], "name": f"{a['name']}: unequip {', '.join(edited[j] for j in a['cycle'])} (link repair, law 60)",
                 "data": {"jutsus": [j for j in a['kit'] if j not in a['cycle']]}} for a in affected], "capture": readback}
re = {"_note": f"AI link repair step 2 RE-EQUIP (law 60): {len(affected)} AI(s). Sends each AI's exact original kit from push/228 ({src}), original order. Run only after push/229 is done. Generated by push/229_ai_link_repair.gen.py; do not hand-edit.",
      "items": [{"entity": "ai", "slot": "edit", "targetId": a['id'], "name": f"{a['name']}: re-equip original kit (link repair)",
                 "data": {"jutsus": list(a['kit'])}} for a in affected], "capture": readback}
for path, m in (('push/229_ai_link_repair_unequip.json', un), ('push/230_ai_link_repair_reequip.json', re)):
    json.dump(m, open(path, 'w'), indent=1, ensure_ascii=False); open(path, 'a').write('\n')
    print('wrote', path, len(m['items']), 'AI edits')
for a in affected:
    print(f"  {a['name']}: {', '.join(edited[j] for j in a['cycle'])}")
