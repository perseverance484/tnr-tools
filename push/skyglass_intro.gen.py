#!/usr/bin/env python3
"""Wreck Sighted, new: the Skyglass event tutorial, a fresh one-time quest. One quest CREATE, HIDDEN.

    python3 push/skyglass_intro.gen.py                 -> push/497_skyglass_wreck_sighted_tutorial.json

Director, 2026-11-05 (RUL-2026-11-05-122 item 3): build the tutorial as a NEW one-time quest, hidden until he publishes
it; he deletes the old live Wreck Sighted (v7kKhLXsX9aofQfc7BnGx) himself. Text of record: docs/design/SKYGLASS_TEXT.md
section 1a, copied verbatim through push/skyglass_text.py. Design: docs/design/EVENT_JOURNAL.md section 6a.

Engine facts (theninjarpg@3314d122, read, not run):
  * One completion per player per quest id (maxCompletes 1, libs/quest.ts 2503-2513). A new record is a new id, so
    players who finished the old Wreck Sighted will also see this one once, and get its Tide Chart.
  * Deleting a quest is an in-game editor action for content roles (routers/quests.ts 1090-1125); it also deletes every
    player's history rows for that quest. Forge has no delete operation.
  * Nothing in the repository or any capture points at the old id (prerequisiteQuestId, completeQuestIds, newQuestIds):
    see docs/design/EVENT_JOURNAL.md section 6a for the list of references.
Do not hand-edit the output.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "push"))
import skyglass_text as T  # noqa: E402

NUM = 497
OUT = os.path.join(ROOT, f"push/{NUM}_skyglass_wreck_sighted_tutorial.json")
Q = "Wreck Sighted (tutorial)"
TIDE_CHART = "H1s2IwtZ5JqgPEoJ55IVj"
SALVAGER = "Xugt7415D3-tepLfxpwM5"
BG = "rX78pJPETsUL2JrsSvGHn"  # the shore scene asset (push/385)
IMG = "https://uploadthing.b-cdn.net/f/630cf6e7-c152-4dea-a3ff-821de76d7f5a_default.webp"  # the old record's icon
FLOW = [("d_word", ["d_wreck", "w_done"]), ("d_wreck", ["d_charts"]), ("d_charts", ["d_lantern"]),
        ("d_lantern", ["d_shards"]), ("d_shards", ["d_page"]), ("d_page", ["w_done"])]


def objectives():
    out = []
    for node, nexts in FLOW:
        target = f"obj:{Q}/{node}.description"
        ch = T.choices(target)
        assert len(ch) == len(nexts), (node, ch)
        out.append({"id": node, "task": "dialog", "description": T.block(target), "sceneBackground": BG,
                    "sceneCharacters": [SALVAGER],
                    "nextObjectiveId": [{"text": t, "nextObjectiveId": n} for t, n in zip(ch, nexts)]})
    out.append({"id": "w_done", "task": "win_quest", "description": T.block(f"obj:{Q}/w_done.description"),
                "sceneBackground": BG, "sceneCharacters": [],
                "reward_items": [{"ids": [TIDE_CHART], "number": 100, "quantity": 1}]})
    return out


def main():
    argparse.ArgumentParser(description="Wreck Sighted tutorial (new quest)").parse_args()
    data = {"name": T.block(f"quest:{Q}.name"), "description": T.block(f"quest:{Q}.description"), "image": IMG,
            "questType": "event", "questRank": "D",
            "successDescription": T.block(f"quest:{Q}.successDescription"),
            "retryDelay": "none", "attemptDelay": "none", "consecutiveObjectives": True, "hidden": True,
            "requiredLevel": 1, "maxLevel": 100, "maxAttempts": 1, "maxCompletes": 1,
            "prerequisiteQuestId": None, "tierLevel": None, "requiredVillage": None, "requiredBloodlineId": None,
            "startsAt": None, "endsAt": None,
            "content": {"objectives": objectives(), "sceneBackground": BG, "sceneCharacters": [SALVAGER],
                        "entryItems": [], "reward": {}}}
    item = {"entity": "quest", "slot": "create", "srcId": f"sg{NUM}_wreck_sighted", "phase": 1, "name": data["name"],
            "data": data}
    note = (f"push/{NUM}, HIDDEN: Wreck Sighted, new (RUL-2026-11-05-122), the Skyglass event tutorial as a fresh one-time "
            "quest (maxCompletes 1, the Tide Chart reward). Six short salvager scenes (skip available): the Wreck and "
            "its crew, charts to deeper runs, the lantern and Crownhold, the Haul, four shards and something beneath "
            "(hinted, never named), trade, and the weekly page on the Information Board. The director deletes the old live Wreck Sighted (v7kKhLXsX9aofQfc7BnGx) himself; publish "
            "this in the same sitting so no new player can take both. Veterans of the old one will see this once, by intent. "
            "Generated by push/skyglass_intro.gen.py; do not hand-edit.")
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump({"_note": note, "items": [item]}, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print(f"{os.path.relpath(OUT, ROOT)}: 1 quest create (hidden), {len(data['content']['objectives'])} nodes")


if __name__ == "__main__":
    main()
