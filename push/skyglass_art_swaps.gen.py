#!/usr/bin/env python3
"""Skyglass/Crownhold art batch: placeholder -> final art swaps (push/275).

Each approved image from docs/handoffs/SKYGLASS_CROWNHOLD_ART_BATCH.md lands as an export under art/, then gets one
row in SWAPS. This script writes push/275_skyglass_art_swaps.json: one direct, image-only edit per row on the hidden
live record (direct, not suggest: everything in the event is still hidden). Never hand-edit the output; add a row and
re-run.

The image pack ref is NOT typed: it is the newest commit on HEAD that touched any listed export, checked to contain
every file at the exact bytes on disk. Commit (and push) the export first, then run this.

Rows already run move to DONE (kept for the record, not emitted).
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "push", "275_skyglass_art_swaps.json")

# (batch #, entity, live id, record name, field, export path)  - ids from the session handoff section 1 and
# state/crownhold/ids.json (names matched through the push/272 manifest)
SWAPS = [
    (1, "item", "Ma8S90Nmbi0Xvm4u4FzJh", "Sealed Treasury", "image",
     "art/skyglass_event_icons/exports/icon-sealed-treasury.webp"),
    (2, "item", "B48dTRsoLJGKBWIUbeUoG", "Archive Chart Case", "image",
     "art/skyglass_event_icons/exports/icon-archive-chart-case.webp"),
    (3, "item", "nbLC37UzBamthKXvZsgQB", "Chart of the Buried Cache", "image",
     "art/skyglass_event_icons/exports/icon-chart-buried-cache.webp"),
    (4, "item", "KzITKJ5BUQRz5QuYWw-0B", "Unmarked Cargo", "image",
     "art/skyglass_event_icons/exports/icon-unmarked-cargo.webp"),
    (7, "ai", "81lnIP-q97gItQYWl5vWD", "Foundry Warden", "avatar",
     "art/skyglass_event_icons/avatars/avatar_skyglass_foundry_warden.webp"),
    (8, "ai", "-GKFYAZUg1eF-3VnZhDjx", "Master of Arms", "avatar",
     "art/crownhold/avatar_crownhold_master_of_arms.webp"),
]
DONE = []


def git(*a):
    return subprocess.check_output(["git", "-C", ROOT, *a], text=True).strip()


def main():
    if not SWAPS:
        sys.exit("no pending swaps")
    paths = sorted({r[5] for r in SWAPS})
    ref = git("log", "-1", "--format=%H", "HEAD", "--", *paths)
    if not ref:
        sys.exit("exports not committed")
    files = {}
    for p in paths:
        disk = open(os.path.join(ROOT, p), "rb").read()
        committed = subprocess.check_output(["git", "-C", ROOT, "show", f"{ref}:{p}"])
        if committed != disk:
            sys.exit(f"{p}: working copy differs from {ref}; commit it first")
        files[os.path.basename(p)] = {"path": p, "sha256": hashlib.sha256(disk).hexdigest(), "bytes": len(disk)}
    items = []
    for n, entity, tid, name, field, p in SWAPS:
        items.append({"entity": entity, "slot": "edit", "name": name, "targetId": tid,
                      "data": {field: "@img:" + os.path.basename(p)}})
    m = {
        "_note": ("Skyglass/Crownhold art batch swaps (generated by push/skyglass_art_swaps.gen.py; do not hand-edit). "
                  "Direct image-only edits on hidden live records, replacing placeholders with the approved premium "
                  "pixel art. Batch images: " + ", ".join(f"#{r[0]} {r[3]}" for r in SWAPS) +
                  ". Exports pinned by commit and SHA-256 in imagePack. Operator runs it from Forge; never skipPreflight."),
        "imgSizes": {k: v["bytes"] for k, v in files.items()},
        "imagePack": {"ref": ref, "files": files},
        "items": items,
    }
    with open(OUT, "w") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(OUT, "ref", ref, "edits", len(items))


if __name__ == "__main__":
    main()
