#!/usr/bin/env python3
"""push/604: the Faded Skyglass Wreck drops the two Driftline charts (design: Split Hold 20%, Broken Stern 5%).
    python3 push/driftline_drops.gen.py <faded_wreck_read.json>   (read taken AFTER 545, which halves and adds salvage)
Only rewards is sent; every other row is copied from the read."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FADED = "j4QEUtjbK_lbOYUPVoidk"
ROWS = [("I09yVwwnSQK8YE2vkdl1l", "Chart of the Split Hold", 20), ("KR5-rVmqtAWeMzpE52aE7", "Chart of the Broken Stern", 5)]
r = json.load(open(sys.argv[1])); r = r.get("data", r) if "id" not in r else r
if isinstance(r, list): r = next(x for x in r if x.get("id") == FADED)
assert r["id"] == FADED and r["name"] == "Faded Skyglass Wreck", (r.get("id"), r.get("name"))
rewards = json.loads(json.dumps(r["rewards"]))
assert any(d.get("id") == "mW6_ZGtGcCSuXGPhn-H4o" for d in rewards["drops"]), "read predates 545 (no salvage row)"
for cid, name, pct in ROWS:
    assert not any(d.get("id") == cid for d in rewards["drops"]), f"{name} already drops: stale read or 604 ran"
    rewards["drops"].append({"type": "item", "id": cid, "chance": pct, "quantity": 1})
m = {"_note": "push/604, LIVE with the Driftline go-live (after 545 and D2): Faded Skyglass Wreck drops Chart of the Split Hold 20% "
              "and Chart of the Broken Stern 5%. Generated by push/driftline_drops.gen.py from a fresh read; do not hand-edit.",
     "items": [{"entity": "dungeon", "slot": "edit", "phase": 1, "targetId": FADED,
                "name": "Faded Skyglass Wreck: drops Split Hold 20%, Broken Stern 5%", "data": {"rewards": rewards}}]}
out = os.path.join(ROOT, "push/604_driftline_drops.json"); json.dump(m, open(out, "w"), indent=1, ensure_ascii=False)
print(os.path.relpath(out, ROOT), len(rewards["drops"]), "drops")
