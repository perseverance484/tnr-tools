#!/usr/bin/env python3
"""Build push/629: Fury of The White Tiger's new animations (suggest mode, one suggestion to the content review desk).

    python3 push/629_white_tiger_suggestion.gen.py <push/627 results bundle> [capture bundle with a fresh jutsu.get]

Without a capture bundle the live record is state/white_tiger/live_jutsu_20261117.json (connector read, 2026-11-17).
Art only, no mechanics. Replaces the three v15d custom clips (art/fury_white_tiger/README_v15d.md):
- damage: appearAnimation waJwepo2V40MYNf6hAWzl (v15d claw strike) -> the push/627 tiger, animationScale 1 -> 3.
  Hit sound yGzPWg1cLQc6dYd1EpCsl stays.
- increasedamagegiven (SELF): appearAnimation '' -> the push/627 gates (the caster's cast clip), staticAnimation
  iBl5_M2fonkk8yiBLQgwU (v15d sparks loop) cleared (RUL-2026-11-17-166: buffs carry no lingering loop),
  animationScale 1 -> 3.
- afterburn (SELF): appearAnimation vP8EISrZnxvKV4dMBQ8x7 (v15d aura burst) cleared; the gates clip is the one caster
  clip (a second caster clip on the same cast would play on top of it).
- stun: unchanged (no art).
Power, rounds, text, icon unchanged. The live effects array is re-sent (arrays are replaced, not merged);
injectableInBattle re-sent at its live value (law 20). Run push/628 (the unhide) first. Law 18: not checked against
AI kits (no census; ~900 AIs). Pattern: push/626 (Rengoku Ro). Director: "Prep the white tiger one for a ticket",
2026-11-17.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
JID = 'QXE9J0fnu1t-DAGTGbaCX'
LIVE = 'state/white_tiger/live_jutsu_20261117.json'
OUT = 'push/629_white_tiger_suggestion.json'
OLD = {'damage': ('appearAnimation', 'waJwepo2V40MYNf6hAWzl'),
       'increasedamagegiven': ('staticAnimation', 'iBl5_M2fonkk8yiBLQgwU'),
       'afterburn': ('appearAnimation', 'vP8EISrZnxvKV4dMBQ8x7')}
TITLE = 'New gates and tiger animations'
RATIONALE = ("Fury of The White Tiger now shows its story: a teal chakra lotus blooms under the user as the gates "
             "open, then a spectral tiger lunges through the target. The two clips replace the three older custom "
             "ones, and the buff no longer leaves a loop on the user. Art only (animation scale 3); power, rounds "
             "and text are unchanged.")
if len(sys.argv) not in (2, 3):
    raise SystemExit(__doc__)
idmap = json.load(open(sys.argv[1])).get('idmap', {})
gates, tiger = idmap.get('white_tiger_anim_gates'), idmap.get('white_tiger_anim_tiger')
assert gates and tiger, 'the White Tiger assets are not in the bundle idmap: run push/627 first'

live = None
if len(sys.argv) == 3:
    for c in json.load(open(sys.argv[2]))['captures']:
        d = c.get('data')
        for cand in (d, (d or {}).get('data') if isinstance(d, dict) else None):
            if isinstance(cand, dict) and cand.get('id') == JID:
                live = cand
    assert live, 'Fury of The White Tiger not found in the capture bundle'
else:
    live = json.load(open(LIVE))
assert live['id'] == JID and live['name'] == 'Fury of The White Tiger', 'live record not found'
types = [e['type'] for e in live['effects']]
assert types == ['damage', 'increasedamagegiven', 'stun', 'afterburn'], f'effects not as expected: {types}'
for e in live['effects']:
    if e['type'] in OLD:
        k, v = OLD[e['type']]
        assert e.get(k) == v, f"{e['type']}.{k} changed since the read; re-read the record"
effects = []
for e in live['effects']:
    t = e['type']
    if t == 'damage':
        e = dict(e, appearAnimation=tiger, animationScale=3)
    elif t == 'increasedamagegiven':
        e = dict(e, appearAnimation=gates, staticAnimation='', animationScale=3)
    elif t == 'afterburn':
        e = dict(e, appearAnimation='')
    effects.append(e)
sug = {"category": "ANIMATION", "title": TITLE, "rationale": RATIONALE}
m = {
    "_note": "Fury of The White Tiger: one suggest-mode suggestion. damage appear -> the push/627 tiger (scale 3); increasedamagegiven appear -> the push/627 gates (scale 3), its v15d sparks loop cleared (RUL-2026-11-17-166); afterburn's v15d aura burst cleared; stun unchanged. Mechanics, text and icon unchanged. Effects array re-sent; injectableInBattle re-sent at its live value (law 20). Generated by push/629_white_tiger_suggestion.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
    "mode": "suggest",
    "suggestion": sug,
    "items": [{
        "entity": "jutsu", "slot": "edit", "name": "Fury of The White Tiger", "targetId": JID,
        "data": {"effects": effects, "injectableInBattle": live['injectableInBattle']},
        "suggestion": sug,
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 suggestion (tiger {tiger}, gates {gates}, scale 3)')
