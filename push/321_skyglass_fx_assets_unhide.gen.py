#!/usr/bin/env python3
"""Build push/321: unhide the ten Skyglass danger-language assets created by push/320 (direct edits).

    python3 push/321_skyglass_fx_assets_unhide.gen.py <push/320 results bundle>

Battles load only game assets with hidden = false (law 16c), and creates must ship hidden (law 16b), hence this follow-up.
Each asset's full create data is re-sent with hidden: false; the uploaded image is kept (image key dropped). The
test-play of the tiles moves to the Proving Ground quest (RUL-2026-10-28-028), so no test jutsu is created here.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/321_skyglass_fx_assets_unhide.json'
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
bundle = json.load(open(sys.argv[1]))
created = json.load(open('push/320_skyglass_fx_assets_create.json'))['items']
by_name = {e.get('name'): e for e in bundle.get('entries', []) if e.get('state') == 'ok' and e.get('slot') == 'create'}
items = []
for c in created:
    name = c['data']['name']
    e = by_name.get(name)
    assert e and e.get('id'), f'{name}: no ok create in the bundle; run push/320 first'
    data = dict(c['data'], hidden=False)
    data.pop('image', None)
    items.append({"entity": "asset", "slot": "edit", "targetId": e['id'], "name": name, "data": data})
m = {"_note": f"Unhides the {len(items)} Skyglass danger-language assets created by push/320 (law 16c: battles load only "
              "unhidden assets). The full create data is re-sent with hidden: false; images unchanged. Generated by "
              "push/321_skyglass_fx_assets_unhide.gen.py from the push/320 results bundle; do not hand-edit.",
     "items": items}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} unhides')
