#!/usr/bin/env python3
"""
Build push/93: set Sealwright's post-migration-0056 combat stats and masteries after push/90 runs.

    python3 push/93_ghost_ship_sealwright_stats.gen.py --results <push/90 Forge results bundle> [--out <path>] [--check]

WHY A SECOND MANIFEST. RUL-2026-10-12-008 makes Sealwright a copy of the regular Captain's profile.
Two Forge 0.5.0 facts stop push/90 from setting the post-0056 columns (offence, defence and six
masteries) itself:
- Forge's pre-create validator pins its AI key set to engine 345d18ac, before migration 0056, so
  it refuses those keys on the create.
- The runner resolves @refs inside `data` but reads `targetId` literally (forge/src/runner/runner.mjs
  _fill), so a same-job edit targeting `@ai:sealwright` calls profile.getAi("@ai:sealwright") and fails.
  The headless dry run (harness/ghost_ship_release_dryrun) found this.
This manifest is therefore generated from push/90's own results. It reads the created Sealwright's
literal userId from the bundle, and refuses unless the bundle is push/90 (same Forge manifest hash),
DONE/success, with the Sealwright create VERIFIED.

The values are the regular Captain's from push/86. The server's scaleEditedAi reweights them
(same level, multiplier and proportions), which reproduces the Captain's 834,780 in every stat and
mastery (docs/reviews/GHOST_SHIP_SKYGLASS_RELEASE_MANIFEST_DRAFT.md §2).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "push", "93_ghost_ship_sealwright_stats.json")
P86 = "harvests/inbox/tnr_results_1791727613862.json"
CAPTAIN = "QY69h271Nx9uHrBeR6jwW"
KEYS = ["offence", "defence", "ninjutsuMastery", "genjutsuMastery", "taijutsuMastery",
        "bukijutsuMastery", "bloodlineMastery", "sageMastery"]


def fail(msg: str) -> None:
    raise SystemExit("BUILD REFUSED: " + msg)


def load(path: str):
    with open(path if os.path.isabs(path) else os.path.join(ROOT, path), encoding="utf-8") as fh:
        return json.load(fh)


def forge_hash(manifest_rel: str) -> str:
    """Forge's own identity for push/90, from forge/tools/check_manifest.mjs."""
    import subprocess
    out = subprocess.run(["node", os.path.join(ROOT, "forge", "tools", "check_manifest.mjs"), os.path.join(ROOT, manifest_rel)],
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False).stdout
    for line in out.splitlines():
        if "manifest hash" in line:
            return line.rsplit(" ", 1)[-1]
    fail("could not compute push/90's Forge manifest hash")
    return ""


def build(results: str) -> dict:
    b = load(results)
    j = b.get("journal") or {}
    if j.get("manifestNumber") != 90 or j.get("manifestPath") != "push/90_ghost_ship_skyglass_release.json":
        fail(f"{results} is not a push/90 results bundle ({j.get('manifestPath')})")
    want = forge_hash("push/90_ghost_ship_skyglass_release.json")
    if j.get("manifestHash") != want:
        fail(f"bundle ran Forge manifest hash {j.get('manifestHash')}, the committed push/90 is {want}")
    if b.get("state") != "DONE" or b.get("outcome") != "success":
        fail(f"push/90 run is {b.get('state')}/{b.get('outcome')}, not DONE/success")
    sw = [e for e in b.get("entries", []) if e.get("srcId") == "sealwright" and e.get("entity") == "ai" and e.get("op") == "create"]
    if len(sw) != 1 or sw[0].get("forgeState") != "VERIFIED" or not sw[0].get("id"):
        fail("the Sealwright create is not VERIFIED with an id in the bundle")
    uid = sw[0]["id"]
    if (b.get("idmap") or {}).get("sealwright") not in (None, uid):
        fail("bundle idmap and entry disagree on Sealwright's id")
    cap = next(c["data"] for c in load(P86)["captures"] if c.get("proc") == "profile.getAi" and c["data"]["userId"] == CAPTAIN)
    return {
        "_note": ("Ghost Ship / Skyglass follow-up to push/90 (RUL-2026-10-12-008): Sealwright's post-0056 offence, defence "
                  "and six masteries equal the regular Captain's (push/86). Generated by push/93_ghost_ship_sealwright_stats.gen.py "
                  f"from {os.path.relpath(results, ROOT) if os.path.isabs(results) else results}; do not hand-edit. One AI edit, "
                  "literal targetId; run only after push/90 is DONE/success. Operator-run."),
        "items": [{"entity": "ai", "slot": "edit", "targetId": uid,
                   "name": "Sealwright: post-0056 combat stats and masteries equal the regular Captain",
                   "data": {k: cap[k] for k in KEYS}}],
        "capture": {"after": [{"proc": "profile.getAi", "input": {"userId": uid}, "persist": "full"}]},
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True, help="push/90 Forge results bundle (harvests/inbox/tnr_results_*.json)")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(a.results), indent=1, ensure_ascii=False) + "\n"
    if a.check:
        cur = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else None
        print("OK: generator-exact" if cur == text else f"STALE: {a.out}", file=sys.stdout if cur == text else sys.stderr)
        return 0 if cur == text else 1
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
