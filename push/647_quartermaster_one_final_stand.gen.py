#!/usr/bin/env python3
"""Job 647, HIDDEN: The Quartermaster no longer hands out a ration on the turn he opens the stores (the director, Nov 18).

The director (2026-11-18 20:30Z): the Quartermaster uses both of his final stand abilities on the same turn, though one
of them already covers everyone. Cause (live profile ZZWqe77JhJwvyHMt6eSiv, read 2026-11-18 ~20:40Z): rule 1 casts
Open the Stores (40 AP, final stand on every looter) in round 1, and the AI keeps going with 60 AP left; rule 3,
Hand Out a Ration (30 AP), has no condition, so it fires the same turn on a looter who is already covered.
Fix: Hand Out a Ration gets "round greater than 1", so round 1 is Open the Stores alone and rations start in round 2.
Every other rule is the live one, unchanged.

Run: python3 push/647_quartermaster_one_final_stand.gen.py -> push/647_quartermaster_one_final_stand.json. Do not hand-edit.
"""
import copy
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAP = os.path.join(ROOT, "state", "stolen_stores_captures", "quartermaster_live_2026-11-18", "ZZWqe77JhJwvyHMt6eSiv.json")
OUT = os.path.join(ROOT, "push", "647_quartermaster_one_final_stand.json")
QM = "rg-poMY3IBOl3xFrumEaq"
HAND_OUT = "I87F3AHWm29RMFAAWn9qE"


def main():
    with open(CAP) as f:
        prof = json.load(f)
    assert prof["userId"] == QM
    rules = copy.deepcopy(prof["rules"])
    hits = [r for r in rules if r["action"].get("jutsuId") == HAND_OUT]
    assert len(hits) == 1 and hits[0]["conditions"] == []
    hits[0]["conditions"] = [{"type": "round_greater_than", "value": 1,
                              "description": "Current round is greater than specified value"}]
    hits[0]["action"]["description"] = "Hand Out a Ration (weakest looter, round 2 on)"
    items = [{"entity": "aiProfile", "slot": "edit", "targetId": QM, "phase": 10,
              "name": "The Quartermaster: no ration on the turn he opens the stores",
              "data": {"rules": rules, "includeDefaultRules": prof["includeDefaultRules"]}}]
    m = {"_note": ("push/647, HIDDEN: The Quartermaster's Hand Out a Ration waits for round 2, so it never fires on the "
                   "same turn as Open the Stores. Generated by push/647_quartermaster_one_final_stand.gen.py from the "
                   "live profile capture; do not hand-edit."), "items": items}
    with open(OUT, "w") as f:
        json.dump(m, f, separators=(",", ":"))
    print(f"wrote {OUT}: {len(items)} items, {os.path.getsize(OUT)} bytes")


if __name__ == "__main__":
    main()
