#!/usr/bin/env python3
"""Generate push/345_pet_catalogue_capture.json: read-only census of the live pet catalogue.

Director-approved 2026-10-31: the Skyglass Little Horror kit is balanced against live pets, and its default loadout
may name live PETS jutsu. This reads every companion species and every PETS jutsu with full records. It needs Forge
0.12.2 (petSpecies.getAll and jutsu.getAll {jutsuType: ["PETS"], hidden} as persist-full captures; handoff
docs/handoffs/PET_CATALOGUE_READS_3314D122.md). An older Forge refuses the manifest at parse time and reads nothing.
All three reads are public, so any signed-in session works. Zero writes.

  (no args)          write the manifest: petSpecies.getAll, then jutsu.getAll PETS with hidden false and then hidden true.
                     The game omits hidden jutsu unless hidden is sent, so it takes both reads to cover every PETS jutsu.
  --report <bundle>  from the results bundle: every species (rarity, role, isActive, defaults) and every PETS jutsu
                     (rank, cooldown, costs, species lock, hidden). Exits 1 if a read was not persisted, a species'
                     defaultJutsuIds names a jutsu neither read returned, or a jutsu is species-locked to an unknown
                     species.
Run from anywhere; paths are relative to the repository root (--root overrides it).
"""
import argparse, json, os, sys

OUT = "push/345_pet_catalogue_capture.json"
TAIL = " Changes nothing. Generated by push/345_pet_catalogue_capture.gen.py; do not hand-edit."

ap = argparse.ArgumentParser()
ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ap.add_argument("--report", metavar="BUNDLE")
a = ap.parse_args()
os.chdir(a.root)


def pets(hidden):
    return {"proc": "jutsu.getAll", "input": {"jutsuType": ["PETS"], "hidden": hidden}, "persist": "full",
            "_name": f"PETS jutsu, hidden {str(hidden).lower()}"}


if a.report:
    caps = json.load(open(a.report))["captures"]
    bad = [c for c in caps if not (c.get("ok") and c.get("persistOk") and "data" in c)]
    for c in bad:
        print(f"NOT PERSISTED {c.get('proc')} {c.get('input')}: {c.get('error') or c.get('persistError')}")
    species = [s for c in caps if c.get("proc") == "petSpecies.getAll" and "data" in c for s in c["data"]]
    jutsu = {j["id"]: j for c in caps if c.get("proc") == "jutsu.getAll" and "data" in c for j in c["data"]}
    sids = {s["id"] for s in species}
    problems = len(bad) + (0 if any(c.get("proc") == "petSpecies.getAll" for c in caps) else 1) \
        + sum(1 for h in (False, True) if not any(c.get("proc") == "jutsu.getAll" and (c.get("input") or {}).get("hidden") is h for c in caps))
    print(f"{len(species)} species; {len(jutsu)} PETS jutsu ({sum(1 for j in jutsu.values() if j.get('hidden'))} hidden)")
    for s in sorted(species, key=lambda s: s["name"].lower()):
        print(f"  species {s['id']} {s['name']!r} {s['rarity']} {s['role']} active={s['isActive']} "
              f"element={s.get('preferredDamageElement')} effects={len(s.get('effects') or [])} defaults={s.get('defaultJutsuIds')}")
        for d in s.get("defaultJutsuIds") or []:
            if d not in jutsu:
                problems += 1
                print(f"    UNKNOWN DEFAULT {d}: neither PETS read returned it")
    for j in sorted(jutsu.values(), key=lambda j: (j.get("requiredRank") or "", j["name"].lower())):
        lock = j.get("requiredPetSpeciesId")
        print(f"  jutsu {j['id']} {j['name']!r} rank={j.get('jutsuRank')} req={j.get('requiredRank')}/L{j.get('requiredLevel')} "
              f"cd={j.get('cooldown')} ap={j.get('actionCostPerc')} cost(c/s/h)={j.get('chakraCost')}/{j.get('staminaCost')}/{j.get('healthCost')} "
              f"use={j.get('battleUsageType')} lock={lock} hidden={j.get('hidden')} effects={[e.get('type') for e in j.get('effects') or []]}")
        if lock and lock not in sids:
            problems += 1
            print(f"    UNKNOWN SPECIES LOCK {lock}")
    sys.exit(1 if problems else 0)

m = {"_note": "Pet catalogue census: read-only petSpecies.getAll (persist full: every companion species, retired ones too) "
              "and jutsu.getAll {jutsuType: [PETS]} (persist full: whole records) with hidden false and then hidden true, "
              "since the game omits hidden jutsu unless asked. Forge accepts each jutsu read only as one complete page "
              "(nextCursor null) of distinct PETS rows matching the filter. Basis for balancing the Skyglass Little Horror "
              "kit against live pets and choosing its default PETS loadout (director-approved 2026-10-31). Check with "
              "--report <bundle>. Requires Forge 0.12.2; public reads." + TAIL,
     "capture": {"before": [{"proc": "petSpecies.getAll", "persist": "full", "_name": "every pet species"}, pets(False), pets(True)]},
     "items": []}
json.dump(m, open(OUT, "w"), indent=1, ensure_ascii=False)
open(OUT, "a").write("\n")
print(OUT, len(m["capture"]["before"]), "reads")
