#!/usr/bin/env python3
"""Generate push/318: one elemental kunai pouch; the Armory Requisition and the Drowned Foundry pick 1 of 3 (RUL-2026-10-28-003).

    python3 push/elemental_pouch.gen.py

The five elemental kunai are down to one, Elemental Kunai (director 2026-10-28). Phase 1: the Katon Tool Pouch
(D0gtI5dOgj2dFO4VexsLJ, never released) becomes the Elemental Tool Pouch: every Katon Kunai line in its guaranteed
stack and its roll points at Elemental Kunai; the tools are unchanged. The other four pouches stay hidden and unused.
Phase 2: the Armory Requisition (Special) and the Drowned Foundry (whole-record edit, last written by push/268) pick 1 of:
the pouch / Medicine Inro / 50,000 ryo. Do not hand-edit the output.
"""
import importlib.util, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARCH = os.path.join(ROOT, "archive/spent-manifests/push-2026-10-25")
spec = importlib.util.spec_from_file_location("hunts", os.path.join(ROOT, "push/skyglass_hunts.gen.py"))
G = importlib.util.module_from_spec(spec); spec.loader.exec_module(G)

POUCH = "D0gtI5dOgj2dFO4VexsLJ"
KATON_KUNAI = "sXaqXBYXGHvK75D7Bpo1h"
ELEMENTAL_KUNAI = "dY00WA51Mr7-uS6zbcS3r"
INRO = "ixEKlJ0MmDrX7JoMNJVhi"
RYO = 50000
ARMORY_QUEST = "3BYr-HMkOepywS77vJvJh"  # push/274 result
FOUNDRY_QUEST = "UGHSuhi83C3wRtH3FD4Eu"
NAME = "Elemental Tool Pouch"


def pouch_edit():
    src = json.load(open(os.path.join(ARCH, "260_skyglass_items_create.json")))
    d = next(it for it in src["items"] if it["srcId"] == "tool_pouch_katon")["data"]
    s = json.dumps(d["effects"])
    assert s.count(KATON_KUNAI) == 4
    eff = json.loads(s.replace(KATON_KUNAI, ELEMENTAL_KUNAI).replace("Katon Kunai", "Elemental Kunai")
                     .replace("Katon Tool Pouch", NAME))
    return {"entity": "item", "slot": "edit", "targetId": POUCH, "phase": 1, "name": f"Katon Tool Pouch -> {NAME}",
            "data": {"name": NAME, "target": "SELF", "effects": eff,
                     "description": "A buckled armory pouch: elemental kunai and the tools that go with them."}}


def reward():
    return G.items_reward((POUCH, 1), (INRO, 1), reward_money=RYO)


def armory_edit():
    return {"entity": "quest", "slot": "edit", "targetId": ARMORY_QUEST, "phase": 2,
            "name": "Armory Requisition: pick 1 of 3",
            "data": {"description": ("The Skyglass armory still honours a valid requisition. Present it and choose what "
                                     "you were issued."),
                     "successDescription": "The quartermaster's seal accepts your requisition. Choose your issue.",
                     "content": {"objectives": [{"id": "w_issue", "task": "win_quest", "sceneBackground": "",
                                                 "sceneCharacters": [],
                                                 "description": "The requisition is stamped and the armory's stores open."}],
                                 "sceneBackground": "", "sceneCharacters": [], "rewardMode": "choose",
                                 "rewardPickCount": 1, "reward": reward()}}}


def foundry_edit():
    q = G.quest("hunt_foundry", "The Drowned Foundry", G.H.FOUNDRY["premise"],
                "You carried the last pour out of the keel works.", G.ITEM["chart_foundry"],
                "@img:icon-chart-drowned-foundry.webp", G.foundry(), reward(), "A", FOUNDRY_QUEST)
    q["phase"] = 2
    return q


def main():
    items = [pouch_edit(), armory_edit(), foundry_edit()]
    G.write(318, "elemental_pouch_and_picks", (
        "push/318 (RUL-2026-10-28-003), all HIDDEN. Phase 1: the Katon Tool Pouch becomes the Elemental Tool Pouch "
        "(Elemental Kunai x10 every opening; the roll's kunai lines are Elemental Kunai x10/x20/x30; tools unchanged; "
        "the Katon icon stays until a neutral pouch is drawn). Phase 2: the Armory Requisition quest and the Drowned "
        "Foundry (whole record, as push/268 plus this reward) pick 1 of: Elemental Tool Pouch / Medicine Inro / 50,000 ryo. "
        "The other four pouches stay hidden and unused. Generated by push/elemental_pouch.gen.py; do not hand-edit."),
        items)


if __name__ == "__main__":
    main()
