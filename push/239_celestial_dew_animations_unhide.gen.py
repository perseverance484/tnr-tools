#!/usr/bin/env python3
"""Build push/239: unhide the three Celestial Dew animation assets created by push/238 (direct edits).

    python3 push/239_celestial_dew_animations_unhide.gen.py <push/238 results bundle>

Battles load only unhidden assets (law 16c). Creates ship hidden (law 16b, lint L13), hence this follow-up by literal id.
Each asset's data is re-sent as created with hidden: false; the image is not re-sent (Forge merges the live record).
Director, 2026-10-24: "Let's make the animation unhidden first then send in the suggestion ticket" (then push/240).
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/239_celestial_dew_animations_unhide.json'
CREATE = next(p for p in ('archive/spent-manifests/push-2026-10-22/238_celestial_dew_animations.json',
                          'push/238_celestial_dew_animations.json') if os.path.exists(p))
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
idmap = json.load(open(sys.argv[1])).get('idmap', {})
items = []
for it in json.load(open(CREATE))['items']:
    aid = idmap.get(it['srcId'])
    assert aid, f"{it['srcId']} not in the bundle idmap: run push/238 first"
    data = dict(it['data'], hidden=False)
    data.pop('image')
    items.append({"entity": "asset", "slot": "edit", "targetId": aid, "name": it['name'], "data": data})
m = {
    "_note": "Unhides the three Celestial Dew animation assets created by push/238 (shield appear, static, disappear): battles load only unhidden assets (law 16c). Run before push/240 (the suggestion). Generated by push/239_celestial_dew_animations_unhide.gen.py; do not hand-edit.",
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: unhide ' + ', '.join(i['targetId'] for i in items))
