#!/usr/bin/env python3
"""Build push/236: Ethereal Rebirth icon + non-elemental text + cast animation + passive loop (suggest mode, one
suggestion). Replaces push/231, whose suggestion the director cancelled (2026-10-24: "lets make a new one that proposes
all of this").

    python3 push/236_ethereal_rebirth.gen.py <push/230 results bundle> <push/234 results bundle> [ICON]

The absorb effect gains appearAnimation = the cast animation (push/230, now the v5 strip after push/233) and
staticAnimation = the passive loop (push/234, idmap er_anim_soul_orbit; the game loops it while the absorb is active,
libs/threejs/combat.ts:667). Run push/235 (unhide the loop) too; order does not matter.

ICON defaults to art/jutsu_icons/ethereal_rebirth/exports/icon_jutsu_ethereal_rebirth_v1.webp, the director-approved
icon (round 3 polish of R2-2; exported 256 px lossless, artpreflight JUTSU_ICON clean). It must be committed.
The bundle supplies the animation asset id (idmap er_anim_soul_ribbons). The live effects array is re-sent (arrays are
replaced, not merged) with only the absorb effect (target SELF, plays on the caster) gaining appearAnimation = the new
asset; the damage effect keeps its hit animation on the enemy. Text: docs/design/icon_overhaul/ethereal_rebirth/TEXT_V2.md
(approved 2026-10-24), the training warning kept on the description. injectableInBattle re-sent at its live value
(law 20). No AI holds Ethereal Rebirth in the push/228 capture or recent bundles (laws 18, 60).
"""
import hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
JID = 'K0t6Z-Q4lau1jFt8Tkpot'
TEXT = 'docs/design/icon_overhaul/ethereal_rebirth/TEXT_V2.md'
PUBLIC = 'harvests/inbox/tnr_results_1792732003454.json'
OUT = 'push/236_ethereal_rebirth.json'
WARNING = '<br><br><span style="color:#D22B2B">DON\'T TRAIN. ALREADY CAPPED. IT HAS NO POWER PER LEVEL</span>'

if len(sys.argv) not in (3, 4):
    raise SystemExit(__doc__)
ICON = sys.argv[3] if len(sys.argv) == 4 else 'art/jutsu_icons/ethereal_rebirth/exports/icon_jutsu_ethereal_rebirth_v1.webp'
assert os.path.exists(ICON), f'{ICON} not found: approve and export the icon first'
anim = json.load(open(sys.argv[1])).get('idmap', {}).get('er_anim_soul_ribbons')
assert anim, 'er_anim_soul_ribbons not in the bundle idmap: run push/230 first'
loop = json.load(open(sys.argv[2])).get('idmap', {}).get('er_anim_soul_orbit')
assert loop, 'er_anim_soul_orbit not in the bundle idmap: run push/234 first'

live = None
for c in json.load(open(PUBLIC))['captures'][1:]:
    for j in c['data']['data']:
        if j['id'] == JID:
            live = j
assert live and live['name'] == 'Ethereal Rebirth', 'live record not found'
assert live['description'].endswith(WARNING), 'live description no longer ends with the training warning; re-read it'
ab = [e for e in live['effects'] if e['type'] == 'absorb']
assert len(ab) == 1 and ab[0]['target'] == 'SELF' and not ab[0].get('appearAnimation') and not ab[0].get('staticAnimation'), 'absorb effect not as expected; re-read the record'
dmg = [e for e in live['effects'] if e['type'] == 'damage']
assert len(dmg) == 1 and dmg[0].get('elements') == ['None'], 'damage is no longer non-elemental; the text would be wrong'
effects = [dict(e, appearAnimation=anim, staticAnimation=loop) if e['type'] == 'absorb' else dict(e) for e in live['effects']]

t = open(TEXT).read()
def quote(label):
    block = re.search(r'\*\*' + label + r':?\*\*[^\n]*\n((?:> .*\n)+)', t).group(1)
    return ' '.join(l[2:].strip() for l in block.splitlines())
desc = quote('Description') + WARNING
battle = quote('Battle line')
for bad in ('fire', 'water', 'lightning', 'flame', '%jutsu', '—'):
    assert bad not in (desc + battle).lower(), bad
assert battle.startswith('%user') and '%target' in battle

ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
blob = subprocess.check_output(['git', 'show', f'{ref}:{ICON}'])
b = open(ICON, 'rb').read()
assert blob == b, 'the committed icon differs from the file on disk: commit it first'
fn = os.path.basename(ICON)
m = {
    "_note": "Ethereal Rebirth (RUL-2026-10-24-003/-004/-005): one suggest-mode suggestion carrying the new icon (premium upgrade of the original: the white-haired warrior, arms wide, the seal on their soul cracking open, ribbons of soul-light), the approved non-elemental text (TEXT_V2.md), the new cast animation (appearAnimation, push/230 asset, v5 strip) and the passive orbit loop (staticAnimation, push/234 asset) on the absorb effect. Replaces push/231's cancelled suggestion. injectableInBattle re-sent at its live value (law 20). Generated by push/236_ethereal_rebirth.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
    "mode": "suggest",
    "suggestion": {"category": "CONSISTENCY", "title": "New icon, animation and text", "rationale": "New icon, cast animation, active-effect animation and text that match the jutsu."},
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": ICON, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "jutsu", "slot": "edit", "name": "Ethereal Rebirth", "targetId": JID,
        "data": {"image": "@img:" + fn, "description": desc, "battleDescription": battle, "effects": effects,
                 "injectableInBattle": live['injectableInBattle']},
        "suggestion": {"category": "CONSISTENCY", "title": "New icon, animation and text",
                       "rationale": "The old text described green flame and the old art showed fire and water, but the jutsu deals non-elemental damage. The new icon upgrades the original players liked (the same white-haired warrior, now readable at small sizes), the new text matches what the jutsu does, a new cast animation shows the seal cracking open and the soul-light ribbons wrapping the caster, and while the absorb lasts two ribbons quietly orbit the caster to show the protection is active."},
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 suggestion (cast {anim}, loop {loop}), pack @ {ref[:7]}')
