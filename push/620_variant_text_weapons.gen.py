#!/usr/bin/env python3
"""Job 620: premium text for every weapon variant (director 2026-11-15).

Players asked for unique text on every variant, the way Hemathorn and Weeping Testament were done. Each variant's
description and battleDescription mirror its parent item's text sentence by sentence, with the imagery swapped to the
variant (state/variant_text/weapons_20261115.json, parent text read live 2026-11-15).

Edits are itemVariant fetch-merges (name, image, cost, unlock token and order are kept from the live row).
Run: python3 push/620_variant_text_weapons.gen.py -> push/620_variant_text_weapons.json
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "state", "variant_text", "weapons_20261115.json")
OUT = os.path.join(ROOT, "push", "620_variant_text_weapons.json")


def main():
    vs = json.load(open(SRC))["variants"]
    for v in vs:
        for k in ("description", "battleDescription"):
            assert v[k].strip(), (v["name"], k)
        assert "%target" in v["battleDescription"], v["name"]
    assert len({v["id"] for v in vs}) == len(vs)
    items = [{"entity": "itemVariant", "slot": "edit", "targetId": v["id"],
              "name": f"{v['item']}: {v['name']} (variant): description and battle text",
              "data": {"itemId": v["itemId"], "description": v["description"],
                       "battleDescription": v["battleDescription"]}} for v in vs]
    m = {"_note": (f"push/620: unique description and battle text for {len(items)} weapon variants, each mirroring its "
                   "parent's text with the variant's own imagery (director 2026-11-15, Hemathorn/Weeping Testament "
                   "pattern). Fetch-merge itemVariant edits; nothing else changes. Generated by "
                   "push/620_variant_text_weapons.gen.py; do not hand-edit."),
         "items": items}
    json.dump(m, open(OUT, "w"), indent=1, ensure_ascii=False)
    print(f"wrote {OUT}: {len(items)} variants")


if __name__ == "__main__":
    main()
