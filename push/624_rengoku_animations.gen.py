#!/usr/bin/env python3
"""Build push/624: create the two Rengoku Ro animation assets (direct; suggest mode cannot create).

    python3 push/624_rengoku_animations.gen.py

Strips: art/duelyst_fx/rengoku/final/anim_rengoku_{strike,smoulder}_tight_300_b.webp (build_rengoku.py, the "tight"
variant the director chose 2026-11-16), 300 px frames, 70 ms. Source art: OpenDuelyst fx_f4_obliterate, CC0 1.0.
Strike -> the damage effect's appear; smoulder -> the afterburn's static loop (push/626, the suggestion). Created
hidden (law 16b gate); push/625, built from this run's results bundle, unhides them (law 16c). The image pack is
pinned at HEAD: commit the strips first. Pattern: push/238-240 (Celestial Dew).
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
E = 'art/duelyst_fx/rengoku/final/'
OUT = 'push/624_rengoku_animations.json'
PX = 300
LICENSE = 'CC0 1.0 - OpenDuelyst (open-duelyst/duelyst), fx_f4_obliterate, adapted for TNR'
ASSETS = [  # srcId, name, file, frames, speed (ms per frame)
    ('rengoku_anim_strike', 'Rengoku Ro - Purgatory Prison', 'anim_rengoku_strike_tight_300_b.webp', 23, 70),
    ('rengoku_anim_smoulder', 'Rengoku Ro - Smoulder', 'anim_rengoku_smoulder_tight_300_b.webp', 35, 70),
]
from PIL import Image
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
pack, sizes, items = {}, {}, []
for src, name, fn, frames, speed in ASSETS:
    path = E + fn
    w, h = Image.open(path).size
    assert w == PX and h == PX * frames, (fn, w, h)
    b = open(path, 'rb').read()
    assert len(b) < 460800, (fn, len(b))
    assert subprocess.check_output(['git', 'show', f'{ref}:{path}']) == b, 'commit the strips first'
    pack[fn] = {"path": path, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
    sizes[fn] = len(b)
    items.append({"entity": "asset", "slot": "create", "srcId": src, "name": name,
                  "data": {"name": name, "type": "ANIMATION", "image": "@img:" + fn, "folder": "jutsuanimations",
                           "frames": frames, "speed": speed, "hidden": True, "onInitialBattleField": False,
                           "licenseDetails": LICENSE}})
m = {
    "_note": "Creates the two Rengoku Ro animation assets: the strike (a ring of ghost-flame rises around the target, implodes, a dome detonates and collapses into smoke; 23 x 70 ms) and the smoulder (the afterburn loop: a quiet lead-in as long as the strike, then a dim re-flare of the ring; 35 x 70 ms). 300 px frames, adapted from OpenDuelyst fx_f4_obliterate (CC0). Direct creates, hidden (law 16b); push/625 unhides them from this run's bundle (law 16c) and push/626 suggests the jutsu edit. Generated by push/624_rengoku_animations.gen.py; do not hand-edit.",
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": pack},
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset creates, pack @ {ref[:7]}')
