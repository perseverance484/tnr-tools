#!/usr/bin/env python3
"""Generate push/640 (20 normal, special and event jutsu) and push/641 (28 bloodline jutsu).

Each jutsu gets a Forge livePatch {"zeroInstantResidual": true}: at send time the runner reads the
live record and sets residualModifier to 0 on every instant damage, pierce or elementaldamage
effect (rounds 0). The modifier only scales damage on rounds after the cast, so an instant hit is
unchanged in combat; the edit only stops the residual equip cap from counting the jutsu.

Law 18: a jutsu on an AI kit is unequipped (phase 10), edited (20) and put back (30). Kits are the
live read in state/residual_fix/scope.json; re-read them before the run if that date is stale.
The bloodline set is its own job because custom bloodlines need their own go-ahead (DOCTRINE).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
scope = json.load(open(os.path.join(ROOT, "state", "residual_fix", "scope.json"), encoding="utf-8"))
JOBS = [(640, "residual_modifier_fix", lambda j: j["type"] != "BLOODLINE", "normal, special and event"),
        (641, "residual_modifier_fix_bloodline", lambda j: j["type"] == "BLOODLINE", "bloodline")]
assert len(scope["jutsu"]) == 48 and len({j["id"] for j in scope["jutsu"]}) == 48
assert not set(scope["not_changed"]) & {j["id"] for j in scope["jutsu"]}

for num, slug, pick, label in JOBS:
    inn = {j["id"]: j["name"] for j in scope["jutsu"] if pick(j)}
    kits = {a: k for a, k in scope["ai_kits"].items() if any(x in inn for x in k["jutsus"])}
    items = []
    for a, k in kits.items():
        items.append({"entity": "ai", "slot": "edit", "targetId": a, "phase": 10, "name": f"{k['name']}: jutsu off (law 18)",
                      "data": {"jutsus": [x for x in k["jutsus"] if x not in inn]}})
    for j, name in sorted(inn.items(), key=lambda kv: kv[1].lower()):
        items.append({"entity": "jutsu", "slot": "edit", "targetId": j, "phase": 20, "name": f"{name}: instant hit residualModifier 0",
                      "data": {}, "livePatch": {"zeroInstantResidual": True}})
    for a, k in kits.items():
        items.append({"entity": "ai", "slot": "edit", "targetId": a, "phase": 30, "name": f"{k['name']}: kit back (law 18)",
                      "data": {"jutsus": k["jutsus"]}})
    m = {"_note": (f"push/{num}: residualModifier 0 on {len(inn)} {label} jutsu whose only damage is an instant hit, so the "
                   f"residual equip cap stops counting them (game source libs/jutsu.ts matchesJutsuCategory counts any nonzero "
                   f"residualModifier). Combat damage is unchanged: the modifier is only applied on rounds after the cast. Forge "
                   f"livePatch zeroInstantResidual (effects derived from live at send time). Law 18 on {len(kits)} AIs (kits read "
                   f"live {scope['kits_read']}). Not touched: {', '.join(scope['not_changed'].values())} (damage with no rounds set). "
                   f"Generated by push/640_residual_modifier_fix.gen.py; do not hand-edit."),
         "items": items}
    out = os.path.join(ROOT, "push", f"{num}_{slug}.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(m, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {out}: {len(inn)} jutsu, {len(kits)} AIs, {len(items)} items")
