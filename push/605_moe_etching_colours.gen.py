#!/usr/bin/env python3
"""Job 605: the Mother of Echoes etchings each get their own colour (QA, Acts II-III: all five read as the same gold;
Rime and Hail alike; Seam nearly vanishes; Recast: Heart and Recast: Seam the same white burst).

THIS MANIFEST ONLY CREATES THE ART (258 ANIMATION assets, hidden, image-pack bound). It edits no jutsu and no AI.

Why no jutsu edits: job 593 rewrites the same jutsu (animationScale 2.5 by Forge livePatch) before 605 runs, so a 605
jutsu edit must be applied on top of the live record at send time, never a record captured earlier. Forge's livePatch
knows only {animationScale, assets} (forge/src/runner/livepatch.mjs); it cannot swap an effect's appearAnimation to a
new asset, and a plain edit replaces data.effects wholesale (recipes.mjs mergeForUpdate), which would revert 593.
The swap is therefore staged, not built: state/moe_etch_colours/asset_map.json maps every live slice id (read
2026-11-13, state/moe_etch_colours/live_20261113.json, cross-checked against push/506's results idmap) to the srcId
of its v10 replacement here. The follow-up job, once Forge can livePatch an asset map, is: law 18 with kits read at
run time (phase 10 her jutsu off, 20 the 7 jutsu livePatched {assetMap, animationScale 2.5}, 30 kit back), then an
unhide of these assets (law 16c: battles load only hidden=false assets) with literal ids from this run's bundle.

Run (art committed first; the pack pins HEAD):
    python3 art/mother_of_echoes_fx/build_etch_colours_v10.py
    git add art/mother_of_echoes_fx/exports_v10 && git commit ...
    python3 push/605_moe_etching_colours.gen.py   ->  push/605_moe_etching_colours.json + state/moe_etch_colours/asset_map.json
"""
import hashlib
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = "push/605_moe_etching_colours.json"
SNAP = "state/moe_etch_colours/live_20261113.json"
MAP = "state/moe_etch_colours/asset_map.json"
ART = "art/mother_of_echoes_fx/exports_v10/"
FRAMES = {"etch": 22, "recast": 34}  # as push/506's creates of the slices they replace
SPEED = 50
LABEL = {"etch": "Etching", "recast": "Recast"}
FILE = {"etch": "anim_moe_etch3_{x}_p{c}_{r}_a14.webp", "recast": "anim_moe_recast3_{x}_p{c}_{r}_a14_ff.webp"}

ref = subprocess.check_output(["git", "rev-parse", "HEAD"]).decode().strip()
snap = json.load(open(SNAP))
items, sizes, files, amap = [], {}, {}, {}
for jid, j in snap["jutsu"].items():
    kind, x = j["kind"], j["element"]
    X = x.capitalize()
    for (tile, live_id) in zip(j["tiles"], j["appear"]):
        c, r = (int(v) for v in tile.split(","))
        fn = FILE[kind].format(x=x, c=c, r=r)
        path = ART + fn
        subprocess.run(["git", "cat-file", "-e", f"{ref}:{path}"], check=True)  # the pack must resolve at the pinned ref
        b = open(path, "rb").read()
        src = f"sg605_{kind}_{x}__{c}_{r}"
        name = f"MoE II: {LABEL[kind]} {X} v10 - slice c{c:02d}r{r:02d}"
        items.append({"entity": "asset", "slot": "create", "srcId": src, "name": name, "phase": 0, "data": {
            "name": name, "type": "ANIMATION", "folder": f"SkyglassMotherOfEchoesSlices{LABEL[kind]}{X}V10",
            "frames": FRAMES[kind], "speed": SPEED, "hidden": True, "onInitialBattleField": False,
            "licenseDetails": "TNR", "image": f"@img:{fn}"}})
        sizes[fn] = len(b)
        files[fn] = {"path": path, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
        amap.setdefault(jid, {"jutsu": j["name"], "map": {}})["map"][live_id] = src

man = {
    "_note": ("push/605: Mother of Echoes etching colours, art only. 258 ANIMATION slices recoloured per etching "
              "(Rime ice blue, Hail white, Ember orange, Heart teal, Seam white-gold, thickened) plus Recast: Heart/Seam tinted "
              "to match; created hidden (law 16b). No jutsu or AI edit: the asset swap needs a Forge livePatch asset map "
              "(see the generator docstring and state/moe_etch_colours/asset_map.json); unhide follows with that job. "
              "Generated by push/605_moe_etching_colours.gen.py; do not hand-edit."),
    "dedupNames": True,
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": files},
    "items": items,
}
json.dump(man, open(OUT, "w"), indent=1)
json.dump({"_note": "605: live slice asset id (read 2026-11-13) -> srcId of its v10 replacement in push/605, per jutsu. "
           "Input for the follow-up livePatch swap; resolve srcIds through 605's results idmap.", "jutsu": amap},
          open(MAP, "w"), indent=1)
print(f"wrote {OUT}: {len(items)} asset creates, pack @ {ref[:7]}; {MAP}: {sum(len(v['map']) for v in amap.values())} ids")
