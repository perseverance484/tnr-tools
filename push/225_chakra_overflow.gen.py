#!/usr/bin/env python3
"""Build push/225: Chakra Overflow icon + premium text (suggest mode, one suggestion).

    python3 push/225_chakra_overflow.gen.py

Icon: art/jutsu_icons/chakra_overflow/exports/icon_jutsu_chakra_overflow_v1.webp ("the rising star", director-approved
2026-10-23; artpreflight JUTSU_ICON clean). Text: docs/design/chakra_overflow/CHAKRA_OVERFLOW_TEXT.md. injectableInBattle
re-sent at its live value (law 20; true in the public jutsu.getAll read of 2026-10-23). Suggest mode allows no
captures, so the AI-equip check for the 26 AIs no bundle has read stays in push/224 (run it before approving).
The image pack is pinned at HEAD, so commit the export first.
"""
import hashlib, json, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
JID = 'e2eC-x4UXc5m6QexNbx8w'
ICON = 'art/jutsu_icons/chakra_overflow/exports/icon_jutsu_chakra_overflow_v1.webp'
TEXT = 'docs/design/chakra_overflow/CHAKRA_OVERFLOW_TEXT.md'
PUBLIC = 'harvests/inbox/tnr_results_1792732003454.json'
OUT = 'push/225_chakra_overflow.json'

live = None
for c in json.load(open(PUBLIC))['captures'][1:]:
    for j in c['data']['data']:
        if j['id'] == JID:
            live = j
assert live and live['name'] == 'Chakra Overflow', 'live record not found'
t = open(TEXT).read()
desc = re.search(r'\*\*Description:\*\* (.+)', t).group(1).strip()
battle = re.search(r'\*\*Battle line:\*\* (.+)', t).group(1).strip()
assert '%target' not in battle and '%jutsu' not in battle, 'self jutsu: no %target, no %jutsu'
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
subprocess.run(['git', 'cat-file', '-e', f'{ref}:{ICON}'], check=True)
b = open(ICON, 'rb').read(); fn = os.path.basename(ICON)
m = {
    "_note": "Chakra Overflow (director, 2026-10-23: 'the most important icon in the game'; project docs/design/chakra_overflow/). One suggest-mode suggestion: the new icon ('the rising star', RUL-2026-10-23-002 and amendments) and the premium text (docs/design/chakra_overflow/CHAKRA_OVERFLOW_TEXT.md), injectableInBattle re-sent true (law 20). AI equips: the 2026-10-21 census shows only Tyrant King and Tyrant Guard holding it, unequipped (no link to sever); push/224 reads the 26 AIs no bundle has read; run it before approving. Generated by push/225_chakra_overflow.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
    "mode": "suggest",
    "suggestion": {"category": "CONSISTENCY", "title": "New icon and text", "rationale": "New icon and premium text."},
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": ICON, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "jutsu", "slot": "edit", "name": "Chakra Overflow", "targetId": JID,
        "data": {"image": "@img:" + fn, "description": desc, "battleDescription": battle,
                 "injectableInBattle": live['injectableInBattle']},
        "suggestion": {"category": "CONSISTENCY", "title": "New icon and text",
                       "rationale": "The most-used jutsu in the game gets a premium icon (a white-hot star rising on wings of blue chakra, readable at small sizes) and premium text. The old battle line ran five sentences listing the attack types it boosts and repeated the jutsu's name."},
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 suggestion, pack @ {ref[:7]}')
