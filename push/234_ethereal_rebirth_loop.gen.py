#!/usr/bin/env python3
"""Build push/234: create the Ethereal Rebirth passive loop asset (direct; suggest mode cannot create).

    python3 push/234_ethereal_rebirth_loop.gen.py

The strip: art/jutsu_icons/ethereal_rebirth/animation/exports/anim_ethereal_rebirth_loop1.webp (build_strip.py loop1;
director, 2026-10-24: "a subtler effect of the same ribbons ... passively orbiting and protecting the player so long as
the absorb is active"): 48 square frames of 128 px, 80 ms per frame (3.84 s, one orbit, seamless). It becomes the absorb
effect's staticAnimation, which the game loops while the absorb stands (theninjarpg libs/threejs/combat.ts:667,
showAnimation playInfinite).

A new asset. Created hidden because the gates require hidden: true on every create (law 16b, lint L13); battles load only
unhidden assets (law 16c), so the follow-up built from this run's results bundle (idmap er_anim_soul_orbit) unhides it by
literal id and push/231 is rebuilt to set the absorb effect's staticAnimation, in the same one suggestion as the icon,
text and cast animation. The image pack is pinned at HEAD, so the strip must be committed.
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
STRIP = 'art/jutsu_icons/ethereal_rebirth/animation/exports/anim_ethereal_rebirth_loop1.webp'
OUT = 'push/234_ethereal_rebirth_loop.json'
FRAMES, SPEED = 48, 80
NAME = 'Ethereal Rebirth - Soul Orbit'

from PIL import Image
im = Image.open(STRIP)
w, h = im.size
assert w == 128 and h == 128 * FRAMES, (w, h)
b = open(STRIP, 'rb').read()
assert len(b) < 460800, len(b)
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
blob = subprocess.check_output(['git', 'show', f'{ref}:{STRIP}'])
assert blob == b, 'the committed strip differs from the file on disk: commit it first'
fn = os.path.basename(STRIP)
m = {
    "_note": "Creates the Ethereal Rebirth passive loop asset: one gold and one blue soul-light band orbiting the user's avatar, quiet and seamless (48 frames x 80 ms = 3.84 s, one orbit), for the absorb effect's staticAnimation (loops while the absorb is active). Direct create, hidden (law 16b gate); a follow-up built from this run's results bundle (idmap er_anim_soul_orbit) unhides it (law 16c) and push/231 is rebuilt to set the absorb effect's staticAnimation. Generated by push/234_ethereal_rebirth_loop.gen.py; do not hand-edit.",
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": STRIP, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "asset", "slot": "create", "srcId": "er_anim_soul_orbit", "name": NAME,
        "data": {
            "name": NAME,
            "type": "ANIMATION",
            "image": "@img:" + fn,
            "folder": "jutsuanimations",
            "frames": FRAMES,
            "speed": SPEED,
            "hidden": True,
            "onInitialBattleField": False,
            "licenseDetails": "TNR",
        },
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 asset create, {FRAMES} frames x {SPEED} ms, {len(b)} bytes, pack @ {ref[:7]}')
