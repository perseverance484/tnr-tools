#!/usr/bin/env python3
"""Build push/226: create the Chakra Overflow cast animation as a new ANIMATION game asset (direct create).

    python3 push/226_chakra_overflow_animation.gen.py

The strip: art/jutsu_icons/chakra_overflow/animation/exports/anim_chakra_overflow_v1.webp (build_strip.py v5, director-
approved 2026-10-23): 48 square frames of 128 px stacked vertically, played at 54 ms per frame (2.6 s). A new asset,
because the jutsu's current animation (spellcast_D_large_violet, QgsljoZSCOKhdQxCIGnTU) is shared by six other jutsu.
Suggest mode cannot carry creates, so this runs on its own; push/225 is then rebuilt with the new asset id from this
run's results bundle. hidden: true per the create rule (law 16b; gameAsset hidden affects listing only, law 16c).
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
STRIP = 'art/jutsu_icons/chakra_overflow/animation/exports/anim_chakra_overflow_v1.webp'
OUT = 'push/226_chakra_overflow_animation.json'
FRAMES, SPEED = 48, 54

from PIL import Image
im = Image.open(STRIP)
w, h = im.size
assert w == 128 and h == 128 * FRAMES, (w, h)
b = open(STRIP, 'rb').read()
assert len(b) < 460800, len(b)
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
subprocess.run(['git', 'cat-file', '-e', f'{ref}:{STRIP}'], check=True)
fn = os.path.basename(STRIP)
m = {
    "_note": "Creates the Chakra Overflow cast animation ('the rising star' dissolving in, glinting, dissolving out; 48 frames x 54 ms = 2.6 s) as a NEW ANIMATION game asset, srcId co_anim_rising_star. Direct create (suggest mode cannot carry creates). The jutsu is not touched here: push/225 is rebuilt afterwards from this run's results bundle to point Chakra Overflow's visual effect at the new id, alongside the new icon and text, as one suggestion. Art: docs/handoffs/CHAKRA_OVERFLOW_ANIMATION_ART_REQUEST.md sections 6-10. Generated by push/226_chakra_overflow_animation.gen.py; do not hand-edit.",
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": STRIP, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "asset", "slot": "create", "srcId": "co_anim_rising_star",
        "name": "Chakra Overflow - Rising Star",
        "data": {
            "name": "Chakra Overflow - Rising Star",
            "type": "ANIMATION",
            "image": "@img:" + fn,
            "folder": "jutsuanimations",
            "frames": FRAMES,
            "speed": SPEED,
            "hidden": True,
            "onInitialBattleField": False,
            "licenseDetails": "TNR",
        },
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 asset create, {FRAMES} frames x {SPEED} ms, {len(b)} bytes, pack @ {ref[:7]}')
