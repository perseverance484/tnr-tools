"""push/327: bind the six live token variants to the Lion Token (RUL-2026-10-29-054 item 2).

Reads the push/326 pass-2 bundle and writes one itemVariant edit per variant whose requiredItemId is empty, setting it to
the Lion Token. The edit is fetch-merged over the live row, so name, image, cost and order are kept. After this, only a
Lion Token unlocks these variants; the generic Skyglass Token cannot.

    python3 push/327_lion_token_variant_bind.gen.py harvests/inbox/<push/326 pass-2 bundle>
"""
import json, sys

LION = "FG4xYkI8UmRrJCdD3yPxI"
bundle = json.load(open(sys.argv[1]))
items = []
for c in bundle["captures"]:
    if c.get("proc") != "item.getItemVariants":
        continue
    for v in c["data"]:
        if v.get("costType") == "VARIANT_TOKEN" and not v.get("requiredItemId"):
            items.append({"entity": "itemVariant", "slot": "edit", "name": v["name"], "targetId": v["id"],
                          "data": {"itemId": v["itemId"], "requiredItemId": LION}})
# Director 2026-10-30: hide the stray unhidden generic "Test Variant" token item.
items.append({"entity": "item", "slot": "edit", "name": "Test Variant", "targetId": "QeQtevFEEL766JJQZ5tWK",
              "data": {"hidden": True}})
out = {"_note": "Bind every live VARIANT_TOKEN variant without a required unlock item to the Lion Token "
                "(RUL-2026-10-29-054 item 2), so the generic Skyglass Token cannot unlock them, and hide the stray "
                "\"Test Variant\" token item. Fetch-merge edits; nothing else changes. Generated by push/327_lion_token_variant_bind.gen.py from the push/326 pass-2 "
                "bundle; do not hand-edit.",
       "items": items}
json.dump(out, open("push/327_lion_token_variant_bind.json", "w"), indent=1, ensure_ascii=False)
print(len(items), "edits")
