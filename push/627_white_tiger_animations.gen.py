#!/usr/bin/env python3
"""Build push/627: create the two Fury of The White Tiger animation assets (direct; suggest mode cannot create).

    python3 push/627_white_tiger_animations.gen.py

Strips: art/duelyst_fx/showcase/final/anim_white_tiger_{gates_140,tiger_102}.webp (build_white_tiger.py, the staff
showcase, re-cut by art/duelyst_fx/recut_4096.py so each strip is <= 4096 px tall: phones draw taller native strips
as black boxes). Gates: OpenDuelyst fx_f2_eightgates_teallotus recoloured to chakra teal, 29 x 70 ms, the
caster's cast clip. Tiger: fx_f2_saberspineseal, 10 blank lead frames (the gale's travel time) then the tiger strike,
40 x 80 ms, the target's hit clip. Both CC0 1.0. Created hidden (law 16b); push/628, built from this run's results
bundle, unhides them (law 16c); push/629 is the suggestion. The image pack is pinned at HEAD: commit the strips
first. Pattern: push/624-626 (Rengoku Ro).
"""
import hashlib, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
E = 'art/duelyst_fx/showcase/final/'
OUT = 'push/627_white_tiger_animations.json'
LICENSE = 'CC0 1.0 - OpenDuelyst (open-duelyst/duelyst), fx_f2_eightgates_teallotus / fx_f2_saberspineseal, adapted for TNR'
ASSETS = [  # srcId, name, file, frame px, frames, speed (ms per frame)
    ('white_tiger_anim_gates', 'Fury of The White Tiger - Gates', 'anim_white_tiger_gates_140.webp', 140, 29, 70),
    ('white_tiger_anim_tiger', 'Fury of The White Tiger - Tiger', 'anim_white_tiger_tiger_102.webp', 102, 40, 80),
]
from PIL import Image
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
pack, sizes, items = {}, {}, []
for src, name, fn, PX, frames, speed in ASSETS:
    path = E + fn
    w, h = Image.open(path).size
    assert w == PX and h == PX * frames, (fn, w, h)
    assert h <= 4096, (fn, h, 'phones draw strips over 4096 px tall as black boxes')
    b = open(path, 'rb').read()
    assert len(b) < 460800, (fn, len(b))
    assert subprocess.check_output(['git', 'show', f'{ref}:{path}']) == b, 'commit the strips first'
    pack[fn] = {"path": path, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
    sizes[fn] = len(b)
    items.append({"entity": "asset", "slot": "create", "srcId": src, "name": name,
                  "data": {"name": name, "type": "ANIMATION", "image": "@img:" + fn, "folder": "jutsuanimations",
                           "frames": frames, "speed": speed, "hidden": True, "onInitialBattleField": False,
                           "licenseDetails": LICENSE}})
m = {
    "_note": "Creates the two Fury of The White Tiger animation assets: the gates (teal chakra lotus blooms under the caster as the gates open and flares up around them; 29 x 70 ms, 140 px) and the tiger (a short quiet lead-in for the gale's travel, then a spectral tiger lunges and slashes through the target; 40 x 80 ms, 102 px). Adapted from OpenDuelyst fx_f2_eightgates_teallotus and fx_f2_saberspineseal (CC0). Direct creates, hidden (law 16b); push/628 unhides them from this run's bundle (law 16c) and push/629 suggests the jutsu edit. Generated by push/627_white_tiger_animations.gen.py; do not hand-edit.",
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": pack},
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} asset creates, pack @ {ref[:7]}')
