for o in q["data"]["content"]["objectives"]:
    if o["task"] == "defeat_opponents":
        o["opponent_scaled_to_user"] = True; n_fight += 1
    if o["id"] in BOSS_DIALOGS:
        o["sceneCharacters"] = ["@scene:pz_scene_char"]; n_scene += 1
assert n_scene == len(BOSS_DIALOGS), n_scene
q["name"] = f"Vanquish the Horde: Patient Zero scene character on {n_scene} boss dialogs, {n_fight} fights scaled to the player"
