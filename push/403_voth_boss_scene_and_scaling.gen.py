import json, copy, hashlib, os
# Base: the LIVE record from the push/401 recapture (tnr_results_1793568292560, 2026-11-01). Diffed against the push/336
# payload: unchanged since 2026-10-31 02:34Z apart from @ai:pz_boss now resolved to its live id, so no staff edit is lost.
B = "harvests/inbox/tnr_results_1793568292560.json"
live = next(c["data"] for c in json.load(open(B))["captures"] if c["input"].get("id") == "0U8N6218b095-TQbWlCep")
