#!/usr/bin/env python3
"""Generate push/316 + 317: Core Rupture becomes a small, heavy blast (director 2026-10-28, RUL-2026-10-28-001).

    python3 push/core_rupture.gen.py

Core Rupture (nCQETf-HNnbRec1OSY2-R) is held only by Seal Charge and Core Canister (consumer audit,
state/ghost_ship_legacy_jutsu_consumer_audit.json). Law 18: 316 unequips it from both; 317 converts the jutsu and
re-equips. Source record: harvests/inbox/tnr_results_1792900120886.json. Do not hand-edit the outputs.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAP = os.path.join(ROOT, "harvests/inbox/tnr_results_1792900120886.json")
JID = "nCQETf-HNnbRec1OSY2-R"
AIS = {"wTgO-Q32caSSd0is1QIS7": "Seal Charge", "frc9LTxqQlM7mncG4VZGK": "Core Canister"}
ARMOR = "h-V9uiuxbL7lAWkO6nZWt"  # AI Heavy Armor, held by both; kept
PIERCE = 180  # was 120 on every player (method ALL); now the target and the ring around it


def captured():
    found = {}
    def walk(o):
        if isinstance(o, dict):
            if o.get("userId") in AIS and "jutsus" in o:
                found[o["userId"]] = o
            for v in o.values(): walk(v)
        elif isinstance(o, list):
            for v in o: walk(v)
    walk(json.load(open(CAP)))
    return found


def main():
    ais = captured()
    assert set(ais) == set(AIS)
    for uid, a in ais.items():
        assert [j["jutsuId"] for j in a["jutsus"] if j["equipped"]] == [JID], uid
        assert [i["itemId"] for i in a["items"]] == [ARMOR], uid
    jutsu = next(iter(ais.values()))["jutsus"][0]["jutsu"]
    eff = json.loads(json.dumps(jutsu["effects"]))
    assert [e["type"] for e in eff] == ["pierce", "onehitkill", "stun"] and eff[0]["power"] == 120
    assert eff[1]["target"] == "SELF"  # the self-destruct stays
    eff[0]["power"] = PIERCE
    unequip = [{"entity": "ai", "slot": "edit", "targetId": uid, "name": f"{n}: unequip Core Rupture (law 18)",
                "data": {"jutsus": [], "items": [ARMOR]}} for uid, n in AIS.items()]
    convert = {"entity": "jutsu", "slot": "convert", "targetId": JID, "name": "Core Rupture: small heavy blast",
               "data": {"target": "OTHER_USER", "method": "AOE_CIRCLE_SPAWN", "range": 5, "effects": eff,
                        "injectableInBattle": False}}
    reequip = [{"entity": "ai", "slot": "edit", "targetId": uid, "name": f"{n}: re-equip Core Rupture",
                "data": {"jutsus": [JID], "items": [ARMOR]}} for uid, n in AIS.items()]
    return unequip, convert, reequip


def write_standalone(unequip, convert, reequip):
    out = {
        "316_core_rupture_unequip.json": {
            "_note": "STEP 1 of 2 (director 2026-10-28, RUL-2026-10-28-001). Unequips Core Rupture from Seal Charge and "
                     "Core Canister (law 18); AI Heavy Armor kept. Run 317 next. Generated by push/core_rupture.gen.py.",
            "items": unequip},
        "317_core_rupture_blast.json": {
            "_note": "STEP 2 of 2 (after 316). Core Rupture: method ALL (every player on the board) -> AOE_CIRCLE_SPAWN "
                     f"(the target and the six hexes around it), range 5; pierce 120 -> {PIERCE}. The self-destruct "
                     "(onehitkill on SELF) and the 2-round stun are unchanged; effects otherwise re-sent as captured "
                     "(tnr_results_1792900120886). Then re-equips it on both; rules untouched. Generated by "
                     "push/core_rupture.gen.py.",
            "items": [convert] + reequip}}
    for name, m in out.items():
        json.dump(m, open(os.path.join(ROOT, "push", name), "w"), indent=1)
        print(name, len(m["items"]))


if __name__ == "__main__":
    write_standalone(*main())
