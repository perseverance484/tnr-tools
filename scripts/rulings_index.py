#!/usr/bin/env python3
"""The rulings ledger: full entries by month in docs/rulings/YYYY-MM.md, an index in docs/RULINGS.md.

    python3 scripts/rulings_index.py           rebuild the index (and move any stray entries, see below)
    python3 scripts/rulings_index.py --check   exit 1 if the index is stale or an entry sits in docs/RULINGS.md

A ruling is a "## RUL-YYYY-MM-DD-NNN — Title" section. Its month file is chosen by the date in its
ID; within a month, entries keep the order they were written in (never re-sorted, never rewritten).
docs/RULINGS.md holds the ledger's rules and the generated index, between the INDEX markers. An
entry appended to docs/RULINGS.md out of habit is moved to its month file by the next rebuild
(never by --check), so the index stays the only thing in that file.

The index lists every ruling: ID, title, status (from its own Status line), its file, and, where a
later ruling's Supersedes line names it, the ruling that supersedes it. Duplicate IDs (three exist
from October) are listed twice and flagged; IDs are cited, so they are never renumbered.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEDGER = os.path.join(ROOT, "docs", "RULINGS.md")
MONTHS = os.path.join(ROOT, "docs", "rulings")
BEGIN = "<!-- INDEX:BEGIN - generated by scripts/rulings_index.py; do not edit by hand -->"
END = "<!-- INDEX:END -->"
HEAD = re.compile(r"^## (RUL-(\d{4})-(\d{2})-(\d{2})-(\d+))\b(.*)$")
ID_RE = re.compile(r"RUL-\d{4}-\d{2}-\d{2}-\d+")


def split_entries(text):
    """(preamble, [(id, month, entry_text)]) where entry_text runs from its heading to the next ## heading."""
    lines = text.split("\n")
    pre, entries, cur = [], [], None
    for line in lines:
        m = HEAD.match(line)
        if m:
            cur = [m.group(1), f"{m.group(2)}-{m.group(3)}", [line]]
            entries.append(cur)
        elif line.startswith("## ") and cur is not None:
            # a non-ruling section after entries ends the entry; keep it in the preamble
            cur = None
            pre.append(line)
        elif cur is not None:
            cur[2].append(line)
        else:
            pre.append(line)
    return "\n".join(pre), [(i, mo, "\n".join(body).rstrip() + "\n") for i, mo, body in entries]


def meta(entry):
    first = entry.split("\n", 1)[0]
    title = HEAD.match(first).group(6).strip().lstrip("—-–: ").strip()
    st = re.search(r"^\*\*Status:\*\*\s*(.+?)\s*$", entry, re.M)
    status = re.sub(r"[.,;\s].*$", "", st.group(1).strip()).upper() if st else "?"
    sup = re.search(r"^\*\*Supersedes:\*\*\s*(.+?)\s*$", entry, re.M)
    supersedes = ID_RE.findall(sup.group(1)) if sup else []
    return title, status, supersedes


def month_path(month):
    return os.path.join(MONTHS, f"{month}.md")


def month_header(month):
    return (f"# Rulings, {month}\n\nFull entries, in the order they were written. The index and the ledger's rules are "
            "in `docs/RULINGS.md`; add a new ruling at the end of the current month's file, then run "
            "`python3 scripts/rulings_index.py`.\n\n---\n\n")


def read_months():
    out = []
    if not os.path.isdir(MONTHS):
        return out
    for name in sorted(os.listdir(MONTHS)):
        if re.fullmatch(r"\d{4}-\d{2}\.md", name):
            _, entries = split_entries(open(os.path.join(MONTHS, name), encoding="utf-8").read())
            out += [(i, mo, e, name) for i, mo, e in entries]
    return out


def render_index(all_entries):
    by_id = {}
    for i, _, e, _ in all_entries:
        by_id.setdefault(i, []).append(e)
    superseded_by = {}
    for i, _, e, _ in all_entries:
        for old in meta(e)[2]:
            superseded_by.setdefault(old, []).append(i)
    rows = ["| ID | Ruling | Status | File |", "|---|---|---|---|"]
    for i, mo, e, name in all_entries:
        title, status, _ = meta(e)
        note = ""
        if i in superseded_by:
            note = " (superseded by " + ", ".join(sorted(set(superseded_by[i]))) + ")"
        if len(by_id[i]) > 1:
            note += " (duplicate ID)"
        title = title.replace("|", "\\|")
        rows.append(f"| {i} | {title}{note} | {status} | [{name}](rulings/{name}) |")
    active = sum(1 for _, _, e, _ in all_entries if meta(e)[1] == "ACTIVE")
    head = (f"{len(all_entries)} rulings ({active} ACTIVE) across {len({n for *_, n in all_entries})} month files. "
            "Read the full entry in its month file before relying on one.")
    return BEGIN + "\n\n" + head + "\n\n" + "\n".join(rows) + "\n\n" + END


def build(check=False):
    ledger = open(LEDGER, encoding="utf-8").read()
    pre, stray = split_entries(ledger)
    problems = []
    if stray:
        if check:
            problems.append(f"{len(stray)} ruling(s) written in docs/RULINGS.md; run scripts/rulings_index.py to move them "
                            f"to docs/rulings/: {', '.join(i for i, _, _ in stray[:6])}")
        else:
            os.makedirs(MONTHS, exist_ok=True)
            for i, mo, e in stray:
                p = month_path(mo)
                text = open(p, encoding="utf-8").read() if os.path.exists(p) else month_header(mo)
                text = text.rstrip("\n") + "\n\n" + e
                open(p, "w", encoding="utf-8").write(text if text.endswith("\n") else text + "\n")
    all_entries = read_months()
    # entries filed under the wrong month
    for i, mo, _, name in all_entries:
        if name != f"{mo}.md":
            problems.append(f"{i} is in {name}; its date puts it in {mo}.md")
    index = render_index(all_entries)
    base = pre
    if BEGIN in base:
        a, rest = base.split(BEGIN, 1)
        b = rest.split(END, 1)[1] if END in rest else ""
        new_ledger = a.rstrip() + "\n\n" + index + b.rstrip("\n") + "\n" if b.strip() else a.rstrip() + "\n\n" + index + "\n"
    else:
        new_ledger = base.rstrip() + "\n\n## Index\n\n" + index + "\n"
    if check:
        if not stray and new_ledger != ledger:
            problems.append("docs/RULINGS.md index is stale; run python3 scripts/rulings_index.py")
        for p in problems:
            print("rulings_index:", p)
        print(f"rulings_index: {len(all_entries)} rulings; {'stale' if problems else 'index current'}")
        return 1 if problems else 0
    open(LEDGER, "w", encoding="utf-8").write(new_ledger)
    for p in problems:
        print("rulings_index:", p)
    print(f"rulings_index: {len(all_entries)} rulings indexed ({len(stray)} moved from docs/RULINGS.md)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv))
