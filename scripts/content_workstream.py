def selftest() -> int:
    import copy
    import tempfile

    failures: list[str] = []

    def want(condition: bool, label: str) -> None:
        print(("  ok   " if condition else "  FAIL ") + label)
        if not condition:
            failures.append(label)

    def has(errors: list[str], needle: str) -> bool:
        return any(needle in e for e in errors)

    with tempfile.TemporaryDirectory() as raw_tmp:
        repo = Path(raw_tmp) / "repo"
        (repo / "docs").mkdir(parents=True)
        (repo / "docs" / "00_INDEX.md").write_text("fixture", encoding="utf-8")
        (repo / WORKSTREAMS_DIR / "fixture").mkdir(parents=True)
        base = _valid_fixture(repo)
        source = repo / WORKSTREAMS_DIR / "fixture" / "roadmap.json"
        source.write_text(json.dumps(base), encoding="utf-8")

        print("a valid roadmap")
        want(validate(base, repo, source) == [], "a well-formed roadmap validates with zero errors")

        print("\ngraph faults")
        bad = copy.deepcopy(base)
        bad["tasks"][1]["id"] = "design.structure"
        want(has(validate(bad, repo, source), "duplicate task id"), "duplicate task ids are rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][1]["depends_on"] = ["nope.missing"]
        want(has(validate(bad, repo, source), "unknown task"), "a missing dependency is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["depends_on"] = ["build.manifest"]
        want(has(validate(bad, repo, source), "dependency cycle"), "a dependency cycle is detected")

        bad = copy.deepcopy(base)
        bad["tasks"][1]["depends_on"] = ["art.scene_characters"]
        want(has(validate(bad, repo, source), "depends on itself"), "self-dependency is rejected")

        print("\nstatus/dependency faults")
        bad = copy.deepcopy(base)
        bad["tasks"][0]["status"] = "PLANNED"
        bad["tasks"][0]["evidence"] = []
        want(
            has(validate(bad, repo, source), "READY but depends on unfinished"),
            "a READY task with an unfinished dependency is rejected",
        )

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = []
        want(has(validate(bad, repo, source), "COMPLETE with no evidence"), "a COMPLETE task without evidence is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][1]["status"] = "BLOCKED"
        want(has(validate(bad, repo, source), "names no blocker"), "a BLOCKED task without a blocker is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][1]["blockers"] = ["something"]
        want(has(validate(bad, repo, source), "still carries blockers"), "a READY task that still carries blockers is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][1]["status"] = "IN_PROGRESS"
        want(has(validate(bad, repo, source), "without a resume_note"), "an IN_PROGRESS task without a resume_note is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][1]["status"] = "NOPE"
        want(has(validate(bad, repo, source), "status must be one of"), "an unknown status is rejected")

        print("\nCOMPLETE needs a verifiable anchor, not a claim")
        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "note", "ref": "done"}]
        want(has(validate(bad, repo, source), "no evidence item is a verifiable anchor"),
             "a note-only COMPLETE is rejected")

        for kind in SOURCED_KINDS:
            bad = copy.deepcopy(base)
            bad["tasks"][0]["evidence"] = [{"kind": kind, "ref": "dauntless approved it in chat"}]
            want(has(validate(bad, repo, source), "no evidence item is a verifiable anchor"),
                 f"free-text {kind} evidence alone cannot close a task")

            bad = copy.deepcopy(base)
            bad["tasks"][0]["evidence"] = [
                {"kind": kind, "ref": "approved", "source": "docs/00_INDEX.md"}
            ]
            want(validate(bad, repo, source) == [],
                 f"{kind} evidence naming a committed source does close a task")

            bad = copy.deepcopy(base)
            bad["tasks"][0]["evidence"] = [
                {"kind": kind, "ref": "approved", "source": "docs/gone.md"}
            ]
            want(has(validate(bad, repo, source), "source docs/gone.md does not exist"),
                 f"{kind} evidence naming a missing source is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [
            {"kind": "approval", "ref": "x", "source": "/mnt/data/approval.txt"}
        ]
        want(has(validate(bad, repo, source), "ephemeral"),
             "a sandbox evidence source is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "note", "ref": "done"},
                                       {"kind": "path", "ref": "docs/00_INDEX.md"}]
        want(validate(bad, repo, source) == [],
             "a note alongside a real anchor is fine; the anchor is what counts")

        for label, ref in (("too short", "abc123"),
                           ("non-hex", "z" * 40),
                           ("uppercase", "A" * 40)):
            bad = copy.deepcopy(base)
            bad["tasks"][0]["evidence"] = [{"kind": "sha", "ref": ref}]
            want(has(validate(bad, repo, source), "sha must be"),
                 f"a malformed sha is rejected ({label})")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "sha", "ref": "e35b84e2290d1a00e298a58344a3eb0b4da58905"}]
        want(validate(bad, repo, source) == [], "an exact 40-hex sha closes a task")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "capture", "ref": "docs/00_INDEX.md"}]
        want(validate(bad, repo, source) == [], "an existing capture closes a task")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "path", "ref": "docs/00_INDEX.md"}]
        want(validate(bad, repo, source) == [], "an existing path closes a task")

        print("\nworkstream-level coherence")
        bad = copy.deepcopy(base)
        bad["status"] = "COMPLETE"
        errs = validate(bad, repo, source)
        want(has(errs, "workstream is COMPLETE but"), "a COMPLETE workstream with unsettled tasks is rejected")
        want(has(errs, "art.scene_characters (READY)") and has(errs, "build.manifest (PLANNED)"),
             "the rejection names every unsettled task")

        settled = copy.deepcopy(base)
        settled["status"] = "COMPLETE"
        settled["tasks"][1]["status"] = "SKIPPED"
        settled["tasks"][2]["status"] = "SUPERSEDED"
        want(validate(settled, repo, source) == [],
             "a COMPLETE workstream whose tasks are all COMPLETE/SKIPPED/SUPERSEDED is accepted")

        active = copy.deepcopy(base)
        active["tasks"][2]["status"] = "BLOCKED"
        active["tasks"][2]["blockers"] = ["waiting on the user"]
        want(validate(active, repo, source) == [],
             "an ACTIVE workstream may hold READY and BLOCKED work together")

        print("\nresource durability")
        bad = copy.deepcopy(base)
        bad["tasks"][1]["required_resources"] = [{"path": "docs/gone.md", "why": "x"}]
        want(
            has(validate(bad, repo, source), "cannot be READY"),
            "a READY task whose required resource is missing is rejected",
        )

        for sandbox in ("/mnt/data/art.zip", "/tmp/x.webp", "sandbox:/x.png", "~/x.png"):
            bad = copy.deepcopy(base)
            bad["tasks"][1]["required_resources"] = [{"path": sandbox, "why": "x"}]
            want(
                has(validate(bad, repo, source), "ephemeral") or has(validate(bad, repo, source), "absolute"),
                f"a sandbox/absolute resource path is rejected: {sandbox}",
            )

        bad = copy.deepcopy(base)
        bad["tasks"][1]["required_resources"] = [{"path": "docs/../../etc/passwd", "why": "x"}]
        want(has(validate(bad, repo, source), "contains '..'"), "a traversing resource path is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "path", "ref": "/mnt/data/out.zip"}]
        want(has(validate(bad, repo, source), "ephemeral"), "sandbox evidence is rejected")

        bad = copy.deepcopy(base)
        bad["tasks"][0]["evidence"] = [{"kind": "path", "ref": "docs/gone.md"}]
        want(has(validate(bad, repo, source), "does not exist"), "evidence pointing at a missing file is rejected")

        bad = copy.deepcopy(base)
        bad["slug"] = "other"
        want(has(validate(bad, repo, source), "does not match its directory"), "a slug/directory mismatch is rejected")

        bad = copy.deepcopy(base)
        bad["version"] = 99
        want(has(validate(bad, repo, source), "version must be"), "a wrong schema version is rejected")

        print("\ndeterminism")
        want(render_roadmap_md(base) == render_roadmap_md(base), "ROADMAP render is deterministic")
        want(render_index_md([base]) == render_index_md([base]), "INDEX render is deterministic")
        want(GENERATED_BANNER in render_roadmap_md(base), "the ROADMAP says it is generated")
        want(GENERATED_BANNER in render_index_md([base]), "the INDEX says it is generated")
        reordered = copy.deepcopy(base)
        reordered["resources"] = list(base["resources"])
        want(render_roadmap_md(reordered) == render_roadmap_md(base), "render depends only on roadmap content")

        print("\ninit packets")
        packet, ok = init_packet(base, find_task(base, "art.scene_characters"), repo)
        text = "\n".join(packet)
        want(ok, "a READY task initializes")
        want(text == "\n".join(init_packet(base, find_task(base, "art.scene_characters"), repo)[0]), "init output is deterministic")
        for needle in ("OBJECTIVE", "SCOPE", "DEPENDENCIES", "READ FIRST", "DELIVERABLES", "COMPLETION GATES", "RECORD RESULTS"):
            want(needle in text, f"the packet carries the {needle} section")
        want("docs/00_INDEX.md" in text, "the packet routes the global precedence file")
        want("design.structure: COMPLETE" in text, "the packet reports upstream dependency status")

        packet, ok = init_packet(base, find_task(base, "build.manifest"), repo)
        text = "\n".join(packet)
        want(not ok, "a PLANNED downstream task refuses to initialize")
        want("STOP" in text and "art.scene_characters is READY" in text, "the refusal names the unfinished dependency")
        want("Executable instead" in text, "the refusal offers an actionable alternative")

        blocked = copy.deepcopy(base)
        blocked["tasks"][1]["status"] = "BLOCKED"
        blocked["tasks"][1]["blockers"] = ["bytes were never committed"]
        packet, ok = init_packet(blocked, find_task(blocked, "art.scene_characters"), repo)
        want(not ok and "bytes were never committed" in "\n".join(packet), "a BLOCKED task refuses and states the blocker")

        print("\nlookup")
        want(find_task(base, "ART.SCENE_CHARACTERS")["id"] == "art.scene_characters", "task lookup is case-insensitive")
        want(resolve_workstream(repo, "fixture") == source, "workstream resolves by slug")
        want(resolve_workstream(repo, "Fixture Event") == source, "workstream resolves by unambiguous title")

    _selftest_new(want, has)

    print()
    if failures:
        print(f"{len(failures)} FAILED")
        for label in failures:
            print(f"  - {label}")
        return 1
    print("content_workstream selftest: all checks passed")
    return 0


