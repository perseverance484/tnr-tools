#!/usr/bin/env python3
"""content_workstream.py - repository-backed content workstreams.

A top-level planning conversation commits a workstream; later specialised
conversations initialize from it. The repository, not a predecessor chat, is the
bridge between them.

    Initialize session from repo. Workstream: One Perfect Crop. Task: art.scene_characters.

From that one line a fresh session reconstructs the project, what is already
done, the selected task's scope, its dependencies, the exact repository
resources to read, the expected outputs, the completion gates, and where results
get recorded.

WHAT THIS IS NOT
  The roadmap is coordination state, never canon. It owns task decomposition,
  status, dependencies, pointers, deliverables, gates and evidence. It does not
  restate quest mechanics, prose, doctrine, engine laws, generated contracts or
  art specs - those keep their existing owners and the roadmap links to them.
  It does not replace state/active-context.md or state/status.json; it is
  content-project coordination beneath the existing repository operating system,
  and docs/00_INDEX.md remains the only precedence table.

LAYOUT
  state/workstreams/INDEX.md               generated projection of all workstreams
  state/workstreams/<slug>/roadmap.json    canonical coordination source (edit this)
  state/workstreams/<slug>/ROADMAP.md      generated projection

COMMANDS
  validate <path>|--all     schema + graph + status + resource invariants
  render <path>|--all       regenerate ROADMAP.md and INDEX.md deterministically
  render --check            fail if a generated projection is stale
  list                      every workstream with progress and current work
  next <slug>               executable and blocked tasks right now
  init <slug> --task <id>   the session initialization packet
  --selftest                socket-free tests over synthesized fixtures

Stdlib only, deterministic, socket-free. Nothing here contacts ChatGPT, GitHub,
the TNR API, or any image generator.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SCHEMA = "tnr.content_workstream"
VERSION = 1

WORKSTREAMS_DIR = "state/workstreams"

TASK_STATUSES = (
    "PLANNED",
    "READY",
    "IN_PROGRESS",
    "BLOCKED",
    "REVIEW",
    "COMPLETE",
    "SKIPPED",
    "SUPERSEDED",
)
WORKSTREAM_STATUSES = ("PLANNED", "ACTIVE", "BLOCKED", "COMPLETE", "SUPERSEDED")

# A dependency in one of these is settled enough for a dependent task to start.
SATISFIED = ("COMPLETE", "SKIPPED", "SUPERSEDED")
# These statuses assert the task is executable now, so their inputs must be real.
EXECUTABLE = ("READY", "IN_PROGRESS")
# Statuses that close a task and therefore owe evidence.
CLOSING = ("COMPLETE",)

AREAS = (
    "design",
    "prose",
    "research",
    "art",
    "admin",
    "build",
    "review",
    "production",
    "tooling",
)

EVIDENCE_KINDS = (
    "path",       # a committed repository artifact
    "capture",    # a committed capture/result bundle
    "sha",        # an exact commit SHA
    "decision",   # a recorded user/content-admin decision
    "validator",  # a named validator/gate result
    "approval",   # recorded user acceptance
    "note",       # anything else, used sparingly
)

# Inputs that live here are not durable and must never back a READY task.
EPHEMERAL_MARKERS = ("/mnt/data", "/tmp/", "sandbox:", "file:///", "~/", "attachment:")

PROGRESS_ORDER = {name: i for i, name in enumerate(TASK_STATUSES)}

GENERATED_BANNER = (
    "<!-- GENERATED by scripts/content_workstream.py - edit roadmap.json, then "
    "`python3 scripts/content_workstream.py render --all`. Never edit this file. -->"
)


def repo_root_default() -> Path:
    here = Path(__file__).resolve().parents[1]
    if (here / "docs" / "00_INDEX.md").exists():
        return here
    return Path.cwd()


