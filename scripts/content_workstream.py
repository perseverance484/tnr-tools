def load_roadmap(path: Path) -> dict:
    try:
        with path.open(encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        raise SystemExit(f"content_workstream: roadmap not found: {path}")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"content_workstream: {path} is not valid JSON: {exc}")


def roadmap_paths(repo_root: Path) -> list[Path]:
    base = repo_root / WORKSTREAMS_DIR
    if not base.is_dir():
        return []
    return sorted(p for p in base.glob("*/roadmap.json") if p.is_file())


def resolve_workstream(repo_root: Path, name: str) -> Path:
    """Match by slug, then unambiguously by title. Deterministic either way."""
    direct = repo_root / WORKSTREAMS_DIR / name / "roadmap.json"
    if direct.is_file():
        return direct
    wanted = name.strip().lower()
    hits = []
    for path in roadmap_paths(repo_root):
        data = load_roadmap(path)
        if data.get("slug", "").lower() == wanted or str(data.get("title", "")).lower() == wanted:
            hits.append(path)
    if len(hits) == 1:
        return hits[0]
    if not hits:
        known = ", ".join(p.parent.name for p in roadmap_paths(repo_root)) or "(none)"
        raise SystemExit(f"content_workstream: no workstream matches {name!r}. Known: {known}")
    raise SystemExit(f"content_workstream: {name!r} is ambiguous; use the slug")


