def progress(roadmap: dict) -> dict[str, int]:
    counts = {name: 0 for name in TASK_STATUSES}
    for task in roadmap.get("tasks", []):
        status = task.get("status")
        if status in counts:
            counts[status] += 1
    return counts


def progress_line(roadmap: dict) -> str:
    counts = progress(roadmap)
    total = sum(counts.values())
    done = counts["COMPLETE"] + counts["SKIPPED"]
    parts = [f"{name.lower()} {n}" for name, n in counts.items() if n]
    return f"{done}/{total} settled - " + ", ".join(parts)


def tasks_by_status(roadmap: dict, *statuses: str) -> list[dict]:
    return [t for t in roadmap.get("tasks", []) if t.get("status") in statuses]


def unmet_deps(roadmap: dict, task: dict) -> list[tuple[str, str]]:
    by_id = {t["id"]: t for t in roadmap.get("tasks", []) if t.get("id")}
    out = []
    for dep in task.get("depends_on", []):
        other = by_id.get(dep)
        status = other.get("status") if other else "UNKNOWN"
        if status not in SATISFIED:
            out.append((dep, status))
    return out


def find_task(roadmap: dict, task_id: str) -> dict:
    wanted = task_id.strip().lower()
    exact = [t for t in roadmap.get("tasks", []) if str(t.get("id", "")).lower() == wanted]
    if len(exact) == 1:
        return exact[0]
    titled = [t for t in roadmap.get("tasks", []) if str(t.get("title", "")).lower() == wanted]
    if len(titled) == 1:
        return titled[0]
    known = ", ".join(t.get("id", "?") for t in roadmap.get("tasks", []))
    raise SystemExit(f"content_workstream: no task matches {task_id!r}. Known task ids: {known}")


