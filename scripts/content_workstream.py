def _bad_path(value: str) -> str | None:
    """Return a reason string if this is not a durable repository-relative path."""
    if not isinstance(value, str) or not value.strip():
        return "empty path"
    for marker in EPHEMERAL_MARKERS:
        if marker in value:
            return f"points at ephemeral/sandbox location ({marker!r}); not durable repository evidence"
    if value.startswith("/") or (len(value) > 1 and value[1] == ":"):
        return "absolute filesystem path; use a repository-relative path"
    if ".." in Path(value).parts:
        return "contains '..'"
    return None


def _cycles(tasks: list[dict]) -> list[list[str]]:
    graph = {t["id"]: [d for d in t.get("depends_on", []) if isinstance(d, str)] for t in tasks if t.get("id")}
    found: list[list[str]] = []
    state: dict[str, int] = {}

    def walk(node: str, trail: list[str]) -> None:
        state[node] = 1
        for nxt in graph.get(node, []):
            if nxt not in graph:
                continue
            if state.get(nxt) == 1:
                cycle = trail[trail.index(nxt):] + [nxt] if nxt in trail else [nxt, node, nxt]
                if cycle not in found:
                    found.append(cycle)
            elif state.get(nxt, 0) == 0:
                walk(nxt, trail + [nxt])
        state[node] = 2

    for node in sorted(graph):
        if state.get(node, 0) == 0:
            walk(node, [node])
    return found


def validate(roadmap: dict, repo_root: Path, source: Path | None = None) -> list[str]:
    errors: list[str] = []

    def bad(msg: str) -> None:
        errors.append(msg)

    if roadmap.get("schema") != SCHEMA:
        bad(f"schema must be {SCHEMA!r}, found {roadmap.get('schema')!r}")
    if roadmap.get("version") != VERSION:
        bad(f"version must be {VERSION}, found {roadmap.get('version')!r}")

    for field in ("slug", "title", "content_type", "status", "objective"):
        if not roadmap.get(field):
            bad(f"workstream field {field!r} is required")

    slug = roadmap.get("slug")
    if isinstance(slug, str) and slug:
        if not slug.replace("_", "").replace("-", "").isalnum():
            bad(f"slug {slug!r} must be alphanumeric with _ or -")
        if source is not None and source.parent.name != slug:
            bad(f"slug {slug!r} does not match its directory {source.parent.name!r}")

    if roadmap.get("status") not in WORKSTREAM_STATUSES:
        bad(f"workstream status must be one of {', '.join(WORKSTREAM_STATUSES)}")

    for position, res in enumerate(roadmap.get("resources", [])):
        label = f"resources[{position}]"
        if not isinstance(res, dict):
            bad(f"{label} is not an object")
            continue
        reason = _bad_path(res.get("path", ""))
        if reason:
            bad(f"{label}: {reason}")
        elif not (repo_root / res["path"]).exists():
            bad(f"{label}: {res['path']} does not exist in the repository")
        if not res.get("why"):
            bad(f"{label}: 'why' is required - a pointer without a reason is noise")

    tasks = roadmap.get("tasks")
    if not isinstance(tasks, list) or not tasks:
        bad("tasks must be a non-empty array")
        return errors

    seen: dict[str, int] = {}
    by_id: dict[str, dict] = {}
    for position, task in enumerate(tasks):
        if not isinstance(task, dict):
            bad(f"tasks[{position}] is not an object")
            continue
        tid = task.get("id")
        if not tid:
            bad(f"tasks[{position}]: id is required")
            continue
        if tid in seen:
            bad(f"task {tid!r}: duplicate task id (also at index {seen[tid]})")
        seen[tid] = position
        by_id[tid] = task

    for tid, task in by_id.items():
        for field in ("title", "area", "status", "owner", "objective"):
            if not task.get(field):
                bad(f"task {tid!r}: field {field!r} is required")

        status = task.get("status")
        if status not in TASK_STATUSES:
            bad(f"task {tid!r}: status must be one of {', '.join(TASK_STATUSES)}")
        if task.get("area") not in AREAS:
            bad(f"task {tid!r}: area must be one of {', '.join(AREAS)}")

        for field in ("scope", "deliverables", "completion_gates"):
            value = task.get(field)
            if not isinstance(value, list) or not value:
                bad(f"task {tid!r}: {field} must be a non-empty list")

        deps = task.get("depends_on", [])
        if not isinstance(deps, list):
            bad(f"task {tid!r}: depends_on must be a list")
            deps = []
        for dep in deps:
            if dep == tid:
                bad(f"task {tid!r}: depends on itself")
            elif dep not in by_id:
                bad(f"task {tid!r}: depends_on references unknown task {dep!r}")

        unmet = [d for d in deps if d in by_id and by_id[d].get("status") not in SATISFIED]
        if status in EXECUTABLE and unmet:
            named = ", ".join(f"{d} ({by_id[d].get('status')})" for d in unmet)
            bad(f"task {tid!r} is {status} but depends on unfinished {named}")
        if status in CLOSING and unmet:
            bad(f"task {tid!r} is COMPLETE but depends on unfinished {', '.join(unmet)}")

        resources = task.get("required_resources", [])
        if not isinstance(resources, list):
            bad(f"task {tid!r}: required_resources must be a list")
            resources = []
        for position, res in enumerate(resources):
            label = f"task {tid!r} required_resources[{position}]"
            if not isinstance(res, dict):
                bad(f"{label} is not an object")
                continue
            reason = _bad_path(res.get("path", ""))
            if reason:
                bad(f"{label}: {reason}")
                continue
            if not res.get("why"):
                bad(f"{label}: 'why' is required")
            if not (repo_root / res["path"]).exists():
                if status in EXECUTABLE:
                    bad(
                        f"{label}: {res['path']} does not exist, so {tid!r} cannot be {status}. "
                        "READY means a fresh session can execute it from repository evidence alone."
                    )
                else:
                    bad(f"{label}: {res['path']} does not exist in the repository")

        blockers = task.get("blockers") or []
        decisions = task.get("open_decisions") or []
        if status == "BLOCKED" and not (blockers or decisions):
            bad(f"task {tid!r} is BLOCKED but names no blocker or open decision")
        if status in EXECUTABLE and blockers:
            bad(f"task {tid!r} is {status} but still carries blockers: {'; '.join(map(str, blockers))}")

        evidence = task.get("evidence") or []
        if not isinstance(evidence, list):
            bad(f"task {tid!r}: evidence must be a list")
            evidence = []
        if status in CLOSING and not evidence:
            bad(
                f"task {tid!r} is COMPLETE with no evidence. A conversation saying it is done "
                "is not evidence; record artifacts, captures, SHAs, validator results or approval."
            )
        if status == "PLANNED" and evidence:
            bad(f"task {tid!r} is PLANNED but already carries evidence")
        for position, item in enumerate(evidence):
            label = f"task {tid!r} evidence[{position}]"
            if not isinstance(item, dict):
                bad(f"{label} is not an object")
                continue
            kind = item.get("kind")
            if kind not in EVIDENCE_KINDS:
                bad(f"{label}: kind must be one of {', '.join(EVIDENCE_KINDS)}")
            if not item.get("ref"):
                bad(f"{label}: 'ref' is required")
                continue
            if kind in ("path", "capture"):
                reason = _bad_path(item["ref"])
                if reason:
                    bad(f"{label}: {reason}")
                elif not (repo_root / item["ref"]).exists():
                    bad(f"{label}: {item['ref']} does not exist in the repository")

        if status == "IN_PROGRESS" and not task.get("resume_note"):
            bad(
                f"task {tid!r} is IN_PROGRESS without a resume_note. Partial work needs a durable "
                "note or the next session restarts it."
            )

    for cycle in _cycles([t for t in tasks if isinstance(t, dict) and t.get("id")]):
        bad(f"dependency cycle: {' -> '.join(cycle)}")

    return errors


