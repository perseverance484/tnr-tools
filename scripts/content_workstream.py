def render_roadmap_md(roadmap: dict) -> str:
    out: list[str] = [GENERATED_BANNER, ""]
    out.append(f"# {roadmap['title']} - content workstream roadmap")
    out.append("")
    out.append(f"- **Slug:** `{roadmap['slug']}`")
    out.append(f"- **Content type:** {roadmap['content_type']}")
    out.append(f"- **Status:** {roadmap['status']}")
    out.append(f"- **Progress:** {progress_line(roadmap)}")
    out.append("")
    out.append(f"{roadmap['objective']}")
    out.append("")
    out.append(
        "This roadmap is **coordination state, not canon.** It points at the authoritative "
        "sources below and never restates them. `docs/00_INDEX.md` remains the only precedence "
        "table; `state/active-context.md` and `state/status.json` remain the global session state."
    )
    out.append("")

    resources = roadmap.get("resources", [])
    if resources:
        out.append("## Workstream resources")
        out.append("")
        out.append("| Path | Why |")
        out.append("| --- | --- |")
        for res in resources:
            out.append(f"| `{res['path']}` | {res['why']} |")
        out.append("")

    out.append("## Tasks")
    out.append("")
    out.append("| Task | Status | Owner | Depends on | Scope |")
    out.append("| --- | --- | --- | --- | --- |")
    for task in roadmap["tasks"]:
        deps = ", ".join(f"`{d}`" for d in task.get("depends_on", [])) or "-"
        scope = str(task.get("scope", ["-"])[0])
        out.append(
            f"| `{task['id']}` | {task['status']} | {task['owner']} | {deps} | {scope} |"
        )
    out.append("")

    ready = tasks_by_status(roadmap, "READY")
    in_progress = tasks_by_status(roadmap, "IN_PROGRESS")
    if ready or in_progress:
        out.append("## Executable now")
        out.append("")
        for task in in_progress:
            out.append(f"- **`{task['id']}`** (IN_PROGRESS) - {task['title']}")
            out.append(f"  - resume: {task.get('resume_note', '')}")
        for task in ready:
            out.append(f"- **`{task['id']}`** (READY) - {task['title']}")
            out.append(
                f"  - `python3 scripts/content_workstream.py init {roadmap['slug']} --task {task['id']}`"
            )
        out.append("")

    blocked = tasks_by_status(roadmap, "BLOCKED")
    if blocked:
        out.append("## Blocked")
        out.append("")
        for task in blocked:
            out.append(f"### `{task['id']}` - {task['title']}")
            out.append("")
            for item in task.get("blockers", []):
                out.append(f"- BLOCKER: {item}")
            for item in task.get("open_decisions", []):
                out.append(f"- OPEN DECISION (user-owned): {item}")
            out.append("")

    open_elsewhere = [
        (t, d)
        for t in roadmap["tasks"]
        if t.get("status") != "BLOCKED"
        for d in t.get("open_decisions", [])
    ]
    if open_elsewhere:
        out.append("## Other open decisions")
        out.append("")
        for task, decision in open_elsewhere:
            out.append(f"- `{task['id']}`: {decision}")
        out.append("")

    waiting = [
        t for t in roadmap["tasks"] if t.get("status") == "PLANNED" and unmet_deps(roadmap, t)
    ]
    if waiting:
        out.append("## Waiting on dependencies")
        out.append("")
        for task in waiting:
            unmet = ", ".join(f"`{d}` ({s})" for d, s in unmet_deps(roadmap, task))
            out.append(f"- `{task['id']}` - waiting on {unmet}")
        out.append("")

    done = tasks_by_status(roadmap, "COMPLETE", "SKIPPED", "SUPERSEDED")
    if done:
        out.append("## Completed, with evidence")
        out.append("")
        for task in done:
            out.append(f"### `{task['id']}` - {task['title']} ({task['status']})")
            out.append("")
            for item in task.get("evidence", []):
                note = f" - {item['note']}" if item.get("note") else ""
                if item.get("kind") in ("path", "capture"):
                    out.append(f"- {item['kind']}: `{item['ref']}`{note}")
                else:
                    out.append(f"- {item['kind']}: {item['ref']}{note}")
            out.append("")

    out.append("## Task detail")
    out.append("")
    for task in roadmap["tasks"]:
        out.append(f"### `{task['id']}` - {task['title']}")
        out.append("")
        role = f", lead role {task['lead_role']}" if task.get("lead_role") else ""
        out.append(f"**{task['status']}** - area {task['area']}, owner {task['owner']}{role}")
        out.append("")
        out.append(task["objective"])
        out.append("")
        out.append("**Scope**")
        out.append("")
        for item in task.get("scope", []):
            out.append(f"- {item}")
        out.append("")
        if task.get("out_of_scope"):
            out.append("**Out of scope**")
            out.append("")
            for item in task["out_of_scope"]:
                out.append(f"- {item}")
            out.append("")
        if task.get("required_resources"):
            out.append("**Required resources**")
            out.append("")
            for res in task["required_resources"]:
                out.append(f"- `{res['path']}` - {res['why']}")
            out.append("")
        out.append("**Deliverables**")
        out.append("")
        for item in task.get("deliverables", []):
            out.append(f"- {item}")
        out.append("")
        out.append("**Completion gates**")
        out.append("")
        for item in task.get("completion_gates", []):
            out.append(f"- {item}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_index_md(roadmaps: list[dict]) -> str:
    out: list[str] = [GENERATED_BANNER, ""]
    out.append("# Content workstreams")
    out.append("")
    out.append(
        "Coordination projection for repository-backed content workstreams. This is **not** the "
        "global board: `state/active-context.md` and `state/status.json` remain the session state, "
        "and `docs/00_INDEX.md` remains the precedence table. The workflow is "
        "`docs/workflows/CONTENT_WORKSTREAM.md`."
    )
    out.append("")
    if not roadmaps:
        out.append("_No workstreams yet._")
        return "\n".join(out) + "\n"

    out.append("| Workstream | Slug | Type | Status | Progress | Roadmap |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for roadmap in roadmaps:
        out.append(
            f"| {roadmap['title']} | `{roadmap['slug']}` | {roadmap['content_type']} | "
            f"{roadmap['status']} | {progress_line(roadmap)} | "
            f"[`ROADMAP.md`]({roadmap['slug']}/ROADMAP.md) |"
        )
    out.append("")

    for roadmap in roadmaps:
        out.append(f"## {roadmap['title']}")
        out.append("")
        out.append(f"`{WORKSTREAMS_DIR}/{roadmap['slug']}/roadmap.json`")
        out.append("")
        current = tasks_by_status(roadmap, "IN_PROGRESS") + tasks_by_status(roadmap, "READY")
        if current:
            out.append("**Executable now**")
            out.append("")
            for task in current:
                out.append(f"- `{task['id']}` ({task['status']}) - {task['title']}")
            out.append("")
        else:
            out.append("**Executable now:** none.")
            out.append("")
        blocked = tasks_by_status(roadmap, "BLOCKED")
        if blocked:
            out.append("**Blocked**")
            out.append("")
            for task in blocked:
                reasons = (task.get("blockers") or []) + (task.get("open_decisions") or [])
                out.append(f"- `{task['id']}` - {reasons[0] if reasons else 'see roadmap'}")
            out.append("")
        out.append(
            f"Start a session: `python3 scripts/content_workstream.py init {roadmap['slug']} --task <id>`"
        )
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_all(repo_root: Path, check: bool = False, only: Path | None = None) -> int:
    paths = [only] if only else roadmap_paths(repo_root)
    roadmaps = [load_roadmap(p) for p in roadmap_paths(repo_root)]
    stale: list[str] = []
    wrote: list[str] = []

    def emit(target: Path, text: str) -> None:
        rel = target.relative_to(repo_root).as_posix()
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            print(f"same   {rel}")
            return
        if check:
            print(f"STALE  {rel}")
            stale.append(rel)
            return
        target.write_text(text, encoding="utf-8")
        print(f"wrote  {rel}")
        wrote.append(rel)

    for path in paths:
        roadmap = load_roadmap(path)
        emit(path.parent / "ROADMAP.md", render_roadmap_md(roadmap))

    index = repo_root / WORKSTREAMS_DIR / "INDEX.md"
    index.parent.mkdir(parents=True, exist_ok=True)
    emit(index, render_index_md(roadmaps))

    if check and stale:
        print(f"\n{len(stale)} generated projection(s) are stale; run render --all", file=sys.stderr)
        return 1
    print("\n" + ("all projections current (exit 0)" if check else f"{len(wrote)} file(s) written"))
    return 0


