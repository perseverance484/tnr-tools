def render_all(repo_root: Path, check: bool = False, only: Path | None = None) -> int:
    paths = [only] if only else roadmap_paths(repo_root)
    roadmaps = [load_roadmap(p) for p in roadmap_paths(repo_root)]
    stale: list[str] = []
    wrote: list[str] = []

    def emit(target: Path, text: str) -> None:
        rel = target.relative_to(repo_root).as_posix()
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            print(f"same   {rel}")
            return
        if check:
            print(f"STALE  {rel}")
            stale.append(rel)
            return
        target.write_text(text, encoding="utf-8")
        print(f"wrote  {rel}")
        wrote.append(rel)

    for path in paths:
        roadmap = load_roadmap(path)
        emit(path.parent / "ROADMAP.md", render_roadmap_md(roadmap))

    index = repo_root / WORKSTREAMS_DIR / "INDEX.md"
    index.parent.mkdir(parents=True, exist_ok=True)
    emit(index, render_index_md(roadmaps))

    if check and stale:
        print(f"\n{len(stale)} generated projection(s) are stale; run render --all", file=sys.stderr)
        return 1
    print("\n" + ("all projections current (exit 0)" if check else f"{len(wrote)} file(s) written"))
    return 0


