def render_roadmap_md(roadmap: dict) -> str:
    out: list[str] = [GENERATED_BANNER, ""]
    out.append(f"# {roadmap['title']} - content workstream roadmap")
    out.append("")
    out.append(f"- **Slug:** `{roadmap['slug']}`")
    out.append(f"- **Content type:** {roadmap['content_type']}")
    out.append(f"- **Status:** {roadmap['status']}")
    out.append(f"- **Progress:** {progress_line(roadmap)}")
    out.append("")
    out.append(f"{roadmap['objective']}")
    out.append("")
    out.append(
        "This roadmap is **coordination state, not canon.** It points at the authoritative "
        "sources below and never restates them. `docs/00_INDEX.md` remains the only precedence "
        "table; `state/active-context.md` and `state/status.json` remain the global session state."
    )
    out.append("")

    resources = roadmap.get("resources", [])
    if resources:
        out.append("## Workstream resources")
        out.append("")
        out.append("| Path | Why |")
        out.append("| --- | --- |")
        for res in resources:
            out.append(f"| `{res['path']}` | {res['why']} |")
        out.append("")

    out.append("## Tasks")
    out.append("")
    out.append("| Task | Status | Owner | Depends on | Scope |")
    out.append("| --- | --- | --- | --- | --- |")
    for task in roadmap["tasks"]:
        deps = ", ".join(f"`{d}`" for d in task.get("depends_on", [])) or "-"
        scope = str(task.get("scope", ["-"])[0])
        out.append(
            f"| `{task['id']}` | {task['status']} | {task['owner']} | {deps} | {scope} |"
        )
    out.append("")

    ready = tasks_by_status(roadmap, "READY")
    in_progress = tasks_by_status(roadmap, "IN_PROGRESS")
    if ready or in_progress:
        out.append("## Executable now")
        out.append("")
        for task in in_progress:
            out.append(f"- **`{task['id']}`** (IN_PROGRESS) - {task['title']}")
            out.append(f"  - resume: {task.get('resume_note', '')}")
        for task in ready:
            out.append(f"- **`{task['id']}`** (READY) - {task['title']}")
            out.append(
                f"  - `python3 scripts/content_workstream.py init {roadmap['slug']} --task {task['id']}`"
            )
        out.append("")

    blocked = tasks_by_status(roadmap, "BLOCKED")
    if blocked:
        out.append("## Blocked")
        out.append("")
        for task in blocked:
            out.append(f"### `{task['id']}` - {task['title']}")
            out.append("")
            for item in task.get("blockers", []):
                out.append(f"- BLOCKER: {item}")
            for item in task.get("open_decisions", []):
                out.append(f"- OPEN DECISION (user-owned): {item}")
            out.append("")

    open_elsewhere = [
        (t, d)
        for t in roadmap["tasks"]
        if t.get("status") != "BLOCKED"
        for d in t.get("open_decisions", [])
    ]
    if open_elsewhere:
        out.append("## Other open decisions")
        out.append("")
        for task, decision in open_elsewhere:
            out.append(f"- `{task['id']}`: {decision}")
        out.append("")

    waiting = [
        t for t in roadmap["tasks"] if t.get("status") == "PLANNED" and unmet_deps(roadmap, t)
    ]
    if waiting:
        out.append("## Waiting on dependencies")
        out.append("")
        for task in waiting:
            unmet = ", ".join(f"`{d}` ({s})" for d, s in unmet_deps(roadmap, task))
            out.append(f"- `{task['id']}` - waiting on {unmet}")
        out.append("")

    done = tasks_by_status(roadmap, "COMPLETE", "SKIPPED", "SUPERSEDED")
    if done:
        out.append("## Completed, with evidence")
        out.append("")
        for task in done:
            out.append(f"### `{task['id']}` - {task['title']} ({task['status']})")
            out.append("")
            for item in task.get("evidence", []):
                note = f" - {item['note']}" if item.get("note") else ""
                if item.get("kind") in ("path", "capture"):
                    out.append(f"- {item['kind']}: `{item['ref']}`{note}")
                else:
                    out.append(f"- {item['kind']}: {item['ref']}{note}")
            out.append("")

    out.append("## Task detail")
    out.append("")
    for task in roadmap["tasks"]:
        out.append(f"### `{task['id']}` - {task['title']}")
        out.append("")
        role = f", lead role {task['lead_role']}" if task.get("lead_role") else ""
        out.append(f"**{task['status']}** - area {task['area']}, owner {task['owner']}{role}")
        out.append("")
        out.append(task["objective"])
        out.append("")
        out.append("**Scope**")
        out.append("")
        for item in task.get("scope", []):
            out.append(f"- {item}")
        out.append("")
        if task.get("out_of_scope"):
            out.append("**Out of scope**")
            out.append("")
            for item in task["out_of_scope"]:
                out.append(f"- {item}")
            out.append("")
        if task.get("required_resources"):
            out.append("**Required resources**")
            out.append("")
            for res in task["required_resources"]:
                out.append(f"- `{res['path']}` - {res['why']}")
            out.append("")
        out.append("**Deliverables**")
        out.append("")
        for item in task.get("deliverables", []):
            out.append(f"- {item}")
        out.append("")
        out.append("**Completion gates**")
        out.append("")
        for item in task.get("completion_gates", []):
            out.append(f"- {item}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


