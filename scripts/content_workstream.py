def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--repo-root", type=Path, default=None)
    sub = parser.add_subparsers(dest="command")

    p_validate = sub.add_parser("validate", help="validate a roadmap")
    p_validate.add_argument("path", nargs="?", type=Path)
    p_validate.add_argument("--all", action="store_true")

    p_render = sub.add_parser("render", help="regenerate ROADMAP.md and INDEX.md")
    p_render.add_argument("path", nargs="?", type=Path)
    p_render.add_argument("--all", action="store_true")
    p_render.add_argument("--check", action="store_true", help="fail if a projection is stale")

    sub.add_parser("list", help="list workstreams")

    p_next = sub.add_parser("next", help="show executable and blocked tasks")
    p_next.add_argument("workstream")

    p_init = sub.add_parser("init", help="print the session initialization packet")
    p_init.add_argument("workstream")
    p_init.add_argument("--task", required=True)

    p_new = sub.add_parser("new", help="scaffold an optional multi-session workstream (preview unless --write)")
    p_new.add_argument("slug")
    p_new.add_argument("--title", required=True)
    p_new.add_argument("--type", required=True, dest="content_type", help="quest or event")
    p_new.add_argument("--write", action="store_true", help="create the files; without it nothing is written")
    p_new.add_argument("--json", action="store_true", help="print exactly the roadmap.json bytes to stdout")

    args = parser.parse_args(argv)
    if args.selftest:
        return selftest()
    if not args.command:
        parser.print_help()
        return 2

    repo_root = (args.repo_root or repo_root_default()).resolve()

    if args.command == "validate":
        if args.all or not args.path:
            paths = roadmap_paths(repo_root)
            if not paths:
                print("no workstreams found")
                return 0
        else:
            paths = [args.path if args.path.is_absolute() else repo_root / args.path]
        failed = 0
        for path in paths:
            roadmap = load_roadmap(path)
            errors = validate(roadmap, repo_root, path)
            rel = path.relative_to(repo_root).as_posix() if path.is_relative_to(repo_root) else str(path)
            if errors:
                failed += 1
                print(f"FAIL  {rel}  {len(errors)} error(s)", file=sys.stderr)
                for err in errors:
                    print(f"  - {err}", file=sys.stderr)
            else:
                print(f"ok    {rel}  {len(roadmap['tasks'])} tasks, {progress_line(roadmap)}")
        if failed:
            print(f"\n{failed} roadmap(s) failed validation", file=sys.stderr)
            return 1
        print(f"\n{len(paths)} roadmap(s) valid (exit 0)")
        return 0

    if args.command == "render":
        only = None
        if args.path and not args.all:
            only = args.path if args.path.is_absolute() else repo_root / args.path
        return render_all(repo_root, check=args.check, only=only)

    if args.command == "list":
        paths = roadmap_paths(repo_root)
        if not paths:
            print("no workstreams found")
            return 0
        for path in paths:
            roadmap = load_roadmap(path)
            print(f"{roadmap['slug']}  -  {roadmap['title']}  [{roadmap['status']}]")
            print(f"    {roadmap['content_type']}, {progress_line(roadmap)}")
            current = tasks_by_status(roadmap, "IN_PROGRESS") + tasks_by_status(roadmap, "READY")
            print(f"    executable now: {', '.join(t['id'] for t in current) or 'none'}")
            blocked = tasks_by_status(roadmap, "BLOCKED")
            if blocked:
                print(f"    blocked:        {', '.join(t['id'] for t in blocked)}")
            print(f"    roadmap:        {path.relative_to(repo_root).as_posix()}")
            print()
        return 0

    if args.command == "next":
        path = resolve_workstream(repo_root, args.workstream)
        roadmap = load_roadmap(path)
        print(f"{roadmap['title']} ({roadmap['slug']}) - {roadmap['status']}")
        print(f"{progress_line(roadmap)}")
        print()
        current = tasks_by_status(roadmap, "IN_PROGRESS")
        if current:
            print("IN PROGRESS")
            for task in current:
                print(f"  {task['id']}  {task['title']}")
                print(f"    resume: {task.get('resume_note', '')}")
            print()
        ready = tasks_by_status(roadmap, "READY")
        print("READY" if ready else "READY: none")
        for task in ready:
            print(f"  {task['id']}  {task['title']}")
            print(f"    init: python3 scripts/content_workstream.py init {roadmap['slug']} --task {task['id']}")
        print()
        blocked = tasks_by_status(roadmap, "BLOCKED")
        if blocked:
            print("BLOCKED")
            for task in blocked:
                print(f"  {task['id']}  {task['title']}")
                for item in task.get("blockers", []):
                    print(f"    blocker: {item}")
                for item in task.get("open_decisions", []):
                    print(f"    open decision (user-owned): {item}")
            print()
        waiting = [t for t in roadmap["tasks"] if t["status"] == "PLANNED" and unmet_deps(roadmap, t)]
        if waiting:
            print("WAITING ON DEPENDENCIES")
            for task in waiting:
                unmet = ", ".join(f"{d} ({s})" for d, s in unmet_deps(roadmap, task))
                print(f"  {task['id']}  waiting on {unmet}")
        return 0

    if args.command == "init":
        path = resolve_workstream(repo_root, args.workstream)
        roadmap = load_roadmap(path)
        errors = validate(roadmap, repo_root, path)
        if errors:
            print(f"content_workstream: {path} does not validate; fix it before initializing", file=sys.stderr)
            for err in errors:
                print(f"  - {err}", file=sys.stderr)
            return 1
        task = find_task(roadmap, args.task)
        packet, ok = init_packet(roadmap, task, repo_root)
        stream = sys.stdout if ok else sys.stderr
        print("\n".join(packet), file=stream)
        return 0 if ok else 1

    if args.command == "new":
        code, lines, text = new_workstream(
            repo_root, args.slug, args.title, args.content_type, write=args.write
        )
        if args.json and text is not None:
            sys.stdout.write(text)
            print("\n".join(lines), file=sys.stderr)
        else:
            print("\n".join(lines), file=sys.stdout if code == 0 else sys.stderr)
        return code

    parser.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
