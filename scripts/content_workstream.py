GLOBAL_AUTHORITY = [
    ("state/active-context.md", "current global session state - read first"),
    ("state/status.json", "the board"),
    ("docs/00_INDEX.md", "precedence, evidence tiers, task routing - arbitrates disagreements"),
    ("docs/RULINGS.md", "durable user rulings"),
    ("docs/workflows/CONTENT_WORKSTREAM.md", "how to work and close out a workstream task"),
]


def init_packet(roadmap: dict, task: dict, repo_root: Path) -> tuple[list[str], bool]:
    out: list[str] = []
    ok = True
    status = task.get("status")

    out.append(f"SESSION INIT - {roadmap['title']} / {task['id']}")
    out.append("=" * len(f"SESSION INIT - {roadmap['title']} / {task['id']}"))
    out.append("")
    out.append(f"Workstream : {roadmap['title']} (`{roadmap['slug']}`), {roadmap['content_type']}, {roadmap['status']}")
    out.append(f"Task       : {task['title']}")
    out.append(f"Status     : {status}")
    out.append(f"Area/owner : {task['area']} / {task['owner']}" + (f" / lead role {task['lead_role']}" if task.get("lead_role") else ""))
    out.append(f"Progress   : {progress_line(roadmap)}")
    out.append("")

    unmet = unmet_deps(roadmap, task)
    if status not in EXECUTABLE:
        ok = False
        out.append("STOP - this task is not executable.")
        out.append("")
        out.append(f"  Its status is {status}, not READY or IN_PROGRESS.")
        if unmet:
            out.append("  Unfinished dependencies:")
            for dep, dep_status in unmet:
                out.append(f"    - {dep} is {dep_status}")
        for item in task.get("blockers", []):
            out.append(f"  BLOCKER: {item}")
        for item in task.get("open_decisions", []):
            out.append(f"  OPEN DECISION (user-owned): {item}")
        out.append("")
        ready = tasks_by_status(roadmap, "READY") + tasks_by_status(roadmap, "IN_PROGRESS")
        if ready:
            out.append("  Executable instead:")
            for other in ready:
                out.append(f"    - {other['id']} ({other['status']}) - {other['title']}")
        else:
            out.append("  Nothing in this workstream is executable right now.")
        out.append("")
        out.append("  Do not start this task by inventing its missing inputs.")
        return out, ok

    out.append("OBJECTIVE")
    out.append("")
    out.append(f"  {task['objective']}")
    out.append("")
    out.append("SCOPE - this session, and only this")
    out.append("")
    for item in task.get("scope", []):
        out.append(f"  - {item}")
    if task.get("out_of_scope"):
        out.append("")
        out.append("  Out of scope:")
        for item in task["out_of_scope"]:
            out.append(f"  - {item}")
    out.append("")

    if task.get("resume_note"):
        out.append("RESUME NOTE - work already in progress")
        out.append("")
        out.append(f"  {task['resume_note']}")
        out.append("")

    out.append("DEPENDENCIES")
    out.append("")
    if task.get("depends_on"):
        by_id = {t["id"]: t for t in roadmap["tasks"]}
        for dep in task["depends_on"]:
            other = by_id.get(dep, {})
            out.append(f"  {dep}: {other.get('status', 'UNKNOWN')} - {other.get('title', '?')}")
    else:
        out.append("  none")
    out.append("")

    out.append("READ FIRST - global authority (verify the live repository head before substantive work)")
    out.append("")
    for path, why in GLOBAL_AUTHORITY:
        mark = " " if (repo_root / path).exists() else "!"
        out.append(f" {mark} {path}")
        out.append(f"     {why}")
    out.append("")

    if roadmap.get("resources"):
        out.append("READ - workstream resources")
        out.append("")
        for res in roadmap["resources"]:
            mark = " " if (repo_root / res["path"]).exists() else "!"
            out.append(f" {mark} {res['path']}")
            out.append(f"     {res['why']}")
        out.append("")

    already = {res["path"] for res in roadmap.get("resources", [])}
    task_only = [res for res in task.get("required_resources", []) if res["path"] not in already]
    if task_only:
        out.append("READ - required for this task, beyond the workstream resources above")
        out.append("")
        for res in task_only:
            mark = " " if (repo_root / res["path"]).exists() else "!"
            out.append(f" {mark} {res['path']}")
            out.append(f"     {res['why']}")
        out.append("")

    upstream = [
        t
        for t in roadmap["tasks"]
        if t["id"] in task.get("depends_on", []) and t.get("evidence")
    ]
    if upstream:
        out.append("UPSTREAM OUTPUTS already settled - build on these, do not redo them")
        out.append("")
        for other in upstream:
            out.append(f"  {other['id']} ({other['status']}):")
            for item in other["evidence"]:
                note = f" - {item['note']}" if item.get("note") else ""
                out.append(f"    {item['kind']}: {item['ref']}{note}")
        out.append("")

    out.append("DELIVERABLES")
    out.append("")
    for item in task.get("deliverables", []):
        out.append(f"  - {item}")
    out.append("")

    out.append("COMPLETION GATES - all of these, or the task is not COMPLETE")
    out.append("")
    for item in task.get("completion_gates", []):
        out.append(f"  - {item}")
    out.append("")

    decisions = task.get("open_decisions") or []
    if decisions:
        out.append("OPEN USER-OWNED DECISIONS - do not settle these yourself")
        out.append("")
        for item in decisions:
            out.append(f"  - {item}")
        out.append("")

    ws_open = [
        (t["id"], d)
        for t in roadmap["tasks"]
        if t["id"] != task["id"]
        for d in (t.get("open_decisions") or [])
    ]
    if ws_open:
        out.append("OPEN ELSEWHERE IN THE WORKSTREAM - context, not this session's work")
        out.append("")
        for tid, decision in ws_open:
            out.append(f"  - {tid}: {decision}")
        out.append("")

    out.append("RECORD RESULTS BACK INTO THE REPOSITORY")
    out.append("")
    out.append(f"  Source of record : {WORKSTREAMS_DIR}/{roadmap['slug']}/roadmap.json (edit this)")
    out.append("  At a durable stopping point, set this task's status and evidence, and if the")
    out.append("  work is partial, set IN_PROGRESS with a concise resume_note. Then:")
    out.append("")
    out.append("    python3 scripts/content_workstream.py validate --all")
    out.append("    python3 scripts/content_workstream.py render --all")
    out.append("")
    out.append("  COMPLETE requires evidence a later session can verify from the repository:")
    out.append("  committed artifact paths, accepted filenames, QC/preflight results, captures,")
    out.append("  exact SHAs, validator results, or recorded user acceptance. Saying it is")
    out.append("  finished is not evidence.")
    out.append("")
    out.append("BOUNDARIES")
    out.append("")
    out.append("  - The roadmap is coordination state. Canon stays with its owner; if this task")
    out.append("    needs a canonical change, change the owner, do not restate it here.")
    out.append("  - Balance, rewards, rarity, publishing, final art direction and final content")
    out.append("    acceptance are the user's. Propose; do not settle.")
    out.append("  - The user is the only live-game actor. No game write happens in this session.")
    return out, ok


