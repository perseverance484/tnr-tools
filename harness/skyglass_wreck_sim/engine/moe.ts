type Run = { seed: number; acts: ActResult[]; cleared: boolean; reachedAct: number };
const runEncounter = async (seed: number, cell: string, policy: Policy, kill: "sayo" | "silence", actsWanted: number[], trace = false): Promise<Run> => {
  const model = playerModel(cell);
  const cfgs = actCfgs(kill);
  const acts: ActResult[] = [];
  let start: any = undefined;
  let reached = 0;
  for (const cfg of cfgs) {
    if (!actsWanted.includes(cfg.act)) continue;
    reached = cfg.act;
    const r = await runAct(cfg, { seed, policy, model, start, trace, catalog: CAT });
    acts.push(r);
    if (r.outcome !== "won") break;
    start = { hp: r.endHp, cp: r.endCp, sp: r.endSp };
  }
  return { seed, acts, cleared: acts.length === actsWanted.length && acts.every((a) => a.outcome === "won"), reachedAct: reached };
};
const med = (xs: number[]) => { if (!xs.length) return null; const s = [...xs].sort((a, b) => a - b); const m = Math.floor(s.length / 2); return s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2; };
const summarise = (runs: Run[], acts: number[]) => {
  const out: any = { runs: runs.length, fullClears: runs.filter((r) => r.cleared).length };
  out.fullClearPct = Math.round((1000 * out.fullClears) / runs.length) / 10;
  out.perAct = {};
  for (const a of acts) {
    const rs = runs.map((r) => r.acts.find((x) => x.act === a)).filter(Boolean) as ActResult[];
    const won = rs.filter((x) => x.outcome === "won");
    const deaths: Record<string, number> = {};
    for (const x of rs) if (x.outcome === "lost") deaths[x.deathCause ?? "?"] = (deaths[x.deathCause ?? "?"] ?? 0) + 1;
    const sets: Record<string, any> = {};
    for (const x of rs) for (const [k, s] of Object.entries(x.sets)) { const t = (sets[k] ??= { mark: 0, land: 0, hit: 0, dmg: 0, unmarked: 0 }); t.mark += s.mark; t.land += s.land; t.hit += s.hit; t.dmg += s.dmg; t.unmarked += s.unmarked; }
    for (const t of Object.values<any>(sets)) { t.landsPerFight = Math.round((10 * t.land) / Math.max(1, rs.length)) / 10; t.dmgPerHit = t.hit ? Math.round(t.dmg / t.hit) : null; }
    const specials: Record<string, number> = {};
    for (const x of rs) for (const [k, v] of Object.entries(x.specials)) specials[k] = (specials[k] ?? 0) + v;
    const idle: Record<string, string> = {};
    const turns: Record<string, number> = {}, idl: Record<string, number> = {};
    for (const x of rs) { for (const [k, v] of Object.entries(x.bossTurns)) turns[k] = (turns[k] ?? 0) + v; for (const [k, v] of Object.entries(x.bossIdle)) idl[k] = (idl[k] ?? 0) + v; }
    for (const k of Object.keys(turns)) idle[k.replace("moe-ai-", "")] = `${idl[k] ?? 0}/${turns[k]}`;
    const killFirst: Record<string, number> = {};
    for (const x of rs) if (x.killFirst) killFirst[x.killFirst.replace("moe-ai-", "")] = (killFirst[x.killFirst.replace("moe-ai-", "")] ?? 0) + 1;
    out.perAct[a] = {
      entered: rs.length, won: won.length, clearPctOfEntered: rs.length ? Math.round((1000 * won.length) / rs.length) / 10 : null,
      roundsWonMedian: med(won.map((x) => x.rounds)), roundsAllMedian: med(rs.map((x) => x.rounds)), endHpWonMedianPct: med(won.map((x) => Math.round(100 * x.endHp))),
      bossHpLeftLostMedian: Object.fromEntries(Object.keys(rs[0]?.bossHpPct ?? {}).map((k) => [k.replace("moe-ai-", ""), med(rs.filter((x) => x.outcome !== "won").map((x) => x.bossHpPct[k]!))])),
      deaths, stalled: rs.filter((x) => x.outcome === "stalled").length, sets, unmarked: rs.reduce((s, x) => s + x.unmarkedTotal, 0), specials, idleTurns: idle, killFirst,
      maxHitMedian: med(rs.map((x) => x.maxHit.dmg)), healedMedian: med(rs.map((x) => Math.round(x.healed))), dodgesPerFight: Math.round((10 * rs.reduce((s, x) => s + x.dodges, 0)) / Math.max(1, rs.length)) / 10,
    };
  }
  return out;
};

const main = async () => {
  const sp = opt("write-spec");
  if (sp) { mkdirSync(dirname(resolve(sp)), { recursive: true }); writeFileSync(resolve(sp), `${JSON.stringify(spec(), null, 1)}\n`); console.log(`wrote ${sp}`); }
  const issues = validateAll(P);
  console.log(issues.length ? `VALIDATION ISSUES:\n  ${issues.join("\n  ")}` : "records valid");
  const kill = (opt("kill", "sayo") as "sayo" | "silence");
  const acts = opt("acts", "1,2,3")!.split(",").map(Number);
  const tr = opt("trace");
  if (tr) {
    const [cell, pol] = opt("cells", "elite:play")!.split(",")[0]!.split(":");
    const r = await runEncounter(Number(tr), cell!, pol as Policy, kill, acts, true);
    for (const a of r.acts) { console.log(`--- act ${a.act}: ${a.outcome} in ${a.rounds} rounds; end HP ${(100 * a.endHp).toFixed(0)}%; bosses ${JSON.stringify(a.bossHpPct)}; death ${a.deathCause}; unmarked ${a.unmarkedTotal}`); for (const l of a.trace!) console.log("  " + l); console.log(JSON.stringify({ sets: a.sets, specials: a.specials, dmgBySource: a.dmgBySource, maxHit: a.maxHit })); }
    return;
  }
  const cells = opt("cells", "elite:play,elite:ignore,elite_imm:play,elite_imm:ignore,average:play")!.split(",");
  const runs = Number(opt("runs", "30"));
  const seed0 = Number(opt("seed", "1"));
  const result: any = { generatedBy: "engine/moe.ts", visualFilter: !args.includes("--no-visual-filter"), engine: "theninjarpg 3314d122", dmgConfig: dmg.name, params: P, kill, acts, runs, seed0, cells: {} };
  for (const c of cells) {
    const [cell, pol] = c.split(":");
    const rs: Run[] = [];
    for (let s = seed0; s < seed0 + runs; s++) rs.push(await runEncounter(s, cell!, pol as Policy, kill, acts));
    const sum = summarise(rs, acts);
    result.cells[c] = { summary: sum, runs: rs.map((r) => ({ seed: r.seed, cleared: r.cleared, acts: r.acts.map(({ trace: _t, ...x }) => x) })) };
    console.log(`\n== ${c}: full clear ${sum.fullClears}/${runs}; ` + acts.map((a) => `act ${a}: ${sum.perAct[a]?.won}/${sum.perAct[a]?.entered} rounds ${sum.perAct[a]?.roundsAllMedian} deaths ${JSON.stringify(sum.perAct[a]?.deaths)} unmarked ${sum.perAct[a]?.unmarked}`).join(" | "));
  }
  const out = opt("out");
  if (out) { mkdirSync(dirname(resolve(out)), { recursive: true }); writeFileSync(resolve(out), `${JSON.stringify(result, null, 1)}\n`); console.log(`wrote ${out}`); }
};
await main();
