#!/usr/bin/env python3
"""Resolve the Crowned Captain fight's inputs from committed evidence into data/crowned_captain_inputs.json.

    python3 harness/skyglass_wreck_sim/tools/build_crowned_captain_inputs.py [--check]

- The boss (D5.BOSS, live id 7QofodAiUwIoM-voiA2p6) and the Recall echo (D5.REG1 Sanctum Vanguard,
  pshn-LkaC5vIgI6EOv68I): push/272 manifest data, with the server-computed combat stats from the push/272
  results bundle (tnr_results_1792984876132.json, verdict "drift": the server recomputes stats from
  statsMultiplier).
- Jutsu and item records: the newest captured full record per id across harvests/ and answers/
  (by updatedAt); push/271 manifest data for The Last Directive / Extermination Order / Countermand only if
  no capture exists.
- The old Crowned Captain kit rows (Final Command, Keelbind, Ruin Refrain): data/baseline.json (push/249
  roster capture).
"""
import glob, json, os, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "data/crowned_captain_inputs.json")
M272 = "archive/spent-manifests/push-2026-10-25/272_crownhold_ais.json"
M271 = "archive/spent-manifests/push-2026-10-25/271_crownhold_exclusives.json"
RES272 = "harvests/inbox/tnr_results_1792984876132.json"
IDS = "state/crownhold/ids.json"
BOSS_SRC, ECHO_SRC = "crownhold_d5.boss", "crownhold_d5.reg1"
OLD_KIT = {"Final Command": "X2P22h8ApDmTZHjWpNO87", "Keelbind": "PdD44PGaNv4MN5fOALhAF", "Ruin Refrain": "EQ93LX8wvuIAd5u75q_i1"}
# Donor shapes for the new records (captured): Drowning Mire (GROUND AOE, visual row), Hell Hound (summon row).
DONORS = {"ground": "VmZzkyfPswbJLXvuB-mcV", "summon": "kP_KMs7H9wQJwRHeaTGCZ"}


def load(p):
    return json.load(open(os.path.join(REPO, p)))


def walk(x, f, want, kind, best):
    if isinstance(x, list):
        for v in x:
            walk(v, f, want, kind, best)
    elif isinstance(x, dict):
        rid = x.get("id")
        if rid in want and "effects" in x and (("jutsuType" in x) if kind == "jutsu" else ("itemType" in x)):
            cur = best.get(rid)
            if cur is None or str(x.get("updatedAt") or "") > str(cur[0].get("updatedAt") or ""):
                best[rid] = (x, f)
        for v in x.values():
            walk(v, f, want, kind, best)


def captured(ids, kind):
    best = {}
    files = sorted(glob.glob(os.path.join(REPO, "harvests/**/*.json"), recursive=True)
                   + glob.glob(os.path.join(REPO, "answers/**/*.json"), recursive=True))
    for path in files:
        raw = open(path, encoding="utf-8", errors="replace").read()
        if not any(i in raw for i in ids):
            continue
        try:
            doc = json.loads(raw)
        except json.JSONDecodeError:
            continue
        walk(doc, os.path.relpath(path, REPO), set(ids), kind, best)
    return best


def ai_row(m272, res, src):
    item = next(i for i in m272["items"] if i["srcId"] == src)
    entry = next(e for e in res["entries"] if e["srcId"] == src)
    live = {d["key"]: d["live"] for d in entry.get("diffs", [])}
    return {"id": entry["id"], "srcId": src, "data": item["data"], "liveStats": live,
            "source": f"{M272} data + {RES272} readback (stats)"}


def build():
    m272, m271, res = load(M272), load(M271), load(RES272)
    boss, echo = ai_row(m272, res, BOSS_SRC), ai_row(m272, res, ECHO_SRC)
    ids = json.load(open(os.path.join(REPO, IDS)))
    jutsu_ids = sorted(set(boss["data"]["jutsus"]) | set(echo["data"]["jutsus"]) | set(DONORS.values()))
    item_ids = sorted({i for it in boss["data"]["items"] for i in it["ids"]})
    jutsu = {k: {"record": v[0], "source": v[1]} for k, v in captured(jutsu_ids, "jutsu").items()}
    items = {k: {"record": v[0], "source": v[1]} for k, v in captured(item_ids, "item").items()}
    for it in m271["items"]:
        rid = ids.get(f"@{it['entity']}:{it['srcId']}")
        bucket = jutsu if it["entity"] == "jutsu" else items
        if rid and rid not in bucket:
            bucket[rid] = {"record": {**it["data"], "id": rid}, "source": f"{M271} data (no capture)"}
    baseline = load("harness/skyglass_wreck_sim/data/baseline.json")
    old = {}
    for e in baseline["enemies"].values():
        for uj in e["user"]["jutsus"]:
            if uj["jutsu"]["id"] in OLD_KIT.values():
                old[uj["jutsu"]["id"]] = {"record": uj["jutsu"], "source": "data/baseline.json (push/249 capture, old Crowned Captain kit)"}
    missing = [i for i in jutsu_ids if i not in jutsu] + [i for i in item_ids if i not in items] + [i for i in OLD_KIT.values() if i not in old]
    if missing:
        raise SystemExit(f"missing records: {missing}")
    return {"_note": "generated by tools/build_crowned_captain_inputs.py; do not hand-edit",
            "boss": boss, "echo": echo, "jutsu": jutsu, "items": items, "oldKit": old, "donors": DONORS}


def main():
    doc = build()
    text = json.dumps(doc, indent=1, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            raise SystemExit("data/crowned_captain_inputs.json is stale; rerun the builder")
        print("crowned_captain_inputs.json current")
        return
    open(OUT, "w").write(text)
    print(f"wrote {OUT}: {len(doc['jutsu'])} jutsu, {len(doc['items'])} items")


if __name__ == "__main__":
    main()
