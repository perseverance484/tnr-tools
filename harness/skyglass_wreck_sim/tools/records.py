def tier_name(prefix, crew):
    return f"{prefix} {re.sub(r'^The ', '', CREW_NAME[crew])}"


def src_id(key):
    return "sg344_" + key.replace(":", "-")


IGNORED_ROW = {"userId", "username", "aiProfileId"}


def signature(row, profile):
    """A record's identity for sharing: its row (less ids and name) and its rules."""
    r = {k: v for k, v in row.items() if k not in IGNORED_ROW}
    p = {"includeDefaultRules": profile.get("includeDefaultRules"), "rules": profile["rules"]}
    return json.dumps([r, p], sort_keys=True)


def tuning_of(row):
    eff = row.get("effects") or []
    rows = sum(1 for e in eff if e.get("type") == "increasedamagegiven")
    taken = [e["power"] for e in eff if e.get("type") == "increasedamagetaken"]
    down = [e["power"] for e in eff if e.get("type") == "decreasedamagegiven"]
    dr = [e["power"] for e in eff if e.get("type") == "decreasedamagetaken"]
    t = {"level": row.get("level"), "statsMultiplier": row.get("statsMultiplier"),
         "poolsMultiplier": row.get("poolsMultiplier"), "maxHealth": row.get("maxHealth"), "damageRows": rows}
    if taken:
        t["damageTaken"] = taken
    if down:
        t["damageGivenDown"] = down
    if dr:
        t["damageReduction"] = dr
    return t


def rule_parts(r):
    a = r.get("action") or r.get("do") or {}
    c = r.get("conditions") if "conditions" in r else (r.get("when") or [])
    return a, c


def cap_gate_problems(rules):
    """AI_PROFILE_MAX_RULES and Forge's kitProblems gate rule (range+1 on a pool jutsu; forge/src/runner/pool.mjs).
    Pool = 32b_DATA_pool.json, keyed by live id; library set pieces are not pool jutsu (engine/gates.ts, Forge)."""
    out = []
    if len(rules) > MAX_RULES:
        out.append(f"{len(rules)} rules > {MAX_RULES}")
    for i, r in enumerate(rules):
        a, conds = rule_parts(r)
        rec = POOL_BY_ID.get(a.get("jutsuId"))
        if not rec or rec.get("gate") is None:
            continue
        for c in conds or []:
            if c.get("type") == "distance_lower_than" and c.get("value") != rec["gate"]:
                out.append(f"rules[{i}] {rec['name']}: gate {c.get('value')} != range+1 {rec['gate']}")
    return out


class Table:
    def __init__(self):
        self.recs = {}      # key -> record
        self.by_sig = {}    # (tier, signature) -> key

    def add(self, key, **rec):
        if key in self.recs:
            raise SystemExit(f"duplicate key {key}")
        rec = {"key": key, "srcId": None if rec.get("kind") == "live" else src_id(key), **rec, "usedBy": []}
        self.recs[key] = rec
        return rec

    def use(self, key, fight):
        u = self.recs[key]["usedBy"]
        if fight not in u:
            u.append(fight)


def captured_ai_usernames():
    """Every AI username in the repository's captures (harvests/: rows with isAi, aiProfileId or poolsMultiplier)."""
    out = set()

    def walk(o):
        if isinstance(o, dict):
            u = o.get("username")
            if isinstance(u, str) and (o.get("isAi") is True or "aiProfileId" in o or "poolsMultiplier" in o):
                out.add(u)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    for r, _, fs in os.walk(os.path.join(REPO, "harvests")):
        for f in fs:
            if f.endswith(".json"):
                try:
                    walk(json.load(open(os.path.join(r, f))))
                except (ValueError, OSError):
                    pass
    return out


