    captured = set(json.load(open(names_file))) if names_file else captured_ai_usernames()
    if captured:
        clash = sorted(n for n in names if n in captured)
        if clash:
            problems.append(f"new usernames already taken by a captured AI: {clash}")
    return T, problems


