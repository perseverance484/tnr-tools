#!/usr/bin/env python3
"""Generate push/178-181: read-only census of player jutsu for the description pass.

Target set: every jutsu whose last known type is a player type (NORMAL, SPECIAL,
FORBIDDEN, LOYALTY, CLAN, EVENT), from the 2026-10-06 census bundles (push/68-74,
live type wins) and the seed index harvests/seed/40_INDEX_jutsu.json, plus visible
jutsu named in docs/reviews/QA_LIVE_2026-10-20.findings.json that neither source
knows. Bloodline and AI jutsu are left out. Hidden state is not trusted: every
record is point-read and the live hidden/jutsuType fields decide.

Forge list reads keep only a row count, so jutsu ids made after the seed and not
flagged by the QA pass are not covered; part 1's jutsu.getAllNames row count shows
how far the universe has drifted. Run from the repo root.
"""
import glob, json, os

PLAYER_TYPES = {"NORMAL", "SPECIAL", "FORBIDDEN", "LOYALTY", "CLAN", "EVENT"}
CENSUS_BUNDLES = ["1791246947793", "1791247158542", "1791247363737", "1791247737840",
                  "1791247939010", "1791248138851", "1791248170855"]
PARTS = 4

def main():
    live = {}
    for ts in CENSUS_BUNDLES:
        b = json.load(open(f"harvests/inbox/tnr_results_{ts}.json"))
        for c in b.get("captures") or []:
            d = c.get("data")
            if isinstance(d, dict) and d.get("id"):
                live[d["id"]] = d
    seed = json.load(open("harvests/seed/40_INDEX_jutsu.json"))
    cols = seed["cols"]
    rows = {r[cols.index("id")]: r for r in seed["rows"]}
    ids = []
    for jid, r in rows.items():
        t = live[jid]["jutsuType"] if jid in live else r[cols.index("type")]
        if t in PLAYER_TYPES:
            ids.append(jid)
    findings = json.load(open("docs/reviews/QA_LIVE_2026-10-20.findings.json"))["findings"]
    for x in findings:
        if x["entity"] != "jutsu" or x["hidden"] is not False or x["id"] in rows or x["id"] in ids:
            continue
        if (x.get("evidence") or {}).get("jutsuType") in ("AI", "BLOODLINE"):
            continue
        ids.append(x["id"])
    ids = sorted(set(ids))
    size = -(-len(ids) // PARTS)
    for p in range(PARTS):
        chunk = ids[p * size:(p + 1) * size]
        before = ([{"proc": "jutsu.getAllNames", "input": {}}] if p == 0 else [])
        before += [{"proc": "jutsu.get", "input": {"id": j}, "persist": "full"} for j in chunk]
        m = {
            "_note": (f"READ-ONLY player jutsu census, part {p + 1} of {PARTS} ({len(chunk)} of {len(ids)} jutsu). "
                      "Fresh live records for the jutsu description pass (QA tickets from 12). Zero items, zero writes. "
                      "Every read is jutsu.get with persist:'full'; a missing record answers NOT_FOUND and is simply gone. "
                      + ("jutsu.getAllNames is a live row-count check only. " if p == 0 else "")
                      + "Run 178, 179, 180, 181 one after another. Generated by push/178_player_jutsu_census.gen.py; do not hand-edit."),
            "capture": {"before": before},
        }
        path = f"push/{178 + p}_player_jutsu_census_{p + 1}.json"
        with open(path, "w") as f:
            json.dump(m, f, indent=1, ensure_ascii=False)
            f.write("\n")
        print(path, len(chunk))

if __name__ == "__main__":
    main()
