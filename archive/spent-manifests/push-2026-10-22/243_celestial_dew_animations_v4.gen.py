#!/usr/bin/env python3
"""Build push/243: put the v5 Celestial Dew strips on the three existing assets (direct edits).

    python3 push/243_celestial_dew_animations_v4.gen.py <push/238 results bundle>

v4 (director, 2026-10-24: "The animations circle seems to clip at the top when the ward forms"): the ward ring is tucked
over the portrait's rim so it stays inside the frame (PROJECT.md section 10). v5 (section 11): the appear flashes the
ward up as the ripples touch the rim and hands over to the loop's slower breath (5.76 s). Same
asset ids, so push/240 is unchanged. New filenames (law 32); hidden stays false (law 16c). The image pack is pinned at
HEAD: commit the strips first.
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = 'push/243_celestial_dew_animations_v4.json'
E = 'art/jutsu_icons/celestial_dew/animation/exports/'
CREATE = 'archive/spent-manifests/push-2026-10-22/238_celestial_dew_animations.json'
STRIPS = {'cd_anim_appear': ('anim_celestial_dew_appear_v5.webp', 74, 46),
          'cd_anim_loop': ('anim_celestial_dew_loop_v5.webp', 64, 90),
          'cd_anim_break': ('anim_celestial_dew_break_v5.webp', 30, 46)}
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
idmap = json.load(open(sys.argv[1])).get('idmap', {})
from PIL import Image
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
pack, sizes, items = {}, {}, []
for it in json.load(open(CREATE))['items']:
    aid = idmap.get(it['srcId'])
    assert aid, f"{it['srcId']} not in the bundle idmap"
    fn, frames, speed = STRIPS[it['srcId']]
    path = E + fn
    w, h = Image.open(path).size
    assert w == 112 and h == 112 * frames, (fn, w, h)
    b = open(path, 'rb').read()
    assert len(b) < 460800 and subprocess.check_output(['git', 'show', f'{ref}:{path}']) == b, 'commit the strips first'
    pack[fn] = {"path": path, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
    sizes[fn] = len(b)
    data = dict(it['data'], image='@img:' + fn, frames=frames, speed=speed, hidden=False)
    items.append({"entity": "asset", "slot": "edit", "targetId": aid, "name": it['name'], "data": data})
m = {
    "_note": "Celestial Dew v5 strips on the three existing assets: the ward ring stays inside the frame (it clipped at the top), and the appear flashes the ward up and hands over to the loop's slower breath. Same ids, so push/240 is unchanged; new filenames (law 32); hidden false (law 16c). Generated by push/243_celestial_dew_animations_v4.gen.py; do not hand-edit.",
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": pack},
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: ' + ', '.join(i['targetId'] for i in items) + f', pack @ {ref[:7]}')
