#!/usr/bin/env python3
"""Build push/249: suggest the new Earth Scroll and Heaven Scroll icons (suggest mode, one suggestion per item).

    python3 push/249_chunin_exam_scrolls.gen.py

Director, 2026-10-25: "Here's Earth Scroll, add it's ticket to the manifest" / "And heaven scroll". Design:
docs/design/chunin_exam_scrolls/PROJECT.md (colour + seal). Image only; the item records are otherwise untouched.
The image pack is pinned at HEAD: commit the exports first.
"""
import hashlib, json, os, subprocess
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = 'push/249_chunin_exam_scrolls.json'
E = 'art/item_icons/chunin_exam_scrolls/exports/'
ITEMS = [
    ('Earth Scroll', 'npOljgp_QZUUd6g9wPBk0', 'icon_earth_scroll_v1.webp',
     "The old icon copied the anime's exam scroll, painted character and all, inside a heavy yellow outline glow. New icon "
     "keeps the green and gold scroll and seals it with a red wax seal pressed with mountains, so it reads as Earth with no writing."),
    ('Heaven Scroll', '5W8HJUSPt15Lu14EFvHqi', 'icon_heaven_scroll_v1.webp',
     "The old icon copied the anime's exam scroll, painted character and all, inside a heavy yellow outline glow. New icon "
     "keeps the navy and gold scroll and seals it with a red wax seal pressed with a cloud, matching the new Earth Scroll."),
]
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
from PIL import Image
pack, sizes, items = {}, {}, []
for name, iid, fn, why in ITEMS:
    path = E + fn
    assert Image.open(path).size == (256, 256), fn
    b = open(path, 'rb').read()
    assert len(b) < 460800 and subprocess.check_output(['git', 'show', f'{ref}:{path}']) == b, 'commit the exports first'
    pack[fn] = {"path": path, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
    sizes[fn] = len(b)
    items.append({"entity": "item", "slot": "edit", "name": name, "targetId": iid, "data": {"image": "@img:" + fn},
                  "suggestion": {"category": "VISUAL", "title": "New Chunin Exam scroll icon", "rationale": why}})
m = {
    "_note": "Chunin Exam scrolls (The Chunin Exams quest props): new Earth Scroll and Heaven Scroll icons, colour + seal "
             "direction (docs/design/chunin_exam_scrolls/PROJECT.md). Suggest mode: one suggestion per item; image only. "
             "The quest's deliver objective keeps its own copy of the old Earth Scroll image (a quest edit, not possible in "
             "suggest mode). Generated by push/249_chunin_exam_scrolls.gen.py; do not hand-edit.",
    "mode": "suggest",
    "suggestion": {"category": "VISUAL", "title": "New Chunin Exam scroll icon",
                   "rationale": "New icon for a Chunin Exams quest scroll."},
    "imgSizes": sizes,
    "imagePack": {"ref": ref, "files": pack},
    "items": items,
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: {len(items)} items, pack @ {ref[:7]}')
