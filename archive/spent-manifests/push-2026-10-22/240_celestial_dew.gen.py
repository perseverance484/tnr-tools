#!/usr/bin/env python3
"""Build push/240: Celestial Dew's animations (suggest mode, one suggestion).

    python3 push/240_celestial_dew.gen.py <push/238 results bundle> [push/241 capture bundle]

With the push/241 bundle, the live record comes from that fresh capture (jutsu.get) instead of the 2026-10-23 public
read.

Sets the SHIELD effect's appearAnimation (the moon, the drop, the splash and the ripples), staticAnimation (the ward
breathing; its first glow peak when the ripples reach the rim) and disappearAnimation (the ward shattering) to the push/238
assets. The heal effect is untouched: it keeps its own appear animation I9aYhT5wMB (director, 2026-10-24: "that appears
on the heal tag, not on the shield tag and would still play normally. Ours is for the shield tag"). It also brings
back our reworked icon (the "reverted" one, not live: the live record went back to the original; director, 2026-10-24:
"The reverted version isnt live, thats why its called reverted"): art/jutsu_icons/celestial_dew/exports/
icon_jutsu_celestial_dew_v1.webp (256 px lossless, artpreflight JUTSU_ICON clean). Text unchanged. The live effects array is re-sent (arrays are replaced, not merged); injectableInBattle re-sent at its live
value (law 20). No AI holds Celestial Dew in recent captures (laws 18, 60). Run push/239 (the unhide) first.
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
JID = '2vNeMhph6A9Ld--WXa35O'
PUBLIC = 'harvests/inbox/tnr_results_1792732003454.json'
OUT = 'push/240_celestial_dew.json'
ICON = 'art/jutsu_icons/celestial_dew/exports/icon_jutsu_celestial_dew_v1.webp'
if len(sys.argv) not in (2, 3):
    raise SystemExit(__doc__)
idmap = json.load(open(sys.argv[1])).get('idmap', {})
appear, loop, brk = (idmap.get(k) for k in ('cd_anim_appear', 'cd_anim_loop', 'cd_anim_break'))
assert appear and loop and brk, 'the Celestial Dew assets are not in the bundle idmap: run push/238 first'

live = None
if len(sys.argv) == 3:
    for c in json.load(open(sys.argv[2]))['captures']:
        d = c.get('data')
        for cand in (d, (d or {}).get('data') if isinstance(d, dict) else None):
            if isinstance(cand, dict) and cand.get('id') == JID:
                live = cand
    assert live, 'Celestial Dew not found in the capture bundle'
else:
    for c in json.load(open(PUBLIC))['captures'][1:]:
        for j in c['data']['data']:
            if j['id'] == JID:
                live = j
assert live and live['name'] == 'Celestial Dew', 'live record not found'
sh = [e for e in live['effects'] if e['type'] == 'shield']
hl = [e for e in live['effects'] if e['type'] == 'heal']
assert len(sh) == 1 and not (sh[0].get('appearAnimation') or sh[0].get('staticAnimation') or sh[0].get('disappearAnimation')), \
    'shield effect not as expected; re-read the record'
assert len(hl) == 1 and hl[0].get('appearAnimation') == 'I9aYhT5wMB', 'heal effect not as expected; re-read the record'
ref = subprocess.check_output(['git', 'rev-parse', 'HEAD']).decode().strip()
b = open(ICON, 'rb').read()
assert subprocess.check_output(['git', 'show', f'{ref}:{ICON}']) == b, 'commit the icon first'
fn = os.path.basename(ICON)
effects = [dict(e, appearAnimation=appear, staticAnimation=loop, disappearAnimation=brk) if e['type'] == 'shield'
           else dict(e) for e in live['effects']]
m = {
    "_note": "Celestial Dew: one suggest-mode suggestion bringing back our reworked icon and setting the shield effect's appear (moon, drop, splash, ripples), static (the ward breathing) and disappear (the ward shattering) animations to the push/238 assets. Heal effect and text unchanged. Effects array re-sent; injectableInBattle re-sent at its live value (law 20). Generated by push/240_celestial_dew.gen.py; do not hand-edit. Operator runs it from Forge; never skipPreflight.",
    "mode": "suggest",
    "suggestion": {"category": "CONSISTENCY", "title": "New icon and shield animations",
                   "rationale": "Our reworked icon and new animations that play what the jutsu describes: the moon, the drop and the ward."},
    "imgSizes": {fn: len(b)},
    "imagePack": {"ref": ref, "files": {fn: {"path": ICON, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}}},
    "items": [{
        "entity": "jutsu", "slot": "edit", "name": "Celestial Dew", "targetId": JID,
        "data": {"image": "@img:" + fn, "effects": effects, "injectableInBattle": live['injectableInBattle']},
        "suggestion": {"category": "CONSISTENCY", "title": "New icon and shield animations",
                       "rationale": "Brings back our reworked icon (staff scored it 10/10) and adds animations that play what the jutsu describes: a crescent moon drops a bead of starlight into the caster's portrait, the ripples charge its edge into a glowing ward that breathes while the shield lasts, and the ward shatters when the shield ends. Nothing showed the shield before. The heal keeps its heart effect; the text is unchanged."},
    }],
}
json.dump(m, open(OUT, 'w'), indent=1, ensure_ascii=False); open(OUT, 'a').write('\n')
print(f'wrote {OUT}: 1 suggestion (icon {fn}; shield appear {appear}, static {loop}, disappear {brk}), pack @ {ref[:7]}')
