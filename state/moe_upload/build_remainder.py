#!/usr/bin/env python3
"""Build push/527 (the rest of push/506; it ran as push/509 before the 2026-11-08 renumber) for the game-connection runner, from:
  - push/506_master_2026-11-06.json
  - the 2026-11-06 browser run's idmap (harvests/inbox/tnr_results_1794006062657.json): 351 asset creates done,
    plus the image URLs of the files it uploaded
  - state/moe_upload/uploaded.json: the 622 remaining sheets (50 px) and the An Absence avatar on the
    director's own UploadThing app (director, 2026-11-07)
Drops the 351 done creates, turns their @scene refs into literal ids, turns every @img ref into its URL and
drops the imagePack, so mcp_run can run it. Everything else is 506 unchanged.
    python3 state/moe_upload/build_remainder.py
"""
import json, re, sys
M = json.load(open("push/506_master_2026-11-06.json"))
ID = json.load(open("harvests/inbox/tnr_results_1794006062657.json"))["idmap"]
UP = json.load(open("state/moe_upload/uploaded.json"))["files"]
byfile = {v["file"]: v["url"] for v in UP.values()}
done = {i["srcId"] for i in M["items"] if i["entity"] == "asset" and i["slot"] == "create" and i["srcId"] in ID}
assert len(done) == 351, len(done)

def img_url(name):
    if name in byfile: return byfile[name]
    if name in ID and ID[name].startswith("https://"): return ID[name]
    sys.exit(f"no URL for @img:{name}")

def fix(v):
    if isinstance(v, str):
        m = re.fullmatch(r"@img:(.+)", v)
        if m: return img_url(m.group(1))
        m = re.fullmatch(r"@scene:(.+)", v)
        if m and m.group(1) in done: return ID[m.group(1)]
        return v
    if isinstance(v, list): return [fix(x) for x in v]
    if isinstance(v, dict): return {k: fix(x) for k, x in v.items()}
    return v

items = []
for i in M["items"]:
    if i["entity"] == "asset" and i["slot"] == "create" and i["srcId"] in done: continue
    if i["entity"] == "asset" and i["slot"] == "create" and i["srcId"] in UP:
        i = dict(i); i["data"] = dict(i["data"]); i["data"]["image"] = UP[i["srcId"]]["url"]
    items.append(fix(i))
left = [s for s in re.findall(r'"@img:[^"]+"', json.dumps(items))]
assert not left, left[:3]
out = {"_note": "push/509: the rest of push/506 (MoE final tuning 501 + asset folders 500) for the game-connection runner. "
       "Generated by state/moe_upload/build_remainder.py; do not hand-edit. 351 asset creates already ran in the "
       "browser on 2026-11-06 (tnr_results_1794006062657) and are dropped, their refs literal. The 622 remaining "
       "sheets (50 px, exact 3x reductions) and the An Absence avatar are on the director's own UploadThing app "
       "(director, 2026-11-07: the game connection has no upload). Assets are created HIDDEN; push/502 unhides.",
       "items": items, "dedupNames": M.get("dedupNames", True)}
if "imgSizes" in M: out["imgSizes"] = M["imgSizes"]
# The _note text above keeps "push/509" on purpose: the committed manifest and its results bundle
# (manifestHash) carry that text, so a rebuild must match them byte for byte.
json.dump(out, open("push/527_mother_of_echoes_remainder.json", "w"), indent=1)
print(len(items), "items")
